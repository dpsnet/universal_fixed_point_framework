eigvals_H1 = eigvals_H1[idx]
eigvecs_H1 = eigvecs_H1[:, idx]

print("\n=== Step 3: Cartan Eigenvalues ===")
print(f"H1 eigenvalues (sorted): {np.round(eigvals_H1, 4)}")
print(f"H2 eigenvalues:          {np.round(eigvals_H2[idx], 4)}")

