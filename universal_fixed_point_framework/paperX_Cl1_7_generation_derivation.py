"""
Cl(1,7) 代数 → 三代收缩因子 {c₁,c₂,c₃} 第一原理推导
================================================
从 Cl(1,7) γ 矩阵构造 SU(4) → SU(3)×U(1) 生成元，
计算代标记算子的本征值，导出 IFS 收缩因子的代数比。
"""
import numpy as np
from scipy import linalg
import itertools

I2 = np.eye(2, dtype=complex)

# Pauli matrices
sx = np.array([[0,1],[1,0]], dtype=complex)
sy = np.array([[0,-1j],[1j,0]], dtype=complex)
sz = np.array([[1,0],[0,-1]], dtype=complex)

def gamma_matrix(mu):
    """Cl(1,7) gamma matrices in 8x8 complex representation.
    Signature: (-,+,+,+,+,+,+,+) — gamma_0 is timelike."""
    if mu == 0:
        return np.kron(np.kron(sx, sy), I2)
    elif mu == 1:
        return np.kron(np.kron(sx, sx), sx)
    elif mu == 2:
        return np.kron(np.kron(sx, sx), sy)
    elif mu == 3:
        return np.kron(np.kron(sx, sx), sz)
    elif mu == 4:
        return np.kron(np.kron(sx, sz), I2)
    elif mu == 5:
        return np.kron(np.kron(sy, sy), I2)
    elif mu == 6:
        return np.kron(np.kron(sy, sz), I2)
    elif mu == 7:
        return np.kron(np.kron(sz, I2), I2)
    else:
        raise ValueError(f"mu={mu} out of range 0..7")

def gamma_5():
    """Chirality operator gamma_5 for 4D subspace.
    gamma_5 = i * gamma_0 * gamma_1 * gamma_2 * gamma_3"""
    g = [gamma_matrix(i) for i in range(8)]
    return 1j * g[0] @ g[1] @ g[2] @ g[3]

# ============================================================
# Step 1: Construct generators of SU(4) ⊂ Spin(1,7)
# ============================================================
# SU(4) generators = gamma_{ij} = (i/2)[γ_i, γ_j] for i,j in {4,5,6,7}
# (these are the "internal" gamma matrices after factoring out
#  4D spacetime gamma_0..gamma_3)

g = [gamma_matrix(i) for i in range(8)]

# SU(4) generators are commutators of internal gammas
su4_generators = []
for i, j in itertools.combinations(range(4, 8), 2):
    G = 0.5j * (g[i] @ g[j] - g[j] @ g[i])
    su4_generators.append(G)

print("=== Step 1: SU(4) Generators ===")
print(f"Number of SU(4) generators: {len(su4_generators)} (expected 6)")

# ============================================================
# Step 2: Decompose SU(4) → SU(3) × U(1)
# ============================================================
# Under SU(4), the 4-dimensional fundamental representation decomposes
# as: 4_S = 3 ⊕ 1 under SU(3)
# The SU(3) subalgebra is generated by Gell-Mann-like combinations
# of the SU(4) generators.

# In the spinor representation, SU(3) generators act on the 3-generation
# subspace. We need to find the Cartan subalgebra of SU(3).

# Method: Diagonalize two commuting SU(4) generators to find
# the Cartan subalgebra of the SU(3) subgroup.
# Choose generators that commute:
# λ₃ = G_{45} (generalized Gell-Mann λ₃)
# λ₈ = (1/√3)(G_{46} + G_{57}) (generalized Gell-Mann λ₈)

# The SU(3) Cartan generators in the gamma matrix basis:
def comm(A, B):
    return A @ B - B @ A

# SU(4) generators as gamma_{ij} = (i/2)[γ_i, γ_j]
def su4_gen(i, j):
    return 0.5j * (g[i] @ g[j] - g[j] @ g[i])

# We need spinor-space realization of Gell-Mann matrices
# SU(3) Cartan: λ₃ = γ_{45} = (i/2)[γ₄, γ₅], λ₈ = (1/√3)(γ_{46} + γ_{57})
G45 = su4_gen(4, 5)
G46 = su4_gen(4, 6)
G57 = su4_gen(5, 7)

H1_su3 = G45.copy()  # Cartan 1
H2_su3 = (1.0/np.sqrt(3)) * (G46 + G57)  # Cartan 2

print("\n=== Step 2: SU(3) Cartan Generators ===")
print(f"H1 (lambda_3) anti-Hermitian check: ||H1 + H1^dagger|| = {np.linalg.norm(H1_su3 + H1_su3.T.conj()):.2e}")
print(f"H2 (lambda_8) anti-Hermitian check: ||H2 + H2^dagger|| = {np.linalg.norm(H2_su3 + H2_su3.T.conj()):.2e}")

# Make them Hermitian for eigendecomposition
