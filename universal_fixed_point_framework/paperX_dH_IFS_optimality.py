#!/usr/bin/env python3
"""
paperX_dH_IFS_optimality.py — 3-map IFS 的信息论最优性验证 (路径 C)

验证 3-map IFS 是满足"谱自洽性 + 最少参数"的最优模型。

核心论证:
  n-map IFS 的自由度 = n - 2  (c₁,c₂固定, c₃..cₙ自由)
  约束: Moran 方程 Σ c_i^d = 1

  n=2: 0 自由度, 过约束 (c₁^d + c₂^d ≠ 1, 差 ~0.999)
  n=3: 1 自由度, 恰好 (c₃ 被唯一确定)
  n=4: 2 自由度, 欠约束 (多个解, 无预测力)

  3 = 最小自洽复杂度, 类比 e ≈ 2.718 是基数经济最优
"""
import numpy as np

d_H = 2.7095
ln15 = np.log(15)

# =============================================================
# §1 2-map IFS 的过约束
# =============================================================
print("=" * 72)
print("§1 n=2: 2-map IFS 过约束")
print("=" * 72)

S4 = np.exp(-d_H)
S3 = np.exp(-3)
c1, c2 = S3*S4, S4

moran_2 = c1**d_H + c2**d_H
print(f"  c₁ = {c1:.8f}  (S₃·S₄, 固定)")
print(f"  c₂ = {c2:.8f}  (S₄, 固定)")
print(f"  Moran: c₁^d + c₂^d = {moran_2:.6f}")
print(f"  需要 = 1, 差值 = {moran_2 - 1:.2e}")
print(f"  → 2-map IFS 无解 ❌ (c₁^d + c₂^d ≪ 1)")

# 能否通过调 d 解决?
print(f"\n  扫描 d 寻找 2-map 可能的解:")
for d_test in np.linspace(2.0, 4.0, 21):
    S4_d = np.exp(-d_test)
    c1_d, c2_d = np.exp(-3)*S4_d, S4_d
    val = c1_d**d_test + c2_d**d_test
    print(f"    d={d_test:.2f}: c₁^d+c₂^d = {val:.4f}" +
          f" {'✅' if abs(val-1)<0.01 else ''}")

# =============================================================
# §2 3-map IFS: 恰好 1 个自由度
# =============================================================
print("\n" + "=" * 72)
print("§2 n=3: 3-map IFS 恰好 1 个自由度")
print("=" * 72)

# c₃ 由 Moran 方程唯一确定
c3 = (1 - c1**d_H - c2**d_H)**(1/d_H)
eps3 = 1 - c3

# 验证: δ = ln15 · √5 · ε₃
delta_obs = d_H - ln15
epsbar = delta_obs / ln15
ratio_eps = epsbar / eps3
sqrt5 = np.sqrt(5)

print(f"  c₁ = {c1:.8f} (固定, 来自 S₃·S₄)")
print(f"  c₂ = {c2:.8f} (固定, 来自 S₄)")
print(f"  c₃ = {c3:.8f} (Moran 方程唯一确定)")
print(f"  ε₃ = 1-c₃ = {eps3:.6e}")
print(f"  自由度 = 1 (c₃)")
print(f"  验证 Moran: {c1**d_H + c2**d_H + c3**d_H:.15f} = 1 ✅")
print(f"  ε̄/ε₃ = {ratio_eps:.6f} ≈ √5 = {sqrt5:.6f} (RMS 定理)")

# =============================================================
# §3 4-map IFS: 过多自由度
# =============================================================
print("\n" + "=" * 72)
print("§3 n=4: 4-map IFS 欠约束")
print("=" * 72)

# 对任意 c₄ ∈ (0,1), 存在 c₃ 使 Moran 方程成立
# 即无穷多解系列
print(f"  对给定 d_H, 4-map IFS 的 Moran 方程:")
print(f"    c₁^d + c₂^d + c₃^d + c₄^d = 1")
print(f"    ⇒ c₃^d = 1 - c₁^d - c₂^d - c₄^d")
print(f"  对任意 c₄ ∈ (0, 1-c₁^d-c₂^d), 存在 c₃ 解")
print(f"  自由度 = 2 (c₃, c₄)")
print(f"  → 欠约束, 无预测力 ❌")

# 演示不同 c₄ 的可行解系列
print(f"\n  可行解系列 (固定 d_H):")
for c4_test in [0.001, 0.01, 0.05, 0.1]:
    c3d = 1 - c1**d_H - c2**d_H - c4_test**d_H
    if c3d > 0:
        c3_test = c3d**(1/d_H)
        print(f"    c₄={c4_test:.3f} → c₃={c3_test:.6f} ✅")
    else:
        print(f"    c₄={c4_test:.3f} → 无解 (c₃^d 需 >0) ❌")

# =============================================================
# §4 信息论类比: 3 是复杂度-精确度的最优平衡
# =============================================================
print("\n" + "=" * 72)
print("§4 信息论最优性: 与基数经济 e < 3 的平行")
print("=" * 72)

print(f"""
  模型选择的信息论准则:

  ┌─────────────┬──────┬──────┬──────┐
  │ 模型         │ n=2  │ n=3  │ n=4  │
  ├─────────────┼──────┼──────┼──────┤
  │ 自由度 k     │ 0    │ 1    │ 2    │
  │ 可拟合参数   │ —    │ c₃   │ c₃,c₄│
  │ Moran 自洽  │ ❌   │ ✅   │ ✅   │
  │ 预测力       │ 无解 │ 唯一 │ 无穷 │
  │ AIC 惩罚     │ —    │ 2    │ 4    │
  └─────────────┴──────┴──────┴──────┘

  n=3 是唯一可工作且参数最少的模型:
  - n=2: 数学上无解 (过约束)
  - n=3: 恰好确定 (1 方程, 1 未知数)
  - n=4: 无穷多解 (1 方程, 2 未知数)

  这与基数经济 (§2.1) 的结论平行:
    e ≈ 2.718 < 3 是信息效率最优的进制
    3-map < n-map 是谱自洽性最优的 IFS

  ★ 结论: 3 = N_active 是谱 IFS 的信息论最优选择
""")
