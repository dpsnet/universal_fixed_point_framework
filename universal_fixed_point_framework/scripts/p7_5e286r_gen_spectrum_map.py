from fractions import Fraction as F

DIGEST = 'E:/workspace/hyper-resolution/P7-5e_最新研究成果_2026-10-30.md'
RS = 'E:/workspace/hyper-resolution/universal_fixed_point_framework/RESEARCH_STATE.md'
K = 8
B = K - 3          # 邻居基 b=5
S = K - 1          # 静默/塔锚指数 7
results = []


def chk(name, cond, note=''):
    results.append((name, bool(cond), note))


text = open(DIGEST, 'rb').read().decode('utf-8')
rs = open(RS, 'rb').read().decode('utf-8')

# ---------------- P1 精确性：四系数与 k=8 的对应 ----------------
d_inf = F(1, 7 * 8)
c1 = F(K + B, 2 ** (K - 1))
d2 = F(K * B + 1, 2 ** 4 * B ** 3)
e3 = F(K * B - 1, 2 ** 4 * B ** 3)
chk('P1a δ∞ = 1/(7·8) = 1/56', d_inf == F(1, 56), '1/56=%s' % d_inf)
chk('P1b C = (k+b)/2^{k−1} = 13/128', c1 == F(13, 128), '13/128=%s' % c1)
chk('P1c D = (k·b+1)/(2⁴·b³) = 41/2000', d2 == F(41, 2000), '41/2000=%s' % d2)
chk('P1d E = (k·b−1)/(2⁴·b³) = 39/2000', e3 == F(39, 2000), '39/2000=%s' % e3)
chk('P1e 联合生成：四系数零偏差',
    abs(d_inf - F(1, 56)) + abs(c1 - F(13, 128)) + abs(d2 - F(41, 2000)) + abs(e3 - F(39, 2000)) == 0,
    '单规则输出四系数，精确 0 偏差')

# ---------------- P2 零参数 ----------------
chk('P2 零自由参数：所有量由 k=8 决定', (B == 5) and (S == 7) and (2 ** (K - 1) == 128),
    'b=k−3=5、s=k−1=7、2^{k−1}=128、2⁴=16 —— 无外部标度')

# ---------------- P3 覆盖性：2 幂组合形式化 ----------------
chk('P3a 分子 ε∈±{1,3,5} = ±{2⁰, 2⁰+2¹, 2²+2⁰}',
    (1 == 2 ** 0) and (3 == 2 ** 0 + 2 ** 1) and (5 == 2 ** 2 + 2 ** 0),
    '三个邻居分子全为 2 幂和')
chk('P3b 指数集 {−2,−1,+1,+3} = {−2¹,−2⁰,+2⁰,+2⁰+2¹}',
    sorted([-2, -1, 1, 3]) == sorted([-(2 ** 1), -(2 ** 0), 2 ** 0, 2 ** 0 + 2 ** 1]),
    '四个指数全为 2 幂（含符号）')
chk('P3c 层深分工：2²=4 只出现在分子层（5=2²+2⁰）', 5 == 2 ** 2 + 2 ** 0,
    '分子层上限 2²；指数层上限 2¹（P3b）')
chk('P3d 分母 2000 = 2⁴·b³，2⁴=16 为分子层上限', 2000 == 2 ** 4 * B ** 3,
    '16·125 = 2000')

# ---------------- P4 样本外外推（未参与拟合的深阶系数） ----------------
chk('P4a 深阶 i′(2)=−39/2048 已登记（RS 权威源）', rs.count('39/2048') >= 1,
    'RS 登记处=%d（digest 摘要=%d）' % (rs.count('39/2048'), text.count('39/2048')))
chk('P4b 分子族一致：39 = k·b−1（与 E 同族）', 39 == K * B - 1,
    '同一 8·5−1 分子可同时出现在闭式与深阶')
chk('P4c 分母不一致：2048=2⁴·2⁷ ≠ 2⁴·b³ ⇒ 规则需两分支',
    2048 == 2 ** 4 * 2 ** 7 and 2048 != 2 ** 4 * B ** 3,
    '闭式用 b³=125，深阶用 2^{k−1}=128 ⇒ 非单一分母规则')

# ---------------- P5 受限族唯一性 ----------------
chk('P5a 替代分子 13 = 2k−3 同样成立', 13 == 2 * K - 3, '2·8−3=13')
chk('P5b 替代分子 13 = 2⁴−3 同样成立', 13 == 2 ** 4 - 3, '16−3=13')
chk('P5c 替代分母 128 = 2⁴·8 亦成立（分层可改写）', 128 == 2 ** 4 * 8,
    '16·8=128；分子/分母分工可整套改写')
chk('P5d 结论：受限族内不唯一 ⇒ 唯一定性未达成', True,
    'P5a–P5c 表明同一数值可由不同结构叙述生成；替代族无界，不可穷举')

# ---------------- 判定 ----------------
chk('J1 P1∧P2∧P3 通过 ⇒ 记法压缩达成（零参数单规则覆盖四系数）', True,
    '新资产：四系数压缩为一条代数规则')
chk('J2 P4 部分通过（分子族一致、分母需两分支）', True,
    '样本外仅分子族可预测，分母不闭合')
chk('J3 P5 未通过 ⇒ 机制级未锁，不得升为「生成机制」', True,
    '登记为「记法压缩」而非「生成机制闭合」')
chk('J4 不关闭任何项；不影响 k(2) 开放', True,
    'k(2) 的重启条件仍是 1/m⁵ 精确生成函数，本段只覆盖 ≤1/m³ 与深阶 i′(2)')

npass = sum(1 for _, ok, _ in results if ok)
print('=== 开放项 2 判别：生成谱假说的代数映射 ===')
print('结果 %d/%d 成立' % (npass, len(results)))
