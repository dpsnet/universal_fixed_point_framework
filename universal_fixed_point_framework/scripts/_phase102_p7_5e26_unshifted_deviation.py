# -*- coding: utf-8 -*-
"""
Phase 102 P7-5e-26：无修正偏差分析——修正机制观察性证据
================================================================
谱隙链 5 成员的"无修正基准"（C²×计数因子）对实验值的固有偏差：
第一代偏大（+0.13%）、第二代偏小（−0.16%）、第三代小偏差（+0.04~0.06%）
修正 (1±Δλ/16) 的作用：把偏差压到 0.1% 以下——"谱隙校正"有效性统计
"""
import math

dH   = math.log(15)
dlam = math.pi/(24*dH+72)
kmax, Ngen = 8, 3
C  = 2*math.sqrt(math.log(10))
C2 = C*C
corr = dlam/16

pdg = {"m_e": 0.51099895, "m_ud": 3.45, "m_s": 93.4, "m_tau": 1776.86, "m_b": 4180.0}
fac = {"m_e": (1/18), "m_ud": (3/8), "m_s": (81/8), "m_tau": 193.0, "m_b": (4096/9-1)}
sign = {"m_e": -1, "m_ud": -1, "m_s": +1, "m_tau": 0, "m_b": 0}
order = ["m_e", "m_ud", "m_s", "m_tau", "m_b"]

print("="*104)
print("P7-5e-26：无修正偏差分析——修正机制观察性证据")
print("="*104)
print("  谱隙修正量：Δλ_min/16 = %.6f（%.4f%%）" % (corr, corr*100))
print()

print("① 无修正偏差 vs 修正后偏差（5 成员）：")
print("  %-6s %-14s %-14s %-14s %-10s %s" % ("成员", "无修正值", "无修正偏差", "修正后偏差", "修正符号", "残差<Δλ/16?"))
for k in order:
    base = C2*fac[k]
    dev0 = (base/pdg[k]-1)*100
    dev1 = (base*(1+sign[k]*corr)/pdg[k]-1)*100
    ok = "✓" if abs(dev1) < 0.1 else "✗"
    print("  %-6s %-14.4f %-14.4f %-14.4f %-10s %s" % (k, base, dev0, dev1, sign[k], ok))
print()

print("② 关键观察：")
print("  第一代（m_e/m_ud）无修正偏差：+0.134%/+0.112%——偏大（≈ Δλ/16 = 0.143% 量级）")
print("  第二代（m_s）无修正偏差：−0.156%——偏小（≈ Δλ/16 量级）")
print("  第三代（m_τ/m_b）无修正偏差：+0.041%/+0.060%——小偏差（< Δλ/16）")
print("  修正符号 = 偏差方向的反号（第一代偏大→减、第二代偏小→加、第三代小偏差→不需修正）")
print()

print("③ 修正有效性统计：")
resid = [abs(C2*fac[k]*(1+sign[k]*corr)/pdg[k]-1) for k in order]
print("  修正后残差：全部 < 0.1%%（max = %.4f%%）——'谱隙校正'有效" % (max(resid)*100))
print("  无修正 |δ| 与 Δλ/16 之比：m_e %.2f、m_ud %.2f、m_s %.2f（≈1 量级）——偏差本身就是谱隙量" % (
    (C2*fac["m_e"]/pdg["m_e"]-1)/(corr), (C2*fac["m_ud"]/pdg["m_ud"]-1)/(corr), (C2*fac["m_s"]/pdg["m_s"]-1)/(corr)))
print()

print("④ 判定：")
print("  ★ 观察性证据：无修正偏差 ≈ ±Δλ/16 量级（偏差=谱隙量）——修正符号 = 偏差方向反号（代规则）")
print("  → '谱隙采样方向随代翻转'（第一代减、第二代加、第三代零）——机制描述性成立，来源待论证")
print("  诚实边界：3 数据点（第一/二/三代）定符号规则——统计弱；偏差/Δλ 比 0.78~1.09 非精确 1——谱隙量级一致非恒等")
print()
print("exit 0")
