"""S287: α_s(M_Z) 三路径对比审计（2026-10-28）

α_s(M_Z) 的框架候选已有两条路径：S206 基（1/√10 于 M_τ）+ S249/S249b
能标级联。S286 扫描浮现第三条：1/α_s(M_Z) ≈ (17/2)(1−7σ³)。
本审计三路径对比 + 防巧合唯一性检查。
"""
import math

print("=== S287: α_s(M_Z) 三路径对比审计 ===\n")

sigma = 1/15

# 实验：α_s(M_Z) MS-bar = 0.1179(9)
a_s_exp = 0.1179
s_exp = 0.0009
inv_exp = 1/a_s_exp
s_inv = s_exp/a_s_exp**2
print(f"实验 α_s(M_Z) = 0.1179(9)——1/α_s = {inv_exp:.6f}（σ = {s_inv:.4f}）")

print("\n① 路径 A（S206 基——M_τ 能标）：")
print("   α_s(τ) ≈ 1/√10 = 0.31623——dev 0.7% vs 实验 0.314(3)——0.73σ")
print("   ——基候选（已登记）——需跑动到 M_Z（路径 B 处理）")

print("\n② 路径 B（S249/S249b 能标级联）：")
print("   基 1/√10 → 段因子 6 → 跑动级联——结构已登记（S249 家族）")

print("\n③ 路径 C（S286 浮现——直接闭式）：")
pred = (17/2) * (1 - 7*sigma**3)
print(f"   1/α_s(M_Z) ≈ (17/2)(1−7σ³) = {pred:.6f}")
print(f"   17/2 = (全态+标量)/幂基——7σ³ = 对合×活跃幂")
d = abs(math.log(pred/inv_exp))
print(f"   Δln = {d:.3e}——σ_score = {d/s_inv:.3f}")

print("\n★ 防巧合唯一性检查（1σ 窗口 [8.42, 8.55] 内的框架分数候选）：")
cands = [
    ("17/2", 8.5, "(全态+标量)/幂基"),
    ("42/5", 8.4, "约束域/静默"),
    ("80/9.5?", 8.421, "不干净"),
    ("64/7.5?", 8.533, "不干净"),
    ("12×5/7", 8.571, "不动点×静默/对合——8.57 略出窗"),
    ("16×8/15", 8.533, "全态×k_max/Σ——8.53 在窗内"),
]
for name, v, note in cands:
    inwin = "★窗内" if (inv_exp - s_inv) <= v <= (inv_exp + s_inv) else ""
    sc = abs(math.log(v/inv_exp))/s_inv if v > 0 else float('inf')
    print(f"   {name:<12} = {v:<8.4f} {note:<24} σ_score {sc:.2f} {inwin}")

print("\n诚实判定：")
print("  · 路径 C（17/2×(1−7σ³)）命中 0.009σ——但实验不确定度大（0.76%）——")
print("    是'宽松命中'（预测值落在中心值）——非高精度验证")
print("  · 防巧合：1σ 窗口内 16×8/15 = 8.533 也命中（σ_score 0.80）——")
print("    17/2 非族内唯一——候选级（弱）——不升格")
print("  · 三路径并存：A 基/B 级联/C 闭式——C 为后验观察候选——")
print("    登记为 α_s 家族第三路径——机制缺失（为何 17/2 与 7σ³？）——")
print("    α_s 端整体保持'候选级'状态（S206 判定维持）")
