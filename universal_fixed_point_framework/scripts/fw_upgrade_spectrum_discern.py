print("律1（N_gen×幂基家族）：2⁰·3 ✓、2⁴·3 ✓，中间幂 2¹·3=18/2²·3=12?/2³·3=24")
print("   ——注意 2²·3 = 12 ∈ FW（幂基²×N_gen 在！）——律1 修正：{12, 48} 在 + {3}——")
