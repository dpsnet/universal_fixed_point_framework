from itertools import product

FW = {1,2,3,4,5,7,8,15,16,6,9,10,11,12,13,14,20,21,28,29,30,31,32,35,40,42,
      44,45,46,48,49,56,58,60,61,63,64,65,84,98,100,105,125,210,253,320,675,729,1000}

print("=== 律1：N_gen×幂基家族 2^a·3（a=0..9） ===")
for a in range(10):
    v = 2**a * 3
    print(f"  2^{a}·3 = {v:4d}：{'✓ FW' if v in FW else '✗ 缺'}")
print()

print("=== 律2：静默幂 5^c（c=1..4）及 5^c 的组合 ===")
for c in range(1, 5):
    v = 5**c
    print(f"  5^{c} = {v:4d}：{'✓' if v in FW else '✗'}")
for a in range(4):
    for c in (2, 3):
        v = 2**a * 5**c
        if v <= 1000:
            print(f"  2^{a}·5^{c} = {v:5d}：{'✓' if v in FW else '✗'}")
print()

print("=== 律3：幂基ⁿ×静默 vs 幂基ⁿ×N_gen（n=1..4） ===")
print("  2ⁿ×3（N_gen 家族）：", [f"{2**n*3}{'✓' if 2**n*3 in FW else '✗'}" for n in range(1,6)])
print("  2ⁿ×5（静默 家族）：", [f"{2**n*5}{'✓' if 2**n*5 in FW else '✗'}" for n in range(1,6)])
print("  2ⁿ×7（对合域）：", [f"{2**n*7}{'✓' if 2**n*7 in FW else '✗'}" for n in range(1,6)])
print()

print("=== 补充：全态 2⁴ 与各常数（×全态升级） ===")
print("  16×3 = 48 ✓、16×5 = 80 ✗、16×7 = 112 ✗、16×8 = 128 ✗？、16×2 = 32 ✓、16×4 = 64 ✓")
print("  （16×静默 = 80 缺、16×对合域 = 112 缺、16×k_max = 128 缺——全态升级只允 ×{N_gen, 幂基, 不动点}）")
print()

