print(f"活跃 3 排斥 |f'| = 静默/活跃 = 5/3 = {expansion}（扩张因子 1/c）✓")
print(f"c×1/c = {c*expansion} = 1 ✓（收缩×扩张互逆）")

print("\n=== 关键判别：收缩×变化单位 ===")
print(f"c×σ = (3/5)×(1/15) = {c*sigma} = 1/25 = 静默⁻² ✓✓")
print(f"扩张×σ = (5/3)×(1/15) = {expansion*sigma} = 1/9 = 活跃⁻² ✓✓")
print("→ ★ 静默⁻² = 收缩因子×σ（谱层基 = 收缩×暴露复合）")
print("→ ★ 活跃⁻² = 扩张因子×σ（扩张×暴露）")

print("\n=== 谱层静默⁻² 家族的语义 ===")
