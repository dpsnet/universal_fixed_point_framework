def load():
    with io.open(P, "r", encoding="utf-8", newline="") as f:
        return f.read()


def probe():
    txt = load()
    ok = True
    for old, new, tag in PAIRS:
        c = txt.count(old)
        if c != 1:
            ok = False
            print("!! %s count=%d [%s]" % (tag, c, old[:40].replace("\n", "⏎")))
        else:
            print("OK %s count=1" % tag)
            txt = txt.replace(old, new, 1)
    print("\nCRLF=%d LF=%d PROBE_ALL_CHAIN_OK=%s" % (txt.count("\r\n"), txt.count("\n"), ok))
    return ok


def apply():
    txt = load()
    for old, new, tag in PAIRS:
        c = txt.count(old)
        if c != 1:
            print("ABORT: %s count=%d" % (tag, c))
            return False
        txt = txt.replace(old, new, 1)
    with io.open(P, "w", encoding="utf-8", newline="") as f:
        f.write(txt)
    print("APPLIED %d; bytes=%d lines=%d" % (len(PAIRS), len(txt.encode("utf-8")), txt.count("\n") + 1))
    return True


def verify():
    txt = load()
    bad = []
    for old, new, tag in PAIRS:
        if txt.count(old) != 0:
            bad.append(("old-remains", tag, txt.count(old)))
        if txt.count(new) < 1:
            bad.append(("new-missing", tag, 0))
    for token in ["−4.5σ_score", "Fibonacci {3, 5, 7, 8}", "1.1×10⁻¹⁰", "9.1×10⁻¹⁰",
                  "codata2026_frozen", "v1.2 — 2026-11-11", "n=4 有整数根"]:
        if token in txt:
            bad.append(("token-remains", token, txt.count(token)))
    print("VERIFY issues =", len(bad))
    for b in bad:
        print("  ", b)
    print("CRLF=%d LF=%d lines=%d" % (txt.count("\r\n"), txt.count("\n"), txt.count("\n") + 1))
    return len(bad) == 0


