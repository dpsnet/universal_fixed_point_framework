# 框架量
N_gen, k_max, base, sil, fp, inv = 3, 8, 2, 5, 4, 7
print("=== m_t/m_b 层级规则第四实例判别 ===\n")
print("闭式（观测 41.2838±0.238 / PDG 中心 41.3134）:")
print("  A = 371×451/4050 = 41.31382716（乘法链）")
print("  B = 42 − 7³/500 = 41.314（减法链，禁闭域 42）")
print("  C = 41 + π/10（π 位置锁定，表达式层）")
print("  D = A − 17/40500 = B − 2/3375 = 557731/13500 = 41.3134074（存档级）")

print("\n--- 修正分母分解 ---")
decomp = {
    "A 分母 4050": 4050,
    "B 分母 500": 500,
    "D1 分母 40500": 40500,
    "D2 分母 3375": 3375,
    "D 分母 13500": 13500,
}
for name, d in decomp.items():
    facs = []
    t = d
    for p in [2, 3, 5, 7]:
        c = 0
        while t % p == 0:
            t //= p
            c += 1
        if c:
            facs.append(f"{p}^{c}")
    print(f"  {name} = {d} = {'×'.join(facs)}" + (f"×{t}" if t > 1 else ""))

print("\n--- 归属判别 ---")
print("675 族 = N_gen³·静默² = 27×25 = 675；320 族 = k_max²·静默 = 64×5 = 320")
for name, d in decomp.items():
    q675, q320 = d / 675, d / 320
    s675 = f"{q675:.4f}" if q675 == int(q675) else f"{q675:.4f}（非整）"
    s320 = f"{q320:.4f}" if q320 == int(q320) else f"{q320:.4f}（非整）"
    print(f"  {name}: /675 = {s675}  /320 = {s320}")

