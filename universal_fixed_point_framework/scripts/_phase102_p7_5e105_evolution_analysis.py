def diffs(seq):
    """一阶/二阶/三阶差分"""
    d1 = [seq[i+1]-seq[i] for i in range(len(seq)-1)]
    d2 = [d1[i+1]-d1[i] for i in range(len(d1)-1)]
    d3 = [d2[i+1]-d2[i] for i in range(len(d2)-1)]
    return d1, d2, d3

def ratios(seq):
    """相邻比值（绝对值）"""
    return [abs(seq[i+1]/seq[i]) for i in range(len(seq)-1)]

def search_fw(v, tol=0.005, label=""):
    """框架量搜索（容差 0.5%）"""
    hits = []
    for name, val in FW.items():
        if val != 0 and abs((v-val)/val) < tol:
            hits.append("%s（差 %+.3f%%）" % (name, (v-val)/val*100))
    if hits:
        print("  %s = %.8f → %s" % (label, v, "、".join(hits)))
    else:
        print("  %s = %.8f → 无框架量命中（0.5%% 容差）" % (label, v))
    return hits

