def su2_decomp(dim):
    """将 dim 维空间分解为 SU(2) 不可约表示（整数+半整数 j 混合），返回 j 列表。"""
    j_list = []
    remaining = dim
    # 贪心：先大 j（半整数），保证维数覆盖
    j = dim / 2  # 从最大可能开始
    while remaining > 0:
        d = int(2 * j + 1)
        if d <= remaining:
            j_list.append(j)
            remaining -= d
        else:
            j -= 0.5
            if j < 0:
                break
    return j_list


