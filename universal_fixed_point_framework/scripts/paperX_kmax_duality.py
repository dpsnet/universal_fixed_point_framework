    print(f"    · 分支对偶:   B = 15 = 2·k_max − 1")
    print(f"    · 维数对偶:   d_H = ln(2·k_max − 1) = ln 15")
    print(f"    · 底空间对偶: Cl(1,7) 生成元 = 8 = k_max")
