"""S148 框架常数导出层候选2：韦达互锁 + 15 唯一分解（先证伪）
"为何框架常数恰为 Fib"的归约链：
  4维时空(Cℓ(3,1)) → 全态 16=2⁴ → σ⁻¹=15=16−1 → 15 唯一非平凡分解
  3×5（双双 Fib）→ 和 8=F₆=k_max → {3,5,8} 三重 Fib 派生
验证：
  1. 15 的因子分解唯一性（非平凡对 = {3,5}）
  2. {3,5,8} Fib 身份（F₄=3、F₅=5、F₆=8）
  3. 韦达根唯一性（x+y=8、xy=15 ⟹ {3,5} 唯一正整数解）
  4. λ_k=√(k(k+1)) 比值 → 1（非 φ——候选3证伪）
"""
import numpy as np

print("=== 1. 15 的因子分解（唯一非平凡对） ===")
pairs = [(d, 15//d) for d in range(2, 8) if 15 % d == 0]
print(f"15 的非平凡因子对: {pairs}（唯一——3×5）")
print(f"15 = 1×15、3×5——唯一非平凡分解 ✓")

print("\n=== 2. Fib 身份（F₄=3、F₅=5、F₆=8） ===")
fib = [0, 1]
while len(fib) < 10:
    fib.append(fib[-1] + fib[-2])
print(f"Fib 序列: {fib[1:10]}")
print(f"F₄ = {fib[4]} = 3 ✓   F₅ = {fib[5]} = 5 ✓   F₆ = {fib[6]} = 8 ✓")
print(f"3+5 = {3+5} = F₆ ✓（相邻 Fib 和 = 下一 Fib）")

print("\n=== 3. 韦达根唯一性（x+y=8、xy=15） ===")
sols = [(x, 8-x) for x in range(1, 8) if x*(8-x) == 15]
print(f"正整数解: {sols}（唯一——{sols[0]}）✓")
print(f"3·5 = 15 = σ⁻¹ = 全态−1 ✓")

print("\n=== 4. λ_k 比值渐近（候选3证伪） ===")
for k in [3, 5, 8, 20, 100, 1000]:
    lam = np.sqrt(k*(k+1))
    lam_prev = np.sqrt((k-1)*k)
    print(f"k={k:5d}: λ_k/λ_(k-1) = {lam/lam_prev:.6f}")
print("→ 渐近 1（非 φ=1.618）——'λ 比渐近 φ'候选证伪 ✓")

print("\n=== 5. 归约链完整性 ===")
print("4维(Cℓ(3,1)) → 全态16=2⁴ → σ⁻¹=15=16−1 → 唯一分解{3,5}(双双Fib)")
print("→ 和8=F₆=k_max → {3,5,8} 三重Fib派生——'为何恰为Fib'降级为")
print("  '15 唯一分解 + 3,5 恰为相邻 Fib'的算术事实 + '为何全态16/k_max8'")
print("  剩余第一性开放（归范畴公设层）")
