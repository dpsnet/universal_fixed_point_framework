import math

LAM = 6562.79  # Angstrom (Hα)
# 标准一阶 Zeeman 公式 (朗德 g 组合 ~1): Δλ(Å) = 4.67e-13 · λ²(Å²) · B(G)
# 100 MG 对照: 4.67e-13*4.307e7*1e8 = 2.011 Å (与 236 表 σ 一阶 4668.68 cm^-1 -> 2.011 Å 一致)
PI_100MG_ANG = 153.4  # 100 MG π 完整(纯二次)位移, Å (356.229 cm^-1 * λ²/1e8; 104az-238 勘误: 原 0.1534 少乘 10³)

def sigma1_ang(B_MG):
    return 4.67e-13 * LAM**2 * (B_MG*1e6)

def pi_quad_ang(B_MG):
    return PI_100MG_ANG * (B_MG/100.0)**2   # ∝B² (指数 1.93-2.0, 20-300 MG)

def req_R(B_MG):
    return LAM / pi_quad_ang(B_MG)

