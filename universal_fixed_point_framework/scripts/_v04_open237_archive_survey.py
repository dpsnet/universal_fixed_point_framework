# ⚠️ 勘误(104az-238): 上行为 cm⁻¹→Å 换算少乘 10³ 的错误值; 356.229 cm^-1 = 153.4 Å。
# ⚠️ 勘误(104az-239): 本脚本 π 列为 Hα λ² 标度近似(量级参考); Hβ 精确值 120/150/180 MG = 5260/5485/5761 Å, 蓝窗仅 B≤~125 MG (见 §10.35)。
