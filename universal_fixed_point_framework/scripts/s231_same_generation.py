# -*- coding: utf-8 -*-
"""S231 同代比家族扩展：e 同代资格判别
检验：第 3 代同代比 m_b/m_tau = e^(6/7)（S226——含 e）
     第 2 代同代比 m_c/m_mu = ?（候选 12 = 活跃x不动点——不含 e？）
判别："e 锚定第三代" vs "e 锚定所有同代" vs "e 无关"
"""
import math
print("=== S231: 同代比家族扩展（e 同代资格判别） ===\n")

print("=== 1. 第 2 代同代比：m_c/m_mu ===")
m_c, m_mu = 1.27, 0.1056583755
r = m_c/m_mu
u_c = 0.02
u_mu = 2.3e-6
r_unc = r * math.sqrt((u_c/m_c)**2 + (u_mu/m_mu)**2)
print(f"实验 m_c/m_mu = {r:.4f}±{r_unc:.4f}")
print(f"候选 12 = 活跃x不动点（3x4）——全壳")
s12 = abs(r - 12)/r_unc
print(f"σ_score = {s12:.3f}σ——{'达标' if s12<=1 else '提示'}")

print("\n=== 2. e 同代资格判别 ===")
print("第 3 代同代比：m_b/m_tau = e^(6/7)——含 e（S226——0.234σ）")
print("第 2 代同代比：m_c/m_mu = 12——纯框架（不含 e）")
print("跨代比：m_c/m_tau = 5/7——纯框架（S227——0.041σ）")
print("跨代比：m_mu/m_e ≠ e^(16/3)——证伪（S227）")
print("→ 4 样本：e 仅出现在第 3 代同代比——'e 锚定第三代'候选")

print("\n=== 3. 候选框架审计：12 = 3x4 ===")
print("12 = 活跃 x 不动点 = 3 x 4——全壳组件")
print("框架命名集：3（活跃）、4（不动点）——乘积在命名集内")
print("12 其他分解：2^2 x 3（幂基^不动点 x 活跃）——同样全壳")

print("\n=== 4. 诚实评估 ===")
print("m_c/m_mu = 12：σ_score 0.106σ——达标——但依赖 m_c ±0.02（1.6%）")
print("e 同代资格：4 样本支持'e 锚定第三代'——样本仍小——观察级")
print("预测登记：第 2 代同代比纯框架（12）、第 3 代含 e——")
print("  将来更精确 m_c/m_mu 检验 12 的稳定性")
print("→ 观察级——不升格——但判别叙事收束（e 锚定最重代）")
