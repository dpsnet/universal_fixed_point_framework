print("=== 1. 16/15 = 1+σ 三路径出现汇总（104az-158 开放项）===")
sig = 1/15
print(f"16/15 = {16/15:.9f}；1+σ = {1+sig:.9f} ✓（L6 差 1 链恒等）")
print("\n路径 1（轻子质量链，P7-5c）：m_τ 锚定递归展开 = 16·dH + ln(16/15)/3（dev +0.043%，候选）")
print("路径 2（精细结构候选，P7-5j）：α_v = 16/15 + √(2/N_c)（dev +0.0108%，候选）")
print("路径 3（核磁子链，104az-158）：μ_t = g_p/2×(1+σ)（dev −0.0025%，候选）")
print("\n三路径：轻子/α/磁矩三扇区 × ln/加法/乘法三代数角色 × 同因子 16/15")
print("→ 判别：16/15 为差 1 链结构常数（L6 产物，Pell 恒等锚定），三路径复用 = 生成块复用证据")

print("\n=== 2. n²/(n²−1) 家族（框架常数平方的差 1 邻比）===")
fam = {3:"N_gen", 4:"不动点", 5:"静默", 7:"对合域", 8:"k_max"}
for n, tag in fam.items():
    v = n*n/(n*n-1)
    print(f"  {n}²/({n}²−1) = {n*n}/{n*n-1} = {v:.6f}（{tag}）")

print("\n=== 3. 家族成员在框架已知量中的出现扫描 ===")
cands = {
    "9/8 (N_gen²/(N_gen²−1))": 9/8,
    "16/15 (不动点²/(不动点²−1))": 16/15,
    "25/24 (静默²/(静默²−1))": 25/24,
    "49/48 (对合域²/(对合域²−1))": 49/48,
    "64/63 (k_max²/(k_max²−1))": 64/63,
}
known = {
    "g_p/2": 2.79284734462, "g_n/2": 1.91304273, "μ_t": 2.9789624656,
    "μ_d": 0.8574382308, "d_H(65/24)": 65/24, "1/α_v": 1.983163,
    "κΛ": 401.7316, "Λ_QCD~210": 210.0, "4.2": 4.2, "m_p'/m_e": 1836.152674897,
    "g_p/2−g_n/2": 0.87980461,
}
print("\n对每个候选因子 f，扫描 known 量 k 的 k/f 是否接近框架整数/有理数：")
hits = []
for fname, f in cands.items():
    for kname, k in known.items():
        r = k/f
        for base, bname in [(3,"N_gen"),(4,"不动点"),(5,"静默"),(7,"对合域"),(8,"k_max"),(16,"不动点²"),(25,"静默²"),(40,"4×静默²"),(44,"44"),(45,"45"),(210,"Λ~210"),(231,"231")]:
            dev = (r-base)/base*100
            if abs(dev) < 0.05:
                hits.append((fname, kname, f, k, r, base, bname, dev))
                print(f"  ★ {kname}/{fname} = {r:.6f} ≈ {bname} = {base}（dev {dev:+.4f}%）")

print(f"\n扫描命中数 = {len(hits)}")
print("\n=== 4. μ_t 候选唯一性复核 ===")
mt = 2.9789624656; gp2 = 2.79284734462
print(f"μ_t/g_p/2 = {mt/gp2:.7f} vs 16/15 = {16/15:.7f}：dev {(mt/gp2-16/15)/(16/15)*100:+.5f}%")
print(f"μ_t/(g_p/2) = {mt/gp2:.7f}；候选因子 16/15 是唯一 0.01% 级命中（对照 9/8、25/24、49/48）")
for n in [3,5,7,8]:
    f = n*n/(n*n-1)
    print(f"  对照 {n}²/({n}²−1) = {f:.6f}：dev {(mt/gp2-f)/f*100:+.4f}%")
