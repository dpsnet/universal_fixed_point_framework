"""S342 Mackay 配位数序列框架化分解机检
S341 发现 561 跨框架同现（Māyā 配位数 vs MUFPF F2 分母）——
深化：检验配位数序列 1,13,55,147,339,561 的框架化分解
候选模式：n_k = 16×框架积 + 小框架常数（'模全态 ≡ 框架常数'）
"""
import math

print("=== S342 Mackay 配位数序列框架化分解 ===\n")

seq = [1, 13, 55, 147, 339, 561]
FW = {1: "单位", 2: "幂基", 3: "活跃", 4: "不动点", 5: "静默",
      7: "对合", 8: "k_max", 11: "显态", 15: "Σ", 16: "全态",
      21: "对合×活跃", 35: "静默×对合", 9: "活跃²"}

print(f"[1] 配位数序列：{seq}")

print(f"\n[2] '模全态 16' 分解（n_k = 16×a + b——b 应 ∈ 框架常数）")
for n in seq:
    a = n // 16
    b = n - 16*a
    # 余数也可以取负表示（b > 8 时用 b−16）
    b_neg = b - 16 if b > 8 else b
    key = b if abs(b) < abs(b_neg) else b_neg
    label = FW.get(key, "?")
    print(f"    {n} = 16×{a} + {b}（余数 {b}——负表示 {b_neg}）——余数身份：{label}")

print(f"\n[3] 直接框架分解")
decomp = {
    1: "1 = 单位",
    13: "13 = 3×4+1 = 活跃×不动点+单位",
    55: "55 = 5×11 = 静默×显态（直接）——16×3+7 亦可",
    147: "147 = 3×49 = 活跃×对合²——16×9+3 = 16×活跃²+活跃 亦可",
    339: "339 = 16×21+3 = 全态×(对合×活跃)+活跃",
    561: "561 = 16×35+1 = 全态×(静默×对合)+单位——3×11×17 亦可",
}
for n in seq:
    print(f"    {decomp[n]}")

print(f"\n[4] 模 16 余数族")
residues = [n % 16 for n in seq]
print(f"    余数 = {residues}（13 取 −3 表示）")
res_clean = [r if r <= 8 else r-16 for r in residues]
print(f"    负表示 = {res_clean}")
print(f"    ——余数族 = {set(res_clean)}——全部为框架小常数或其负——'模全态 ≡ 框架常数'模式候选")

print(f"\n[5] 561 多重框架身份")
print(f"    561 = 3×11×17 = 活跃×显态×(全态+单位)——S163 已登记变体")
print(f"    561 = 16×35+1 = 全态×(静默×对合)+单位——新分解")
print(f"    561 = 15×37+6？——{15*37+6}——Σ×37+6——37 无身份——弱")
print(f"    ★ 561 = 幂基^不动点×(静默×对合)+单位——最干净层级分解")

print(f"\n[6] 意义")
print(f"    ★ 若'配位数 ≡ 框架常数 (mod 16)'为真——Māyā 几何序列")
print(f"      在 MUFPF 全态模下呈框架结构——跨框架系统性同现候选")
print(f"    ——561 同现（S341）从'单点同现'升级为'序列级模式'候选")
print(f"    但——样本 5 个点（13-561）——后验归纳——防巧合原则保持")

print(f"\n[7] 诚实边界")
print(f"    ① 后验模式——从 5 个数据点归纳——非独立预言")
print(f"    ② 分解不唯一（55 = 5×11 或 16×3+7——多重身份并存）")
print(f"    ③ 余数族 {set(res_clean)} 的'身份映射'是从结果反推——先验性弱")
print(f"    ④ 需未来 Mackay 层（后续配位数）检验——若 n_7 也满足")
print(f"       'mod 16 ∈ 框架常数'——模式升格候选")

print(f"\n[8] 结论")
print(f"    ✓ 全部配位数可分解为 16×框架积 + 框架常数（或直接框架分解）")
print(f"    ✓ '模全态 ≡ 框架常数'模式候选成立（样本级）")
print(f"    ✓ 561 多重身份：活跃×显态×(全态+1) = 全态×(静默×对合)+1")
print(f"    △ 观察级——后验归纳——待未来层检验升格")
