    print(f"  m²(0⁻⁺) = 10πσ = 5/α' = {m2_0mp:.4f} → m = {m_0mp:.3f} GeV")
    print(f"  vs X(2370) = {x2370} GeV → 偏差 {dev_0mp:.1f}%")
    print(f"  非整数能级：Δm² = ¾·8πσ = 6πσ = 3/α'（D=4 单源）")
    check("G5 0⁻⁺ 扭转模谱定（2.357 GeV vs X(2370) 偏差 0.5%）——依赖 σ + ¾ 因子（均稳健）",
          abs(m_0mp - 2.357) < 0.01, f"偏差 {dev_0mp:.1f}%")

