    check("G1 Λ_QCD 稳健（v0.26 审计：只依赖 Δλ₃/Δλ_min=√2，不受比值第一分量歧义影响）",
          abs(ratio_old - ratio_fixed) < 1e-12, "比值修复仅影响 U(1) 扇区")

    # ============================================================
    # G2: σ = 4Λ²
    # ============================================================
    print("\n" + "=" * 74)
    print("G2. σ = 4Λ² 标度（闭弦 Regge 基础）")
    print("=" * 74)
    Lambda_GeV = Lambda_QCD / 1000.0
    sigma = 4 * Lambda_GeV ** 2  # GeV²
    print(f"  Λ = {Lambda_GeV} GeV → σ = 4Λ² = {sigma:.4f} GeV²")
    print(f"  σ 完全由 Λ_QCD 决定，Λ_QCD 稳健 → σ 稳健")
