import math

RESULTS = []


def check(name, ok, info=""):
    RESULTS.append((name, bool(ok)))
    print(f"  [{'PASS' if ok else 'FAIL'}] {name}" + (f"  ({info})" if info else ""))


def run():
    print("=" * 74)
    print("胶球谱定撤回复核（基础修复后依赖链检查）")
    print("=" * 74)

    # ============================================================
    # G1: Λ_QCD 稳健性
    # ============================================================
    print("\n" + "=" * 74)
    print("G1. Λ_QCD = 210 MeV 稳健性（依赖 Δλ₃/Δλ_min = √2，比值修复后不变）")
    print("=" * 74)
    Lambda_QCD = 210.3  # MeV（谱框架三味值）
    # 比值体系：修复后 1/√3:1:√2；Δλ₃/Δλ_min = √2 在两套体系中相同（v0.26 审计）
    ratio_old = math.sqrt(2) / (1 / math.sqrt(3))  # 旧体系 Δλ₃/Δλ₁
    ratio_fixed = math.sqrt(2) / (1 / math.sqrt(3))  # 修复后相同（第三/第一分量）
    print(f"  Λ_QCD = {Lambda_QCD} MeV（谱框架值，v0.26 审计确认稳健 15 项之一）")
    print(f"  依赖链：Δλ₃/Δλ_min = √2（比值体系第三/第一分量，修复 1/√3 后不变）")
