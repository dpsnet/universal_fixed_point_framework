    print("G3. 0⁺⁺/2⁺⁺ 闭弦 Regge 谱定（m² = 4πσ(J+1)）")
    print("=" * 74)
    m2_0pp = 4 * math.pi * sigma  # J=0
    m2_2pp = 12 * math.pi * sigma  # J=2
    m_0pp = math.sqrt(m2_0pp)
    m_2pp = math.sqrt(m2_2pp)
    print(f"  0⁺⁺ (J=0): m² = 4πσ = {m2_0pp:.4f} → m = {m_0pp:.3f} GeV（格点 1.5-1.7）")
    print(f"  2⁺⁺ (J=2): m² = 12πσ = {m2_2pp:.4f} → m = {m_2pp:.3f} GeV（格点 ~2.40）")
