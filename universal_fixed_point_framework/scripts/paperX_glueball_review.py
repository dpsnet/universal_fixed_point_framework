    print(f"    · ¾ 因子 = D=4 闭弦零点能单源（v0.22：不依赖 Cl(1,7) 谱间隙比）")
    print(f"    · 比值修复（v0.29）：仅 U(1) 扇区变，Λ_QCD/σ/胶球谱数值明确列为'稳健量不变'")
