    check("G4 ¾ 因子 = D=4 闭弦零点能单源（1−a_c(4) = 3/4），独立于 Cl(1,7) 谱间隙比",
          abs(three_quarters - 0.75) < 1e-12, "v0.22 已确认为单源")

    # ============================================================
    # G5: 0⁻⁺ 扭转模
    # ============================================================
    print("\n" + "=" * 74)
    print("G5. 0⁻⁺ 扭转模谱定（m² = 10πσ = 5/α'，偏差 0.5%）")
    print("=" * 74)
