    print(f"  a_c(4) = (4−2)/8 = 1/4 → ¾ = 1 − a_c(4) = {three_quarters}")
    print(f"  ★ v0.22 勘误：¾ 因子 = D=4 闭弦零点能单源（§5.13 Casimir 同源）")
