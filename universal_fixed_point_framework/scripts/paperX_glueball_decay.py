RESULTS = []


def check(name, ok, info=""):
    RESULTS.append((name, bool(ok)))
    print(f"  [{'PASS' if ok else 'FAIL'}] {name}" + (f"  ({info})" if info else ""))


def kallen(a, b, c):
    """Källén 三角形函数 λ(a,b,c) = a²+b²+c²−2ab−2ac−2bc。"""
    return a * a + b * b + c * c - 2 * a * b - 2 * a * c - 2 * b * c


def pstar(m, m1, m2):
    """两体衰变态密度质心动量 p* = √λ(m², m₁², m₂²)/(2m)。"""
    lam = kallen(m * m, m1 * m1, m2 * m2)
    if lam <= 0:
        return 0.0
    return math.sqrt(lam) / (2 * m)


def ps_weight(m, m1, m2, L):
    """相空间 × 角动量势垒简化权重：Γ ∝ (p*)²L⁺¹ / m²（L = 轨道角动量）。"""
    p = pstar(m, m1, m2)
    return (p ** (2 * L + 1)) / (m * m)


