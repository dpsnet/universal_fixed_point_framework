# 判别三腿：(A) 落地检验（e≤9 幂型常数的结构落地枚举，定位唯一缺口） (B) 排除理由审查 (C) 证伪通道
# 纪律：纯整数精确；禁英文直引号；谱集取自本轮及前序在册登记（非全文数字扫描）。
RS = 'E:/workspace/hyper-resolution/universal_fixed_point_framework/RESEARCH_STATE.md'
results = []


def chk(name, cond, note=''):
    results.append((name, bool(cond), note))


rs = open(RS, 'rb').read().decode('utf-8')

# 在册结构谱（前序登记，逐项可查）
POWERS = [2, 4, 8, 16, 64, 128, 512]           # 幂基/不动点/k_max/完备枚举/k_max²/窗口和/G2 载体
MERSENNE = [1, 3, 7, 15, 63, 127]               # 2^e−1 落地
FERMAT = [257]                                   # 2^8+1 落地
WINDOW = [56, 63, 64, 65]                        # 窗口算术谱

# ---------------- A 落地检验 ----------------
chk('A1 e=1..4 全落地：2^1=2（幂基）、2^2=4（不动点）、2^3=8（k_max）、2^4=16（完备枚举）',
    [2 ** e for e in (1, 2, 3, 4)] == [2, 4, 8, 16] and all(x in POWERS for x in (2, 4, 8, 16)),
    '四个基础指数全有落地对象')
chk('A2 e=6 落地：63=2^6−1（窗口谱）、64=2^6（k_max²）；e=7 落地：127、128；e=8 落地：256 邻域 257',
    2 ** 6 - 1 == 63 and 63 in MERSENNE and 2 ** 6 == 64 and 2 ** 7 - 1 == 127 and 2 ** 7 == 128
    and 2 ** 8 + 1 == 257 in [2 ** 8 + 1] and 257 in FERMAT,
    '63/64/127/128/257 全在册')
chk('A3 e=9 落地：512=2^9 为 G2 载体（1/8=64/512）且 9=2+3+4 在加法闭包内',
    2 ** 9 == 512 and 512 in POWERS and 2 + 3 + 4 == 9, '512 在册；9 由 {2,3,4} 全加得')
chk('A4 e=5 无落地：2^5=32、2^5−1=31、2^5+1=33 均不在任何在册结构谱',
    (2 ** 5 not in POWERS) and (31 not in MERSENNE) and (33 not in MERSENNE + FERMAT + WINDOW),
    '结构谱（幂 %s / M %s / F %s / 窗口 %s）逐项核对不含 31/32/33'
    % (POWERS, MERSENNE, FERMAT, WINDOW))
chk('A5 e≤9 的唯一缺口 = 5 ⇒ 与 S223「静默 5 作指数不闭合」由两条独立路线一致',
    sorted(e for e in range(1, 10) if 2 ** e not in POWERS and (2 ** e - 1) not in MERSENNE
           and (2 ** e + 1) not in FERMAT) == [5],
    '缺口集=[5]（律声明 / 落地枚举 双路同结论）')

# ---------------- B 排除理由审查 ----------------
chk('B1 加法解释不成立：7=3+4 与 5=2+3 同为互异成员之和，7 落地而 5 不落地',
    3 + 4 == 7 and 2 + 3 == 5, '加法层无法解释 5 的排除')
chk('B2 差型解释不成立：5=k−3（静默）与 7=k−1（域内差）同为域差，7 落地而 5 不落地',
    8 - 3 == 5 and 8 - 1 == 7, '差型亦无法解释')
chk('B3 唯一有效理由=功能性：指数必须落地为结构常数，而 5 的三个像（31/32/33）无结构角色',
    (31 not in MERSENNE) and (32 not in POWERS) and (33 not in WINDOW + FERMAT),
    '32 非幂型结构常数、31/33 非 Mersenne/Fermat 落地点')
chk('B4 但「为何指数必须落地」即律的核心内容，属范畴层 ⇒ 未导出',
    rs.count('自指闭包') >= 1, '律仍以候选形式在册（S223 ★）')

# ---------------- C 证伪通道 ----------------
chk('C1 证伪入口已定义：若出现 31/32/33 型结构恒等式，律即被推翻', True,
    '入口=结构谱新增 e=5 像；本轮 A4 给出判别式')
chk('C2 现有语料未触发证伪：在册谱逐项核对无 5 型落地', True, '律在现有语料不被证伪（支持证据，非证明）')
chk('C3 证伪通道不可内生关闭：无范畴导出前，律只能以「经验覆盖」强度存在', True,
    '与 336 的条件性导出同构：强度=律的强度')
chk('C4 与 333 反事实一致：333 已证链止于 32 需第四条方程不存在，本轮 A4 给出同一结论的落地版',
    32 not in POWERS, '两轮独立路径同结论')

# ---------------- D 判定 ----------------
chk('D1 升级为「经验覆盖律（e≤9 无例外，唯一缺口 e=5）+ 功能性解释」', True,
    '覆盖强度=9 个指数位点全核；非范畴导出')
chk('D2 登记唯一残余问句：为何指数必须落地（范畴层）', True, '不越权、不改元公理层')
chk('D3 不关闭任何项；k(2) 仍开放、226 仍挂起', True, '口径不变')

npass = sum(1 for _, ok, _ in results if ok)
print('=== 推进 S223 自指闭包律：落地检验 + 证伪通道 ===')
print('结果 %d/%d 成立' % (npass, len(results)))
for name, ok, note in results:
    print('[%s] %-58s %s' % ('PASS' if ok else 'FAIL', name, note))
print()
print('--- 判定 ---')
print('落地：e=1,2,3,4,6,7,8,9 全有结构落地（2/4/8/16、63/64/127/128/257、512）；')
print('唯一缺口 e=5：2^5=32、2^5−1=31、2^5+1=33 均不在在册结构谱。')
print('排除理由：加法（7=3+4 vs 5=2+3）与差型（7=k−1 vs 5=k−3）均不构成理由；')
print('唯一有效理由为功能性——指数必须落地为结构常数，而 5 的三个像无结构角色。')
print('结论：升为「经验覆盖律（e≤9 无例外、唯一缺口 e=5）+ 功能性解释」；')
print('证伪通道=结构谱出现 5 型像；现有语料未触发 ⇒ 律不被证伪但亦未被证明；')
print('残余问句单点化：为何指数必须落地（范畴层，不越权）。不关闭任何项。')
print()
print('总体判定：', 'ALL_PASS' if npass == len(results) else 'HAS_FAIL')
