"""
chainB_hNorm_24_source_judge.py — "维数3投影 ⟷ 四元数维数4/24 一体两面?" 结构来源判别 v1.0
RN-ENDO-010 §8.13 后续判别 配套探点

判辨对象:
   hNorm 等价式  ‖S.A‖ ≤ √(2/3)·spectralGap8 , (DeviationBound.lean L436)
   ‖S.A‖² 的平方系数 2/3 的两条候选路径:
     路径A(V_last): 2/3 = (d−1)/d，d=3(三维球面赤道平衡投影，Maxwell 最概然速率同源)
     路径B(V3):      2/3 = (4/√24)² = 16/24 = dim_ℝℍ²⁄(8·3)，dim_ℝℍ=4

判别问题: 这两条是否"一体两面"(同源、视角不同)？
   判据密钥 = 24 的结构来源。三种 24 候选:
     ① 8×3      证明技术(不等宽链常数8 × 偏差项数3)，非 ℍ 内源
     ② |2T|=24  二元四面体群 ⊂ SU(2) ⊂ ℍ 单元球面(实四元数范数1球面)
     ③ 4!  =24  {3 空间轴 + 1 实部} 的全置换 S₄

权威核(paper1 定义 3.11/3.12a 无关处): 本脚本不触碰 LACI 判据语义
   (LACI 为谱间隙单调递减函数族/静默判据，与 hNorm 范数上界为不同类型量；v1.11 误读已撤回，见 §8.13)
本脚本仅做 2/3 的结构来源匹配，不声称任何 LACI 来源。
"""
import math

# ---------------- 数值基础 ----------------
def spectral_gap8():
    return (math.sqrt(6) - math.sqrt(2)) / math.sqrt(72)

sg = spectral_gap8()
sq23 = math.sqrt(2 / 3)

# ---------------- 路径 A: 维数 3 投影 ----------------
def pathA(d=3):
    return (d - 1) / d

# ---------------- 路径 B: 四元数维数 / 24 ----------------
dimH = 4.0
base8, terms3 = 8.0, 3.0
pathB = (dimH / math.sqrt(base8 * terms3)) ** 2   # (4/√24)²

# ---------------- 一体两面关键恒等: 两式只相切于 d=3 ----------------
# (d+1)²/(8d) = (d−1)/d  ⟺ (d+3)² = 0 ⟺ d=3 (二重根)
def struct_eq(x):
    return ((x + 1) ** 2) / (8 * x)   # 泛化后的路径B候选(d 替换为 d+1? 见下)

def tangent_discriminant(dlist):
    # 对偶数个 d 检验两式差 (用于语义说明), 输出差值
    rows = []
    for d in dlist:
        if d <= 0:
            continue
        # 路径B 在此化为 (d+1)²/(8·d)，表示"4=1+3"换面表达式随 d 演化
        B = ((d + 1) ** 2) / (8 * d)
        A = (d - 1) / d
        rows.append((d, A, B, abs(A - B)))
    return rows

print("=" * 76)
print("hNorm 2/3 一体两面判别 (v1.0)")
print("=" * 76)

# ---------------- 判别矩阵 ----------------
print("\n[0] 数值基础")
print(f"     spectralGap8 = (√6−√2)/√72 = {sg:.10f}")
print(f"     hNorm ‖S.A‖² 系数 = 2/3 = {sq23**2:.10f}")
print(f"     路径A (d−1)/d |d=3   = {pathA():.10f}")
print(f"     路径B (4/√24)²       = {pathB:.10f}")
assert abs(pathA() - pathB) < 1e-12, "两路径数值不一致! ??"
print(f"     → 路径A = 路径B (数值一致, {abs(pathA()-pathB):.1e})")

# ---------------- 一体两面核心判别 ----------------
print("\n" + "=" * 76)
print("[1] 一体两面的实证: 4 = 1(实部) + 3(虚部), 共享同一'3'")
print("=" * 76)
print("""     dim_ℝℍ = 4 = 1 + 3
       1 = 实四元数标量部(ℝ·1)
       3 = Im ℍ = ℝi⊕ℝj⊕ℝk = Cl(0,3) 的 3 个空间生成元 = 路径A 的 d=3
     → 两条链长在同一个对象 ℍ ≅ Cl(0,3)⁰ 上; 路径A 的'3' 与路径B 的'4=1+3'中
       的'3' 是同一枚币。赤道 2/3 平衡投影发生在虚部三维球面 S² 上。
     →【判一/两同源】: 真。此为真正的一体两面(非数值巧合)。""")

# ---------------- 判别二: 16/24 的 24 是否与 ℍ/虚部3 同源 ----------------
print("\n" + "=" * 76)
print("[2] 判别二(决定性): 16/24→2/3 的 24 能否由 ℍ 内源同构地填出?")
print("=" * 76)
print("""     16/24→2/3 并非独立得出 2/3; 它把同一个 2/3 用分母 24 重排(16=4²)。""")

# 三种 24 候选的结构来源判定
print("\n     候选① 24 = 8×3   (不等宽链常数8 × 偏差项数3)")
print("        8=证明技术(Frobenius 链常数), 3=交换律偏差项数")
print("        皆非 Cl(1,7)/ℍ 结构量 → 结构来源: 否(证明技术, 非内源)")
print("        → 若 24 只能如此出, 则路径B 只是 α在原位打转, 一体两面不成立")

print("\n     候选② 24 = |2T|   (二元四面体群 ⊂ SU(2) ⊂ ℍ 单元球面)")
print("        2T = 四面体旋转群 A₄(12 元) 在 SU(2) 的二重覆盖(order 24)")
print("        坐落于实四元数范数1球面 ∂B̅(0,1) ⊂ ℍ → ℍ 内源: 真(几何同源)")
print("        → 若 24=|2T| 能与 S.A 实际谱缝挂接, 则双面真闭合")
print("        ⚠ 关口: |2T| 与 spectralGap8/‖S.A‖ 的挂接尚无推导 → 未闭合")

print("\n     候选③ 24 = 4! = |S₄| (对'3 空间轴 + 1 实部'的全置换)")
print("        作用于 1+3 分解; 涉及 ℍ 结构, 但 '为何选 4!' 无谱缝理由")
print("        → ℍ 内源: 弱(对称性候选, 非自然) → 未闭合")

# ---------------- 判别三: 两表达式唯一相切于 d=3 ----------------
print("\n" + "=" * 76)
print("[3] 判别三(指纹性质): 两式只在 d=3 相切(二重根)")
print("=" * 76)
print("     (d+1)²/(8d) = (d−1)/d  ⟺  (d+3)² = 0  ⟺  d = 3 (二重根)")
print("     即: 路径B 泛化式 在 d 轴上与路径A 仅在 d=3 的一点相切,")
print("     且切点处两式一阶导数也重合(二重根)。")
print("     → 这不是数值巧合, 而是 'd=3 被选中' 的真实结构指纹。")
print("     意义: 框架的 d=3 已由统一3定理 机器自证(闭环), 故该特征点对推进有利;")
print("           但这仅保证'两式在 d=3 一致', 不保证 24 的来源被填出。")

print("\n     [数值佐证: 两式随 d 演化, 差值最小恰在 d=3]")
sun = tangent_discriminant([2, 3, 4])
for d, A, B, diff in sun:
    flag = "  ← 相切点(d=3)" if diff < 1e-9 else ""
    print(f"       d={d}:  A={A:.6f}  B={B:.6f}  |Δ|={diff:.3e}{flag}")

# ---------------- 结论 ----------------
print("\n" + "=" * 76)
print("结论 (v1.0)")
print("=" * 76)
print("""  一体两面 判定: 半成立(拆分):
    ① 真一体: 路径A 的 d=3 与 路径B 的 4=1+3 共享同一个虚部三维(同一枚币)。
       Maxwell 最概然速率/球壳/三相→两相 的 √(2/3) 均为此 (d−1)/d 结构。
    ② 未闭合: 16/24→2/3 中的 24, 若取证明技术的 8×3 → 非内源(一体两面不成立);
       若取 ℍ 内源候选 |2T|=24 或 4! ▶ 需再挂接 S.A 谱缝(未闭合)。
  最终判别钥匙 = 24 与虚部三维的谱同源性, 而非数值上的 16/24=2/3。

  诚实边界: 本脚本交付 ① 的严格核对 + ② 的三候选对置判别;
           未(也不声称)闭合 ② 的谱缝挂接。恒等≠结构证明。""")

# 断言防回归
assert abs(pathA(3) - 2 / 3) < 1e-12
assert abs(pathB - 2 / 3) < 1e-12
