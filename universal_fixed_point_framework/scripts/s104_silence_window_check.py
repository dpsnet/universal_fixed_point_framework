# S104 静默窗口比候选先证伪（2026-10-27）
# 候选：勾股族 tanh(n·ln2) = (2^{2n}−1)/(2^{2n}+1) 的分子/分母 = 静默窗口比
#   15/17（2 层）：15 = 16−1 = orbitCount（静默闭合——全态 16 减一——已 Lean 化）
#   255/257（4 层）：255 = 256−1 = 框架计数 256 减一（静默——S103 frame_count_256）
#   63/65（3 层）：63 = 64−1——64 = 2^6 = 4^3（64 态立方？）
#   65535/65537（8 层）：65535 = 65536−1 = 2^16−1——65536 = 16^4 = 256^2（窗口平方平方）
# 统一："(2^{2n}−1)/(2^{2n}+1)——计数结构 M 的静默闭合 (M−1)/(M+1)"

from math import tanh, log

print("=== 勾股族静默窗口比（M−1)/(M+1)——M = 2^{2n}） ===")
for n in range(1, 6):
    num = 2**(2*n) - 1
    den = 2**(2*n) + 1
    M = 2**(2*n)
    v = tanh(n * log(2))
    print(f"n={n}: tanh({n}·ln2) = {num}/{den} = {num/den:.10f}   M=2^{2*n}={M}")
    # 窗口结构
    if n == 1:
        print(f"   M=4——4 维？(Cl(1,3) 时空维数)——3-4-5 勾股")
    if n == 2:
        print(f"   M=16——全态窗口！15 = 16−1 = orbitCount（静默闭合）——8-15-17 勾股")
    if n == 3:
        print(f"   M=64——4³？——63-16-65 勾股")
    if n == 4:
        print(f"   M=256——框架计数（2^8=16²=Σchoose）——255 = 256−1——255-32-257 勾股")
    if n == 5:
        print(f"   M=1024——2^10——1023 = 1024−1")

print("\n=== 关键对应 ===")
print(f"2 层：15/17——15 = 16−1 = orbitCount（S19 已 Lean 化）——17 = 16+1")
print(f"4 层：255/257——255 = 256−1（S103 frame_count_256）——257 = 256+1")
print(f"8 层：65535/65537——65535 = 2^16−1 = 256²−1（窗口平方）——65537 = 256²+1")

print("\n=== 静默窗口比的谱流深度不变性 ===")
# 窗口 W = 2^{2n}——静默闭合 (W−1)/(W+1)——tanh 位置 n·ln2 = ln(W^{1/2})/ln... 
# 谱流深度对数：n·ln2 = (1/2)·ln(W)
for n in [1, 2, 3, 4, 8]:
    W = 2**(2*n)
    d = n * log(2)
    half_lnW = 0.5 * log(W)
    print(f"n={n}: 谱流深度 n·ln2 = {d:.6f}  ½ln(W) = {half_lnW:.6f}  一致 = {abs(d - half_lnW) < 1e-12}")

print("\n=== 与 S101 连接（卷积系数恒等） ===")
# 256·0.5^8/8! = 1/8!（S101 conv_coeff_anchor_8 的计数来源）
# 255/257 = tanh(4·ln2)——255 = 256−1——静默闭合
from math import factorial
print(f"0.5^8·256/8! = {256 * 0.5**8 / factorial(8):.10f} = 1/8!? {abs(256 * 0.5**8 / factorial(8) - 1/factorial(8)) < 1e-15}")
print(f"255/256 = {(255/256):.6f}（静默闭合比率——轨道 15/16 的窗口平方版）")
print(f"15/16 = {(15/16):.6f}（orbitCount 静默闭合率——S19）")
print(f"两率一致? {abs(255/256 - 15/16) < 1e-9}  {255/256} vs {15/16}")
