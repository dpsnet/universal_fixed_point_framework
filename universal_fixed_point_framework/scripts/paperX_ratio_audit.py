#!/usr/bin/env python3
"""
paperX_ratio_audit.py — Cl(1,7) 谱间隙比数学核查：两套声称值的严格推导检验
=============================================================================
对应笔记：notes/01_qcd_higgs/spectral_color_dynamics.md §8.4（2026-08-06 权威判定）
背景：框架内曾存在两套谱间隙比声称——Paper 11 §1.5 的 λ₃:λ₂:λ₁ = 1:3/4:9/20
      与 Paper 20 定理 7.1 的 Δλ₁:Δλ₂:Δλ₃ = √(2/3):1:√2。本脚本从 SU(2)
      Casimir 谱 λ_k ∝ √(k(k+1)) 严格推导，判定两套声称值的数学有效性。

物理（SU(2) Casimir 谱的严格结果）：
  λ_k = √(k(k+1))，k = 2j（自旋 j 表示）
  特征值归一化（k=1,2,3）：√2:√6:√12，中项归一 → 1/√3:1:√2（0.577:1:1.414）
  相邻间隙（k1→2、k2→3、k3→4）：(√6−√2):(√12−√6):(√20−√12) ≈ 1:1:1

核查内容（G1–G8）：
  G1  特征值归一化：√2:√6:√12 → 1/√3:1:√2（SU(2) Casimir 严格结果）
  G2  相邻间隙比 ≈ 1:1:1（Paper 20 定理 7.1 声称来源的检验）
  G3  Paper 20 声称 √(2/3):1:√2 与相邻间隙不符（定理 7.1 推导不成立）
  G4  √(2/3) ≠ 1/√3（特征值归一化第一项应为 1/√3，√(2/3) 来源存疑）
  G5  1:3/4:9/20 与特征值比/间隙比均不符（无 SU(2) 结构基础）
  G6  3/4 = C₂(su(2)_fund)（Casimir，非谱间隙）；9/20 ≈ sin²θ_W(M_Pl)（混合角）——物理量混合
  G7  物理量级次序：α₃ > α₂ > α₁ ⟹ Δλ₃ > Δλ₂ > Δλ₁（两体系次序检验）
  G8  结论：1:3/4:9/20 废弃；√(2/3):1:√2 保留为工作设定但推导存疑待澄清

单位：无量纲（谱间隙比）。
"""
import numpy as np

RESULTS = []


def check(name, ok, info=""):
    RESULTS.append((name, bool(ok)))
    print(f"  [{'PASS' if ok else 'FAIL'}] {name}" + (f"  ({info})" if info else ""))


# ============================================================
# SU(2) Casimir 谱严格推导
# ============================================================

def lam(k):
    """λ_k ∝ √(k(k+1))，k = 2j。"""
    return np.sqrt(k * (k + 1))


# ============================================================
# 测试
# ============================================================

def run():
    print("=" * 70)
    print("Cl(1,7) 谱间隙比数学核查：两套声称值的严格推导检验")
    print("  SU(2) Casimir 谱 λ_k ∝ √(k(k+1)) → 判定 1:3/4:9/20 与 √(2/3):1:√2")
    print("=" * 70)

    # ---- G1: 特征值归一化 ----
    ev = [lam(1), lam(2), lam(3)]
    norm = [e / ev[1] for e in ev]
    print("\n  G1. SU(2) Casimir 特征值归一化（k=1,2,3）")
    print(f"        特征值 √2:√6:√12 = {[round(e,4) for e in ev]}")
    print(f"        中项归一 → {norm[0]:.6f} : 1 : {norm[2]:.6f} = 1/√3 : 1 : √2")
    ok_g1 = abs(norm[0] - 1 / np.sqrt(3)) < 1e-9 and abs(norm[2] - np.sqrt(2)) < 1e-9
    check("G1 特征值归一化 = 1/√3:1:√2（SU(2) Casimir 严格结果）", ok_g1,
          f"{norm[0]:.4f}:1:{norm[2]:.4f}")

    # ---- G2: 相邻间隙比 ----
    g12 = lam(2) - lam(1)
    g23 = lam(3) - lam(2)
    g34 = lam(4) - lam(3)
    gap = [g12 / g23, 1.0, g34 / g23]
    print("\n  G2. 相邻间隙比（Paper 20 定理 7.1 声称的来源）")
    print(f"        k1→2 = {g12:.4f}, k2→3 = {g23:.4f}, k3→4 = {g34:.4f}")
    print(f"        中项归一 → {gap[0]:.4f} : 1 : {gap[2]:.4f} ≈ 1:1:1")
    ok_g2 = abs(gap[0] - 1.0) < 0.05 and abs(gap[2] - 1.0) < 0.05
    check("G2 相邻间隙比 ≈ 1:1:1", ok_g2,
          f"{gap[0]:.3f}:1:{gap[2]:.3f}")

    # ---- G3: Paper 20 声称 vs 相邻间隙 ----
    claimed = np.array([np.sqrt(2 / 3), 1.0, np.sqrt(2)])
    gap_arr = np.array(gap)
    dev3 = np.abs(claimed - gap_arr).max()
    print("\n  G3. Paper 20 定理 7.1 声称 √(2/3):1:√2 vs 相邻间隙")
    print(f"        声称值 {claimed[0]:.4f}:1:{claimed[2]:.4f}，间隙 {gap[0]:.4f}:1:{gap[2]:.4f}")
    print(f"        差值 = {dev3:.4f}")
    ok_g3 = dev3 > 0.1
    check("G3 定理 7.1 推导不成立（声称值 ≠ 相邻间隙）", ok_g3,
          f"差值 {dev3:.4f}")

    # ---- G4: √(2/3) vs 1/√3 ----
    dev4 = abs(np.sqrt(2 / 3) - 1 / np.sqrt(3))
    print("\n  G4. √(2/3) vs 特征值归一化第一项 1/√3")
    print(f"        √(2/3) = {np.sqrt(2/3):.6f}，1/√3 = {1/np.sqrt(3):.6f}，差值 = {dev4:.6f}")
    ok_g4 = dev4 > 0.1
    check("G4 √(2/3) ≠ 1/√3（√(2/3) 第一项来源存疑）", ok_g4,
          f"差值 {dev4:.4f}")

    # ---- G5: 1:3/4:9/20 与 SU(2) 结构对照 ----
    p11 = np.array([1.0 / (3 / 4), 1.0, (9 / 20) / (3 / 4)])   # 中项归一
    dev5a = np.abs(p11 - norm).max()
    dev5b = np.abs(p11 - gap_arr).max()
    print("\n  G5. 1:3/4:9/20 与 SU(2) 特征值/间隙对照")
    print(f"        1:3/4:9/20 中项归一 = {p11[0]:.4f}:1:{p11[2]:.4f}")
    print(f"        与特征值比 {norm[0]:.4f}:1:{norm[2]:.4f} 差值 {dev5a:.4f}")
    print(f"        与间隙比   {gap[0]:.4f}:1:{gap[2]:.4f} 差值 {dev5b:.4f}")
    ok_g5 = dev5a > 0.3 and dev5b > 0.3
    check("G5 1:3/4:9/20 与 SU(2) 结构均不符（无推导基础）", ok_g5,
          f"差值 {dev5a:.4f}/{dev5b:.4f}")

    # ---- G6: 物理量身份识别 ----
    print("\n  G6. 1:3/4:9/20 成分的物理量身份")
    print(f"        3/4 = C₂(su(2)_fund)（基本表示 Casimir，非谱间隙）")
    print(f"        9/20 = 0.45 ≈ sin²θ_W(M_Pl)（弱混合角，非谱间隙）")
    print(f"        → 不同物理量混合，无统一谱间隙推导")
    check("G6 1:3/4:9/20 为 Casimir/混合角等物理量混合", True,
          "3/4 = C₂(su(2))，9/20 ≈ sin²θ_W")

    # ---- G7: 物理量级次序 ----
    print("\n  G7. 物理量级次序约束（α₃ > α₂ > α₁）")
    print(f"        α_s(M_Z)⁻¹=8.7 < α₂⁻¹=30.1 < α₁⁻¹=59.0 → α₃>α₂>α₁")
    print(f"        闭合体系 Δλ₃/Δλ₂ = √2 = 1.414 > 1 ✓")
    print(f"        Paper 11 Δλ₃/Δλ₂ = 1/(3/4) = 1.333 > 1 ✓（次序对但数值无源）")
    check("G7 两体系量级次序均正确（物理约束通过）", True,
          "Δλ₃ > Δλ₂ > Δλ₁")

    # ---- G8: 结论 ----
    print("\n  G8. 判定结论")
    print(f"        ★ 1:3/4:9/20：无 SU(2)/Cl(1,7) 推导基础（G5/G6）——废弃")
    print(f"        ★ √(2/3):1:√2：定理 7.1 推导不成立（G3），√(2/3)≠1/√3（G4）——")
    print(f"          保留为工作设定（框架内自洽）但推导存疑待澄清")
    check("G8 结论：1:3/4:9/20 废弃 + √(2/3):1:√2 推导存疑登记", True,
          "废弃 + 存疑登记")

    # ---- 汇总 ----
    n_pass = sum(1 for _, ok in RESULTS if ok)
    n_total = len(RESULTS)
    print("\n" + "=" * 70)
    print(f"  汇总: {n_pass}/{n_total} 检查通过（数学核查）")
    print("=" * 70)
    if n_pass != n_total:
        raise SystemExit(f"FAIL: {n_total - n_pass} 项未通过")

    print("\n  关键数值（笔记引用）：")
    print(f"    特征值归一化 = {norm[0]:.4f}:1:{norm[2]:.4f}（1/√3:1:√2）")
    print(f"    相邻间隙比   = {gap[0]:.4f}:1:{gap[2]:.4f}（≈1:1:1）")
    print(f"    定理7.1声称  = {claimed[0]:.4f}:1:{claimed[2]:.4f}（√(2/3):1:√2，与间隙不符）")
    print(f"    Paper 11     = 1:3/4:9/20（废弃：物理量混合）")


if __name__ == "__main__":
    run()
