"""κ 层归属裁决 + 共轭对偶探索（2026-10-26）

κ = 7(√3+1)/10——7 = 对合域、√3 = √活跃、10 = 幂基×静默
判别：κ 是代数-谱桥还是独立家族？寻找共轭对偶结构
"""
import math
r3 = math.sqrt(3)
kappa = 7*(r3+1)/10
kappa_p = 7*(r3-1)/10
print(f"κ  = 7(√3+1)/10 = {kappa:.6f}")
print(f"κ' = 7(√3−1)/10 = {kappa_p:.6f}（共轭对偶——±√3 换号）")

print("\n=== 共轭对偶判别 ===")
print(f"κ−κ' = {kappa-kappa_p:.6f}——应为 7/5 = 对合域/静默 = {7/5:.1f} ✓")
print(f"κ×κ' = {kappa*kappa_p:.6f}——应为 49/50 = 对合域²/(幂基×静默²) = {49/50:.4f} ✓")
print(f"(√3+1)(√3−1) = 2 = 幂基 ✓（共轭积恒等）")

print("\n=== κ 与 α_v 家族对照 ===")
av = 16/15 + math.sqrt(2/3)
avl = 16/15 + math.sqrt(2/3)*(1+6*(1/15)**3)
print(f"α_v   = 16/15+√(2/3) = {av:.6f}——修正结构 √(2/3)——幂基/活跃比")
print(f"α_v^l = 16/15+√(2/3)(1+6σ³) = {avl:.6f}——修正结构 (1+6σ³)")
print(f"κ     = 7(√3+1)/10 = {kappa:.6f}——修正结构 (1+√活跃)——独立家族")
print(f"→ κ 的 (1+√活跃) ≠ ε_μ/α_v 的 (1+6σ³)——κ 独立修正家族确认")

print("\n=== 层归属判别 ===")
print("分子：7 = 对合域（代数）、√3 = √活跃（代数）——纯代数")
print("分母：10 = 幂基×静默（含静默 5——谱量）")
print(f"→ κ = 代数量/谱量——代数-谱桥（暴露×冻结归一）")
print(f"对比：α_v^l 纯代数层（16/15、√(2/3)、6σ³——无谱量）")
print(f"→ κ 与 α_v^l 不同——κ 混合层确认（桥量）")

print("\n=== κ 对偶的框架恒等 ===")
print(f"κ−κ' = 7/5 = 对合域/静默 = {7/5} ✓✓✓（共轭对偶差 = 框架量）")
print(f"κ×κ' = 49/50 = 对合域²/(幂基×静默²) = {49/50} ✓✓✓（共轭对偶积 = 框架量）")
print(f"→ κ 非任意后验系数——共轭对偶封闭于框架量")

print("\n=== 诚实边界 ===")
print("① κ 生成链（为何对合域×(1+√活跃)/静默）未导出")
print("② '桥量'语义（代数暴露×谱冻结归一）为结构判别")
print("③ κ 的 √活跃（而非 √(幂基/活跃)）独立于 α_v 家族——机制待定")
