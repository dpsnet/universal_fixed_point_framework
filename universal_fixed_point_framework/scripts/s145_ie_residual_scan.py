# -*- coding: utf-8 -*-
"""S145 I_e 残余下一阶修正形态扫描（机制层探索——先证伪）
E_e(组装) = E_τ^D + I_e vs E_e(观测)——残余 δ_obs = +1.891e-9（6.43σ）
探索：δ_obs 是否落在整洁框架形态（σ 幂 × e 幂 × 框架有理数）
"""
import numpy as np

σ = 1/15
e = np.exp(1)
ln15 = np.log(15)

# PDG 2024 精确值
m_e = 0.51099895069   # MeV
M_Pl = 1.220890e22    # MeV
σ_rel_e = 2.94e-10    # S129 勘误后（PDG 括号 (15) = ±1.5e-10 MeV）

# 框架精确值
α_vp = 16/15 + np.sqrt(2/3)*(1 + 6*σ**3)
ε_μ = 144 * np.exp(-16) * (1 + 6*σ**3)
E_τD = 16*ln15 + (7/10)*np.log(16/15) - 8*ε_μ - (σ**5 - np.exp(-16)) - 2*σ**8*(1+σ)
I_e = 3*e - σ**3*(1 + α_vp)

E_e_obs = np.log(M_Pl/m_e)
E_e_asm = E_τD + I_e
δ_obs = E_e_asm - E_e_obs

print(f"E_e(obs)      = {E_e_obs:.12f}")
print(f"E_τ^D         = {E_τD:.12f}")
print(f"I_e           = {I_e:.12f}")
print(f"E_e(组装)     = {E_e_asm:.12f}")
print(f"δ_obs         = {δ_obs:+.12e}")
print(f"σ_score(δ)    = {δ_obs/σ_rel_e:.3f}σ  (σ_rel(e) = {σ_rel_e:.2e})")

print("\n=== 形态空间扫描（δ_obs = 系数 × 基底） ===")
bases = {
    "e^-16": np.exp(-16), "e^-17": np.exp(-17), "e^-18": np.exp(-18),
    "e^-19": np.exp(-19), "e^-20": np.exp(-20), "e^-21": np.exp(-21),
    "σ^8": σ**8, "σ^9": σ**9, "σ^10": σ**10,
    "e^-16·σ": np.exp(-16)*σ, "e^-16·σ²": np.exp(-16)*σ**2,
    "ε_μ²": ε_μ**2, "σ^5·e^-16": σ**5*np.exp(-16),
}
print(f"{'基底':12s} {'基底值':14s} {'δ/基底':12s} {'接近有理?':20s}")
for k, v in bases.items():
    ratio = δ_obs/v
    note = ""
    for num in [1, 27/80, 1/2, 2/3, 3/4, 27/40, 9/16, 3/8, 1/4, 27/100, 0.3375, 27/75, 2/75]:
        if abs(ratio - num)/num < 0.005:
            note = f"≈ {num:.6f}"
            break
    print(f"{k:12s} {v:14.6e} {ratio:12.6f} {note:20s}")

print("\n=== 主候选：δ = 27/80 · e^-19（27=3³=活跃³、80=16·5=全态×静默、19=16+3=全态+活跃） ===")
δ_c = (27/80) * np.exp(-19)
print(f"27/80·e^-19    = {δ_c:.12e}")
print(f"δ_obs - δ_c    = {δ_obs-δ_c:+.3e}")
print(f"相对残差       = {(δ_obs-δ_c)/δ_obs:.3e}")
δ_after = δ_obs - δ_c
print(f"修正后残余     = {δ_after:+.3e}")
print(f"修正后σ_score  = {δ_after/σ_rel_e:.3f}σ")

print("\n=== 对照候选（形态空间内其他整洁组合） ===")
cands = {
    "27/80·e^-19": (27/80)*np.exp(-19),
    "27/80·e^-20": (27/80)*np.exp(-20),
    "3³/(2⁴·5)·e^-19": (27/80)*np.exp(-19),
    "1·e^-19": np.exp(-19),
    "1/3·e^-18": np.exp(-18)/3,
    "2·σ⁸·e⁻¹": 2*σ**8/e,
    "σ⁹·1000": σ**9*1000,
    "ε_μ·e^-4": ε_μ*np.exp(-4),
    "σ⁸·e^-1·12": 12*σ**8/e,
}
for k, v in cands.items():
    rel = abs(δ_obs-v)/abs(δ_obs)
    print(f"{k:20s} = {v:.6e}   相对差 = {rel:.4f}   σ(残余后) = {(δ_obs-v)/σ_rel_e:+.2f}σ")

print("\n=== 19 的框架分解核对 ===")
print(f"16+3 = {16+3}（全态+活跃代）  16·(7/10)+3 = {16*7/10+3}")
print(f"19 = 16+3 ✓   vs   19 = 2⁴+3 = 全态+N_gen")
print(f"27/80 化简：{27}/{80} = 3³/(2⁴·5) = 活跃³/(全态×静默)")
print(f"2/75 对照（S10）：{2}/{75} = 幂基³/(N_gen·10²)——同族结构")
