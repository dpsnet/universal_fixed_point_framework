# S105 静默窗口勾股族先证伪（2026-10-27）
# 候选：勾股三元组 (2^{2n}−1, 2^{n+1}, 2^{2n}+1)——(M−1, 2√M, M+1)——M 偶平方
#   n=1: 3-4-5     （M=4——Cl(1,3) 时空维数平方）
#   n=2: 15-8-17   （M=16——全态窗口——15=orbitCount、8=K_max、17=窗口+1）
#   n=3: 63-16-65  （M=64——中间边 16 = 全态！）
#   n=4: 255-32-257（M=256——框架计数——255=256−1 静默）
#   n=8: 65535-512-65537（M=65536=16⁴）
# 恒等式：(M−1)² + (2√M)² = (M+1)²——M = (2^n)² 时 √M = 2^n——中间边 2√M = 2^{n+1}

from math import sqrt, log, tanh

print("=== 静默窗口勾股族 (2^{2n}−1, 2^{n+1}, 2^{2n}+1) ===")
for n in range(1, 9):
    a = 2**(2*n) - 1
    b = 2**(n+1)
    c = 2**(2*n) + 1
    ok = a*a + b*b == c*c
    M = 2**(2*n)
    print(f"n={n}: {a}-{b}-{c}  M={M}  ({a}²+{b}²={c}²? {ok})  √M={2**n} 中间边=2√M={b}")
    if not ok:
        raise SystemExit("勾股恒等式失败！")

print("\n=== 框架常数对应 ===")
print(f"n=2（2 层翻倍）：15-8-17——15 = orbitCount（静默闭合）· 8 = K_max · 17 = 16+1（窗口加一）")
print(f"n=3（3 层翻倍）：63-16-65——中间边 16 = 全态窗口——63 = 64−1（静默）——65 = 64+1（开放）")
print(f"n=4（4 层翻倍）：255-32-257——255 = 256−1（框架计数静默）——257 = 256+1")
print(f"n=8（8 层翻倍）：65535-512-65537——65535 = 16⁴−1——中间边 512 = 2⁹")

print("\n=== 恒等式一般化验证（任意平方 M：(M−1)² + (2√M)² = (M+1)²） ===")
for M in [4, 16, 64, 256, 65536]:
    r = int(sqrt(M))
    assert r*r == M
    ok = (M-1)**2 + (2*r)**2 == (M+1)**2
    print(f"M={M}: ({M}−1)² + (2·{r})² = ({M}+1)²? {ok}")

print("\n=== 谱流连接（tanh 族——速度 = 静默窗口比——S104） ===")
for n in [2, 3, 4]:
    v = tanh(n * log(2))
    ratio = (2**(2*n) - 1) / (2**(2*n) + 1)
    print(f"n={n}: tanh({n}·ln2) = {v:.10f} = ({2**(2*n)}−1)/({2**(2*n)}+1)? {abs(v - ratio) < 1e-12}")
    # γ = cosh——偏转代价系数
    from math import cosh
    g = cosh(n * log(2))
    print(f"   cosh({n}·ln2) = {g:.10f} = ({2**(2*n)}+1)/(2·{2**n})? {abs(g - (2**(2*n)+1)/(2*2**n)) < 1e-12}——γ 的分母 = 中间边/2")
