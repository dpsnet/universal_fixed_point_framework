import itertools

print("=== S352 守恒配对内双域恒等 ===\n")

# 配对（S334 唯一守恒配对）
pairs = [("配对1", 6, 3, 5, 8, 11), ("配对2", 4, 5, 8, 7, 12)]

print("[1] 配对内双域恒等检验")
print("    配对数    系数和    幂次和    守恒值    双域一致?")
for name, c1, p1, c2, p2, cons in pairs:
    cs = c1 + c2
    ps = p1 + p2
    ok = (cs == cons) and (ps == cons)
    print(f"    {name}    {c1}+{c2}={cs}    {p1}+{p2}={ps}    {cons}    {ok}")

print("\n[2] ★ 双域恒等成立：配对 1 幂次和 3+8 = 系数和 6+5 = 11；")
print("    配对 2 幂次和 5+7 = 系数和 4+8 = 12")
print("    ——S334 '幂和=系数和'是配对内恒等的总推论——更强形式成立")

print("\n[3] 幂次集 {3,5,7,8} 的守恒划分唯一性")
powers = [3, 5, 7, 8]
# 两两划分（4 选 2 = 6 种对，每对互补）
combs = list(itertools.combinations(powers, 2))
print("    所有对及和：")
hits = []
for a, b in combs:
    c = list(set(powers) - {a, b})[0]
    d = list(set(powers) - {a, b})[1]
    s1 = a + b
    s2 = c + d
    tag = ""
    if (s1 == 11 and s2 == 12) or (s1 == 12 and s2 == 11):
        tag = "  ★ 守恒划分"
        hits.append(((a, b), (c, d)))
    print(f"      ({a},{b})={s1}  |  ({c},{d})={s2}{tag}")
print(f"    ★ 唯一守恒划分：{hits[0]}——3+8=11、5+7=12")

print("\n[4] 其他划分为什么不行")
for a, b in combs:
    c = list(set(powers) - {a, b})[0]
    d = list(set(powers) - {a, b})[1]
    s1, s2 = a + b, c + d
    if (s1, s2) != (11, 12) and (s1, s2) != (12, 11):
        print(f"      ({a},{b})={s1} vs ({c},{d})={s2}——非 11/12 守恒对")

