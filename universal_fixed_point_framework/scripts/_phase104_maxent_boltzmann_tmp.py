# -*- coding: utf-8 -*-
"""Phase 104r: 能量约束 MaxEnt —— 玻尔兹曼静默分布（深化 104q 的均匀公设）
问题：104q 的 1/8 来自"均匀分配"公设——需机制论证：为什么能量注入后 Balmer 连续区获 1/8
深化：能量约束 MaxEnt——注入能量 ΔE 下静默级分布为玻尔兹曼 P_k ∝ e^{−β·E_k}
  静默级线性谱：E_k = k·ΔE_s（k=1..k_max=8——等间距静默级）
  约束：平均注入能量 Ē = ΔE_inj/N_级（守恒——均匀平均）
  解：β 由 Ē = Σ k·ΔE_s·P_k 自洽——P_k = e^{−βkΔE_s}/Z
目标：检验能量约束解出的"Balmer 连续区份额"是否 ≈ 1/8（5.86% vs 5.8%）
      以及"为什么 1/8"的机制（温度→β→分布形状）
另：温度-辐射难度闭合——ΔT/T 与静默分布变化的关系
"""
import math

k_max = 8
eta_miss = 0.469
obs = 0.058

print('=== Phase 104r: 能量约束 MaxEnt（玻尔兹曼静默分布）===')
print('η_miss=%.1f%%、k_max=%d、观测增强=%.1f%%' % (eta_miss*100, k_max, obs*100))
print()

# ① 均匀极限（104q——β→0）
print('① 均匀极限（β→0）：P_k = 1/8——连续区份额 = 1/8 = %.2f%%（104q 已验——偏差 1.1%%）' % (100/8))
print()

# ② 能量约束 MaxEnt
# 静默级能量 E_k = k·ΔE_s——设 ΔE_s 为静默级间距（框架量）
# 注入总能量 ΔE_tot = η_miss·E_line_ref（线系参考能量）
# 每级平均注入（守恒）：Ē = ΔE_tot/k_max——但各级实际占据 P_k
# 能量约束：Σ P_k·(k·ΔE_s) = Ē——β 自洽
print('② 能量约束 MaxEnt（玻尔兹曼）：')
print('   P_k = e^{−β·k·ΔE_s}/Z——约束 ΣP_k·k·ΔE_s = Ē（守恒）')
print('   ——若 Ē = ΔE_s·(k_max+1)/2（均匀平均=4.5 级），β=0（均匀）')
print('   ——若注入偏集中（Ē 高），β<0（向高静默级偏）——若偏散（Ē 低），β>0')
print()

# ③ 温度-辐射难度闭合：注入能量 → 系统温度变化 → 静默分布形状
# 线能量注入连续区：ΔE/E_cont = η_miss × (E_line/E_cont)
# E_line/E_cont：Balmer 线区能量占连续谱比（观测/框架）
print('③ 温度-辐射难度闭合（能量守恒 → 温升 → 静默分布）：')
# 情形：线能量全部热化入连续区热库
for ratio_line_cont in [0.1, 0.15, 0.2, 0.3]:
    dE_E = eta_miss * ratio_line_cont
    dT_T = dE_E          # 单温度近似：ΔE/E ≈ ΔT/T（黑体能量 ∝ T⁴ 但此处热库近似）
    # 静默分布：玻尔兹曼 e^{−E/kT}——T 升 → 高能占据升
    # 辐射难度 D ∝ ⟨静默层级⟩ 或 逃逸概率 ∝ e^{−E_gap/kT}
    print('   E_line/E_cont=%.2f：ΔE/E_cont = %.1f%% → ΔT/T ≈ %.1f%%' % (ratio_line_cont, dE_E*100, dT_T*100))
print()

# ④ 关键深化：为什么"1/8"——静默级能量与注入能量的几何
# 若静默级能量 ΔE_s = 1 单位——注入能量按级分布——Balmer 连续区=第 1 级（最低级=最易辐射）
# 注入能量 ΔE_tot 中"能落到第 1 级（连续区）"的份额
# 玻尔兹曼占据 P_1 = e^{−βΔE_s}/Z——β 由总注入定
print('④ 机制深挖：注入能量的静默级着陆（Balmer 连续区 = 第 1 静默级——最低辐射难度）')
# 能量守恒：ΔE_tot 注入——先填充最低级（最易辐射通道优先）——填满后溢到上级
# "级联填充"：第 1 级容量 = 1 份额——注入 ≤ 容量 → 全在 1 级；注入 > 容量 → 溢出
# 线缺失能量 ΔE_tot 与第 1 级容量比
# 第 1 级容量 = 连续区本底能量份额（连续谱承载量）
for cap1 in [0.3, 0.5, 0.7, 1.0]:
    # 注入相对第 1 级容量
    inj = eta_miss * 0.15   # 线能量 15% 转连续区
    frac_in_1 = min(1.0, inj/cap1)
    print('   第 1 级容量=%.1f 份额：注入 %.1f%% → 落 1 级 %.0f%%（增强直接=注入×落 1 级）' %
          (cap1, inj*100, frac_in_1*100))
print()

print('=== 结论（诚实）===')
print('1. 能量约束 MaxEnt（β≠0）给非均匀分布——连续区份额 ≠ 1/8 一般情形')
print('2. "为什么 1/8"的两种候选机制：')
print('   A. 级联填充（低静默级优先）：若注入 ≤ 第 1 级容量——全部落连续区——增强=注入')
print('      ——观测 5.8%% = 注入 η_miss×E_line/E_cont = 0.469×0.124 → E_line/E_cont≈0.124？')
print('   B. 均匀/准均匀（MaxEnt 无偏好极限）：1/8——104q 已验')
print('3. 判别：E_line/E_cont（线区能量占比）与"第 1 级容量"的观测约束可区分 A/B')
print('4. 状态：104q（均匀 1/8 命中）+ 104r（机制深挖——能量守恒/级联/玻尔兹曼分布）')
print('   ——"为什么 1/8"机制论证推进——但 A/B 判别需线区能量占比观测约束（开放）')
