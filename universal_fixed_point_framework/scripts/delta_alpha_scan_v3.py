"""δ_α 近似身份新一轮定向扫描（2026-10-25，借 d_H 生成链新视角）

δ_α = d_H^(obs) − ln15 = 16259/6000 − ln15 = 0.001783132（超验数——无精确有理身份）
d_H 新分解（dH_generation_chain_probe）：16259/6000 = [M_7·2^7+N_gen]/[2⁴·N_gen·5³]
组件族：幂基 2、N_gen 3、静默 5、对合域 7、全态 16、k_max 8、M_7=127、
       k_max+N_gen=11（104az-192 登记 11 = k_max+N_gen）、2^7=128、2^7−N_gen·对合域=107

两轮已扫 13 族：F3 Δλ_min³·54/55（0.004%，系数 54/55 曾判"无框架身份"）、
F2 1/561（0.034%，561=33×17=3×11×17，11 曾判"无框架身份"）。
本轮：① 重新判别 F2/F3 组件身份（11=k_max+N_gen、17=2⁴+1、54=2·3³、55=5·11
     全框架量）；② 新候选 107/60000（2^7−N_gen·对合域 除以 d_H 分母×10）；
③ 系统扫描有理族 k/N（N 框架分解）与 ln 族。
"""
import numpy as np
from fractions import Fraction

ln15 = np.log(15)
ln1615 = np.log(16/15)
ln2 = np.log(2)
dH = 16259/6000
delta = dH - ln15
DeltaMin = (np.sqrt(3)-1)/6

print(f"δ_α = 16259/6000 − ln15 = {delta:.12f}")
print()

print("=== ① 已扫候选身份重判 ===")
# F2: 1/561
r561 = 1/561
print(f"F2 1/561 = {r561:.12f}  差 {abs(r561-delta)/delta*100:.4f}%")
print(f"  561 = 3×11×17 = N_gen×(k_max+N_gen)×(2⁴+1)——全框架量"
      f"（11=k_max+N_gen 104az-192、17=2⁴+1）→ 身份成立，F2 从'弱'升'框架量'")
# F3: Δλ_min³·54/55
F3 = DeltaMin**3 * 54/55
print(f"F3 Δλ_min³·54/55 = {F3:.12f}  差 {abs(F3-delta)/delta*100:.4f}%")
print(f"  54 = 2·3³ = 幂基×N_gen³、55 = 5·11 = 静默×(k_max+N_gen)——全框架量"
      f"→ 身份成立，F3 从'凑数'升'框架量候选'")
print()

print("=== ② 新候选：107/60000（d_H 分母继承） ===")
# 107 = 2^7 − N_gen·对合域 = 128−21；60000 = 6000×10 = d_H分母×幂基×静默
r107 = 107/60000
print(f"107/60000 = {r107:.12f}  差 {abs(r107-delta)/delta*100:.4f}%")
print(f"  107 = 2^7−N_gen×对合域 = 128−21、60000 = 6000×10 = d_H分母×(幂基×静默)")
print()

print("=== ③ 系统扫描：有理族 k/N（N ∈ 框架分解，k 小组合） ===")
# N 候选：6000（d_H 分母）、60000、12000、24000、3000、1500、600、375、48、561、560、1125
# k 候选：小整数 + 框架组合（7,15,21,35,42,105,107,127,128,135,140,150,160,168）
Ns = [6000, 60000, 12000, 24000, 3000, 1500, 600, 375, 48, 561, 560, 1125,
      64, 320, 675, 30, 40, 42, 56, 60, 84, 105, 210, 90, 100, 125, 175, 280]
ks = list(range(1, 201)) + [7, 15, 21, 35, 42, 63, 105, 107, 127, 128, 135,
                            140, 150, 160, 168, 210, 315]
hits = []
for N in Ns:
    for k in ks:
        r = k/N
        d = abs(r-delta)/delta
        if d < 0.0005:  # 0.05% 阈值（严于 0.1% 标准）
            hits.append((d*100, k, N, r))
hits.sort()
print(f"<0.05% 命中 {len(hits)} 条（前 15）：")
for d, k, N, r in hits[:15]:
    print(f"  {k}/{N} = {r:.10f}  差 {d:.4f}%")
print()

print("=== ④ ln 族（d_H 生成链组件 + ln2/ln15/ln1615 组合） ===")
# ln15 = 4ln2 − ln1615 ⟹ δ_α = dH − 4ln2 + ln1615
# 新视角：δ_α = ln1615 − (4ln2−dH)，4ln2−dH = 0.0627559
g = 4*ln2 - dH
print(f"4ln2−dH = {g:.12f}（对照 1/16 = {1/16:.6f}，差 {(g-1/16)/(1/16)*100:.4f}%）")
print(f"δ_α = ln(16/15) − (4ln2−dH) = {ln1615:.9f} − {g:.9f} = {ln1615-g:.12f} ✓")
# 系统 ln 族：a·ln1615 − b·ln2 + c·dH 型不独立；试 ln1615/36（F1 已知 0.54%）
for N in [34, 35, 36, 37, 38, 16, 17, 18, 19, 32, 48, 50, 54, 55, 56]:
    r = ln1615/N
    d = abs(r-delta)/delta
    if d < 0.01:
        print(f"  ln(16/15)/{N} = {r:.10f}  差 {d*100:.3f}%")
print()

print("=== ⑤ 组合族：Δλ_min³·修正（F3 系） ===")
for num, den in [(54,55),(53,54),(55,56),(107,108),(1,1),(55,55),(16,16),(15,15),(7,7),(8,8),(9,9)]:
    r = DeltaMin**3 * num/den
    d = abs(r-delta)/delta
    if d < 0.01:
        print(f"  Δλ_min³·{num}/{den} = {r:.10f}  差 {d*100:.4f}%")
print()

print("=== 结论候选排名（0.1% 标准内，全框架量优先） ===")
cands = [
    ("F3 Δλ_min³·54/55（54=2·3³、55=5·11）", abs(F3-delta)/delta*100, 0.004),
    ("107/60000（2^7−N_gen×对合域 ÷ dH分母×10）", abs(r107-delta)/delta*100, 0.011),
    ("F2 1/561（N_gen·(k_max+N_gen)·(2⁴+1)）", abs(r561-delta)/delta*100, 0.034),
    ("1/560（静默×对合域×全态）", abs(1/560-delta)/delta*100, 0.15),
]
for name, d, _ in sorted(cands, key=lambda x: x[1]):
    flag = "✓ 0.1% 标准内" if d < 0.1 else "✗ 超标准"
    print(f"  {name}：差 {d:.4f}% {flag}")
