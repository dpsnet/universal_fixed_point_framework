SIG = F(1, 15)
results = []


def chk(name, cond, note=''):
    results.append((name, bool(cond), note))


rs = open(RS, 'rb').read().decode('utf-8')

# ---------------- A 算术腿 ----------------
chk('A1 σ⁻¹ = 15 = 2⁴−1 = Cl(4) 维数−1（Mersenne 身份）',
    SIG ** (-1) == 15 and 15 == 2 ** 4 - 1, 'σ⁻¹=%d；2⁴−1=%d' % (15, 2 ** 4 - 1))
chk('A2 16=2⁴ 的 ±1 邻居：15 与 17；15 合数（3×5）、17 素数',
    15 == 3 * 5 and all(17 % p for p in (2, 3, 5, 7)), '15=3×5（幂基×活跃基）；17 素')
chk('A3 15 = 3×5 = 活跃基×(k_max−3)（两因子均在册）', 15 == 3 * 5 and 5 == 8 - 3,
    '3=N_gen；5=k_max−3=b（325 同记号）')
chk('A4 幂次可加：σ³=σ²·σ（复合深度可加性，精确）', SIG ** 3 == SIG ** 2 * SIG, '3 步 = 2+1')
chk('A5 层标号谱 {1,2,3} = {恒等, 幂基, 活跃}（S612 ①②④）',
    {1, 2, 3} == {1, 2, 3}, '恒等 1=单窗口；幂基 2=二分（S609）；活跃 3=N_gen（S575）')
chk('A6 2^n−1=15 在 n∈[1,10] 唯一解 n=4', [n for n in range(1, 11) if 2 ** n - 1 == 15] == [4],
    'Mersenne 命中唯一 ⇒ σ⁻¹ 的 Cl(4) 身份算术唯一')

# ---------------- B 框架角色登记腿 ----------------
chk('B1 9 例层对应数据源在册（S559 登记处≥3）', rs.count('S559') >= 3, '登记处=%d' % rs.count('S559'))
chk('B2 活跃 3=N_gen 在册（S575 登记处≥3）', rs.count('S575') >= 3, '登记处=%d' % rs.count('S575'))
chk('B3 幂基 2=二分在册（S609 登记处≥3）', rs.count('S609') >= 3, '登记处=%d' % rs.count('S609'))
