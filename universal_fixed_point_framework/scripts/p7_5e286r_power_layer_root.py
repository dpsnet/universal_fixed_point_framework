# ---------------- C 权重候选族审查 ----------------
chk('C1 候选族 {15,16,137} 中仅 15 具 2⁴−1 身份',
    (15 == 2 ** 4 - 1) and (16 != 2 ** 4 - 1) and all(137 != 2 ** n - 1 for n in range(1, 9)),
    '137 非 2^n±1 形（2⁷+9、2⁸−119）⇒ 与 Clifford 维数无算术纽带')
chk('C2 α_v′ 主项 16/15 = 16·σ（精确）；余量比 15/16 = σ⁻¹/2⁴（精确）',
    F(16, 15) == 16 * SIG and F(15, 16) == (SIG ** (-1)) / 16,
    '单步静默 = 冻结完备枚举余量比（S612③）')
chk('C3 样本=9：S559 九例幂次=层标号全一致（一致性强度高于 ⑦ 的 n=2）', rs.count('S559') >= 3,
    '九例一致为在册记录；本轮按登记引用，未逐例复算')
chk('C4 根源「为何每步权重恰为 σ（而非其他框架常数）」仍候选级', True,
    'S612 诚实边界维持：待范畴导出；C1–C2 只证族内最优，不证必然')
chk('C5 幂次可加性（A4）是复合语义的最小要求，非权重值的锁定', True,
    '任何权重 w 都满足 w³=w²·w ⇒ 可加性对权重值零判别力')

# ---------------- D 判定 ----------------
chk('D1 升级为「受限族内一致（样本=9）」；族={2⁴ 邻域框架常数}，σ 唯一具 2⁴−1 身份', True,
    '判别力=族内 Mersenne 唯一性（A6）+ 余量比身份（C2）')
chk('D2 不称机制闭合：可加性零判别力（C5），根源仍候选（C4）', True,
    '升格条件=范畴导出单步权重 或 权重值独立第二来源')
