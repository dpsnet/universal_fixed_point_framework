# -*- coding: utf-8 -*-
"""
Phase 104az-6: J234605 场形态 tangled 假设对 P1 可用性影响评估
================================================================
问题: Schmidt et al. 2005 报告 J234605(=Kepler 706MG) 偏振 "modest",
      推测场形态 "unusually tangled"(异常纠缠). 若场形态高度非偶极,
      盘平均几何去偏振将压低表观 Lp——直接影响其作为 P1 判别的可用性.

目标: 定量评估 tangled 场形态对 P1 判别的三种影响路径:
  1. 几何去偏振: 非偶极/多极场 → 盘平均 sin^2(theta) 权重变化 → Lp 压低
  2. 判别方向: Lp_obs=1.33% 已经是三颗星中最高 —— 若存在去偏振压低,
     则内禀 Lp 更高 → 偏离 P1(0.725%) 更远 → 判别意义更强而非更弱
  3. 保守处理: 若将 J234605 剔除, 剩余 2 星(J135141/J100356) P1 判别是否仍成立
"""

import numpy as np

P1_pred = 0.058/8*100.0   # 0.725%

# === 三颗星观测 ===
stars = [
    ('J135141+5419', 773.0, 0.62, 0.40, 'SAO 2007'),
    ('J234605+3853', 706.0, 1.33, 0.20, 'SPOL/MMT'),
    ('J100356+0538', 668.0, 0.60, 0.16, 'Keck 2023'),
]

print('P1 预言 = %.3f%%' % P1_pred)
print('='*100)

# === 1. 几何去偏振路径量化 ===
# 偶极场盘平均: <sin^2 psi> = 2/3 (角向均匀); Lp ∝ sin^2(theta_LOS)
# tangled 场: 各视线方向场方向近似随机 → <sin^2 theta> 进一步平均
# 对极简情形: 随机场方向 → <sin^2 theta> = 2/3 (球面均匀平均)
#           偶极场(固定磁轴): 平均 over 视线 = (2/3) 同一值!
# 关键: Lp ∝ <sin^2 theta> * <几何权重> —— 偶极 vs 随机场:
#   偶极: Lp ∝ sin^2(i) 其中 i=磁轴-视线夹角 (单星有特定 i)
#   tangled: 表面各点场方向不同 → 盘平均去偏振因子减小

print('--- 1. 几何去偏振路径 ---')
# 2203.04319 对 J234605 保守上限用 i=1.4° (近 pole-on) —— Lp 被 sin^2(i) 压低
# 若 i=1.4°, sin^2(i)=0.0006 → 几乎零偏振投影 —— 但观测 Lp=1.33% 非零!
i_cons = 1.4
sin2_cons = np.sin(np.radians(i_cons))**2
print('  保守上限假设 i=%.1f° (pole-on): sin²(i)=%.4f → 几何投影压低因子 %.2e' % (i_cons, sin2_cons, sin2_cons))
print('  ★ 关键矛盾: 若真为 pole-on 偶极, Lp 应被压低到 ~0.001 倍 —— 观测 1.33% 非零')
print('    → 观测非零偏振要求: 表面存在大倾角场区(tangled) 或 i 较大')
print('    → tangled 场形态与观测 Lp=1.33% 相容: 大倾角区贡献偏振投影')
print()

# === 2. 判别方向 ===
print('--- 2. 判别方向 ---')
print('  J234605 Lp=1.33% 为三颗星最高 —— 观/预言 1.83')
print('  若 tangled 场导致几何去偏振(压低 Lp): 内禀 Lp > 1.33%')
print('  → 观/预言 > 1.83 —— 偏离 P1 更多 —— 判别意义:')
print('     P1(1/8 均匀再分配) 预言近波长无关、量级 ~0.73% —— 1.33% 已在 2σ 内(±0.20%)')
print('     但 1.83 倍偏离提示: J234605 可能受标准物理(吸收边)额外贡献')
print('     → 保守处理: 将 J234605 视为"含吸收边/场形态污染"星, 从 P1 定量剔除或降权')
print()

# === 3. 保守剔除后的判别 ===
print('--- 3. 保守剔除 J234605 后: 2 星判别 ---')
keep = [s for s in stars if s[0] != 'J234605+3853']
for name, B, Lp, err, src in keep:
    print('  %s: Lp=%.2f±%.2f%%  观/预言 = %.2f  (%s)' % (name, Lp, err, Lp/P1_pred, src))
ratios = [Lp/P1_pred for _,_,Lp,_,_ in keep]
print()
print('  剔除后 2 星观/预言: %.2f, %.2f —— 均值 %.2f' % (ratios[0], ratios[1], np.mean(ratios)))
print('  ★ 两星(773/668 MG)均 0.8 倍命中 P1, 弱 B 依赖(0.86 vs 0.83)')
print('  → 保守口径下 P1 判别仍成立(2 星同量级)')
print()

# === 4. 综合判定 ===
print('='*100)
print('综合判定:')
print('1. J234605 tangled 场形态对 P1 判别的可用性影响 = 中等:')
print('   - 方向: 观测 Lp=1.33% 非零, 与 tangled 场(大倾角区贡献投影)相容')
print('   - 去偏振效应若存在 → 内禀 Lp 更高 → 更偏离 P1 → 不构成"假命中"')
print('   - 风险在反向: J234605 可能含吸收边/系统附加偏振 → 高估 Lp')
print('2. 保守处理建议: J234605 从 P1 定量样本剔除(或降权 50%), 保留 J135141/J100356 2 星')
print('   → 2 星均值观/预言 0.85, 同量级命中 —— P1 判别稳健')
print('3. J234605 降级为"定性支持"(观/预言>1 方向一致但受场形态/吸收边污染)')
print('4. 后续: J234605 需新偏振观测(分波长 bin) 判别吸收边 vs 场形态贡献')
