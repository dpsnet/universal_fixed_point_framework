# 数据
seq = [('Hε', 7, 48.01), ('Hδ', 6, 65.35), ('Hγ', 5, 94.11),
       ('Hβ', 4, 147.05), ('Hα', 3, 261.41)]

print('① 相邻比值检验（B_th(n)/B_th(n-1) vs (n/(n-1))²）：')
print('   ┌────────┬──────┬─────────┬────────────┬────────────┬─────────┐')
print('   │ 线对    │ n→n-1 │ 观测比值  │ (n/(n-1))²  │ 偏差       │ 命中    │')
print('   ├────────┼──────┼─────────┼────────────┼────────────┼─────────┤')
for i in range(len(seq)-1):
    name_h, n_h, b_h = seq[i]
    name_l, n_l, b_l = seq[i+1]
    ratio = b_l / b_h
    pred = (n_h / n_l) ** 2
    dev = (ratio - pred) / pred * 100
    hit = '★ 精确' if abs(dev) < 0.1 else ('✓ 命中' if abs(dev) < 1 else '✗')
    print('   │ %s→%s    │ %d→%d    │ %.4f    │ %.4f     │ %+.3f%%  │ %s   │'
          % (name_h, name_l, n_h, n_l, ratio, pred, dev, hit))
print('   └────────┴──────┴─────────┴────────────┴────────────┴─────────┘')
print()

# 绝对标度
print('② 绝对标度漂移检验（B_th/n² 是否恒定——C 值）：')
