"""
S584: 链静默结构差判别——混合链 vs 纯 σ 链
S583 开放项：I_μ 静默残余根奇幂 5（2σ⁵）vs m_τ 链根偶幂 4
  （2σ⁴——规范形 30σ⁵）。本步判别链类型与静默根幂的对应：
  ① 链类型分类：混合链（含 e 窗口项）vs 纯 σ 链（无 e 项）
     ——I_μ = e + 42e⁻⁶ + 2σ⁵（混合——含 e）
     ——m_τ 链修正模型 = 30σ⁵−360σ⁸（纯 σ——无 e）
  ② 静默根幂对应：混合链根 = 奇幂（σ⁵ = σ·σ⁴——单层窗口
     ×静默二阶）——纯链根 = 偶幂（σ⁴——纯静默二阶）
  ③ 判别对检验：2 例（I_μ 奇/m_τ 偶）——判别对成立——
     候选级（2 例——判别力有限——诚实登记）
  ④ 机制语义：混合链含窗口读数（e 链——测量窗口）——静默
     残余继承单层窗口结构（σ⁵）——纯链无窗口（深层冻结）——
     静默残余纯二阶（σ⁴）
  ⑤ 关联检查：其他含 e 项链（ε_μ = 144e⁻¹⁶(1+6σ³)——乘性
     修正——非加性静默残余——不适用）——边界登记
输出：链类型判别对 + 机制语义 + 候选级登记
"""
sigma = 1/15

def chk(name, lhs, rhs, tol=1e-12):
    ok = abs(lhs - rhs) <= tol
    print(f"  [{'PASS' if ok else 'FAIL'}] {name}: {lhs!r} vs {rhs!r}")
    return ok

print("=== S584: 链静默结构差判别 ===")

print("\n--- ① 链类型分类 ---")
chains = [
    ("I_μ",   "混合链", "e + 42e⁻⁶ + 2σ⁵——含 e 窗口项", "2σ⁵", 5),
    ("m_τ 链", "纯 σ 链", "30σ⁵−360σ⁸——无 e 项——纯 σ", "30σ⁵=2σ⁴", 4),
]
for name, typ, form, residual, root in chains:
    print(f"  {name:6s}: {typ}——{form}——残差 {residual}——根幂 {root}")

print("\n--- ② 静默根幂对应 ---")
print("混合链（I_μ）：根 σ⁵ = σ·σ⁴ = 单层窗口 × 静默二阶")
print("  ——静默残余继承 e 链的单层窗口结构（窗口→σ 层）")
print("纯 σ 链（m_τ）：根 σ⁴ = 纯静默二阶（无单层窗口）")
print("  ——深层冻结（无窗口读数）——规范形 30σ⁵")
print("对应规则候选：链含 e 窗口 ⟹ 静默根含单层（奇幂）")
print("            链纯 σ（无 e）⟹ 静默根纯二阶（偶幂）")

print("\n--- ③ 判别对检验 ---")
print("判别对：I_μ（混合→奇根 5）vs m_τ（纯→偶根 4）")
print("  两例完全区分——判别对成立（方向一致）")
print("  但样本 n = 2——判别力有限——候选级（非全称）")
chk("I_μ 根幂 5 = 奇", 5 % 2, 1)
chk("m_τ 根幂 4 = 偶", 4 % 2, 0)

print("\n--- ④ 机制语义 ---")
print("混合链：测量读数经窗口（e 链——S310 度量函数）——")
print("  静默残余 = 窗口冻结的单层 + 深层静默二阶（σ⁵）")
print("纯 σ 链：质量深层冻结（S106 质量锚定链链内端点）——")
print("  无窗口——静默残余 = 纯静默二阶（σ⁴——规范形 30σ⁵）")
print("  ——链类型决定静默根结构——机制自洽")

print("\n--- ⑤ 关联检查与边界 ---")
print("ε_μ = 144e⁻¹⁶(1+6σ³)——混合链（含 e）——但修正为乘性")
print("  因子（1+6σ³）——非加性静默残余——不适用本判别对")
print("  ——边界：本判别对仅约束加性静默残余项")
print("σ⁸（终止层——S268 已锚）——非加性静默残余——不适用")

print("\n--- 判别结论 ---")
print("链静默结构差判别（候选级——n=2）：")
print("  ① 混合链（含 e 窗口）静默残余根 = 奇幂（σ⁵——")
print("     单层×静默二阶）——I_μ 2σ⁵ ✓")
print("  ② 纯 σ 链（无 e）静默残余根 = 偶幂（σ⁴——纯二阶）")
print("     ——m_τ 30σ⁵=2σ⁴ ✓——规范形化（S583）一致")
print("  ③ 机制：链类型（窗口 vs 深层）决定静默根结构")
print("  ④ 边界：仅加性静默残余适用——乘性因子/已锚常数不适用")
print("状态：判别对成立（候选级）——样本 2 例——需更多链")
print("  检验（可判别的新量：含 e 加性静默残余——预测奇根）")
