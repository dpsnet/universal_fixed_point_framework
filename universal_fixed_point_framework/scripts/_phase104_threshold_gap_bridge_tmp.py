import math

print('=== Phase 104at: 阈值 × 1/8 机制定量衔接模型 ===')
print()

# ① 阈值序列递推（104ar 新发现——B_th(n) = B_th(n-1)·(n/(n-1))²）
print('① 阈值序列递推锚定（(n/(n-1))²——104ar）：')
seq = [('Hε', 7, 48.01), ('Hδ', 6, 65.35), ('Hγ', 5, 94.11),
       ('Hβ', 4, 147.05), ('Hα', 3, 261.41)]
for name, n, b in seq:
    print('   %s (n=%d)：B_th = %.2f MG' % (name, n, b))
b2 = 261.41 * 4 / 9
print('   ★ 递推预言：n=2（若存在对应线——如 Lyman/Paschen 端）B_th(2) = %.2f MG'
      % b2)
print()

# ② 缺口开启模型
print('② 缺口开启模型（缺口份额 vs B）：')
print('   · 缺口份额（单线）s_n(B) = (1/8)·f(B/B_th(n))——')
print('     ——f = 开启函数（0→1）——B < B_th 时 f≈0（未禁戒）——')
print('     ——B ≥ B_th 时 f→1（缺口开启——1/8 饱和）——')
print('   · ★ 104q 衔接：线缺失 46.9% → 连续区 1/8（5.86% vs 5.8% 观测）——')
print('     ——缺口 1/8 = 缺失线流量转移连续区——不是缺失总量——')
print('     ——46.9% 总缺失 = 多机制叠加（Landau/Zeeman/缺口）——')
print('     ——1/8 是缺口通道份额（转移连续区的量）')
print('   · f 候选：')
print('     f1（阶跃）：f = Θ(B - B_th)——阈值处突变——')
print('     ——对应「拓扑门」清晰开启（结构性禁戒——稳态完全缺失）')
print('     f2（平滑）：f = B²/(B² + B_th²)——Landau 化渐进——')
print('     ——对应连续过渡（a₀/ℓ_B 渐进——中场 0.1-0.3 弱）')
print('   · ★ 观测判别：EW 缺失 vs B 分档——')
print('     ——f1 预测：B_th(n) 处缺失出现台阶（突变）——')
print('     ——f2 预测：B_th(n) 处缺失平滑上升（无台阶）——')
print('     ——**台阶 vs 平滑 = 结构性禁戒 vs Landau 渐进的判别**')
print()

# ③ 数值检验：各线阈值处缺失预期
print('③ 数值检验：各线阈值处的缺口开启（f1 阶跃 vs f2 平滑）：')
print('   ┌──────┬───────┬─────────┬─────────────────────┬─────────────────────┐')
print('   │ 线    │ B_th   │ 中场样本  │ f1 缺失（B>B_th）   │ f2 缺失（B/B_th）    │')
print('   │      │ (MG)   │ B 范围    │ 预期                 │ 预期                 │')
print('   ├──────┼───────┼─────────┼─────────────────────┼─────────────────────┤')
for name, n, b in seq:
    # 高场样本 109-778 MG 各线阈值覆盖情况
    covered = '覆盖' if 109 < b < 778 else ('部分' if b > 109 else '未达')
    f1_exp = '1/8 全开' if 778 > b else '1/8 未开'
    # f2: B=778 处开启程度
    f2_at_max = (778**2) / (778**2 + b**2)
    f2_exp = '%.1f%%' % (f2_at_max * 100)
    print('   │ %s    │ %6.1f │ %s      │ %s         │ %s               │'
          % (name, b, covered, f1_exp, f2_exp))
print('   └──────┴───────┴─────────┴─────────────────────┴─────────────────────┘')
print('   · 高场样本（109-778 MG）覆盖 Hε/Hδ/Hγ 阈值（48/65/94 < 109）——')
print('     ——Hβ（147）部分覆盖（147-778 段）——Hα（261）覆盖（261-778）——')
print('     ——★ 高场样本内各线阈值全部可达——判别可实施')
print()

