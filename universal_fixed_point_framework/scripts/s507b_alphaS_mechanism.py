from fractions import Fraction

fact24, involution, total16, powBase = 24, 7, 16, 2
sigma = Fraction(1, 15)

print("=" * 78)
print("S507b α_s 路径 C 全框架化机制确认")
print("=" * 78)

# 1. 17 双恒等
print("\n① 17 双恒等：")
a = fact24 - involution
b = total16 + 1
print("   4!−对合域 = %d；全态+1 = %d —— 双恒等 %s" % (a, b, a == b))

# 2. α_s 路径 C 双表达
print("\n② α_s 路径 C 双框架表达：")
expr1 = Fraction(fact24 - involution, 2) * (1 - involution * sigma ** 3)
expr2 = Fraction(total16 + 1, powBase) * (1 - involution * sigma ** 3)
print("   [(4!−对合域)/2](1−对合域·σ³) = %s" % expr1)
print("   [(全态+1)/幂基](1−对合域·σ³)  = %s" % expr2)
print("   一致：%s —— 原 (17/2)(1−7σ³) = %s" % (expr1 == expr2, Fraction(17, 2) * (1 - 7 * sigma ** 3)))

# 3. 对合域与 δ* 系数谱的连接（配对面）
print("\n③ 对合域 7 的 δ* 结构在场（S334 守恒配对）：")
print("   配对1 (6σ³,5σ⁸)→11；配对2 (4σ⁵,8σ⁷)→12")
print("   配对1和−配对2σ⁵系数 = 11−4 = 7")
print("   配对2和−配对1σ⁸系数 = 12−5 = 7 —— 交叉差双出 = 对合域")
print("   另一观察：σ³系数(6)×对合域(7) = 42 = 约束域 —— α_s 的 σ³ 层"
      "与色约束域共轭")

