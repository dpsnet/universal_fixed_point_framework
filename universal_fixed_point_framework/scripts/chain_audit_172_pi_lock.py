"""chain_audit_172_pi_lock.py — π 位置锁定检验：41+π/10 三候选并存 + 超越常数嵌入规则（104az-172）"""
import io, sys, math
from fractions import Fraction as F
sys.stdout = io.TextIOWrapper(sys.stdout.buffer, encoding="utf-8")

print("=== 1. C = 41 + π/10 数值核验 ===")
obs = 172.69 / 4.18
C = 41 + math.pi / 10
print(f"41 + π/10 = {C:.9f}")
print(f"观测 m_t/m_b (172.69/4.18) = {obs:.9f}")
print(f"dev = {(obs/C-1)*100:+.6f}%")
print(f"vs PDG 中心比值 41.283768：dev {(41.283768/C-1)*100:+.4f}%（统计 {((41.283768-C)/0.238057):+.3f}σ）\n")

print("=== 2. π 的系数位置锁定检验 ===")
k = (obs - 41) / math.pi
print(f"反推系数 k = (m_t/m_b − 41)/π = {k:.6f}")
print(f"候选 1/10 = 0.1；dev {(k/0.1-1)*100:+.4f}%")
print(f"→ 1/10 = 1/(幂基×静默) = 1/(N_gen+k_max−1)（104az-162 恒等）——系数位置是框架量 ✓")
print(f"m_b 观测精度 ±0.55% >> 系数偏差 0.24%——π 位置在精度范围内被锁定\n")

print("=== 3. 三候选并存比较 ===")
A = F(371, 9) * F(451, 450)
B = F(42) - F(343, 500)
cands = [("A = 371×451/4050", float(A), "纯框架有理（全因子）"),
         ("B = 42−343/500", float(B), "纯框架有理（结构层）"),
         ("C = 41+π/10", C, "框架量 41/10 + 超越常数 π")]
print(f"{'候选':<22}{'值':<16}{'dev(观测)':<12}{'m_b反推':<10}{'身份'}")
for name, v, ident in cands:
    print(f"{name:<22}{v:<16.8f}{((obs/v)-1)*100:+.6f}%  {172.69/v:<10.6f}{ident}")
print(f"\n观测 m_b 反推参考：{172.69/obs:.6f}")
print(f"A/B/C 反推 m_b：{172.69/float(A):.6f} / {172.69/float(B):.6f} / {172.69/C:.6f}——均在 4.1799x（互相 0.001% 内）\n")

print("=== 4. 三候选间距 ===")
print(f"A→B 间距 = {float(B)-float(A):.10f}（= 7/40500 = 0.00017284，纯素基框架量）")
print(f"B→C 间距 = {C-float(B):.10f}（= (π−3.14)/10 = 0.00015927，含 π——非纯框架量）")
print(f"A→C 间距 = {C-float(A):.10f}")
print("→ A/B 在框架有理互锁族内（差纯素基）；C 为外族（含超越常数）——三角互锁未成形但三候选同窗口并存\n")

print("=== 5. 框架超越常数嵌入规则（语义升级）===")
print("公设层：λ = π² 循环公设——π 无代数身份且位置（公设本身）无框架参数 → 不立（104az-166）")
print("表达式层：超越常数可嵌入派生表达式，但全部位置参数须为框架量——")
print("  先例：m_μ/m_τ = e^{−(ln16+e^{−3})}（16、3 框架量，P7-4d）；m_e = m_τ·e^{−(3e−σ³(1+α_v))}（3、σ、α_v 框架量，P7-5v）")
print("  新实例：m_t/m_b ≈ 41 + π/10（41 = 静默单元+1、10 = 幂基×静默——π 位置被框架量锁定）")
print("→ 判别规则统一：超越常数允许出现在表达式层，位置参数必须有框架身份；无身份参数（如 σ/78 的 78）不立（P7-5u 先例）\n")

print("=== 6. 判别 ===")
print("① ★ 用户主张成立：41+π/10 的 π 系数 1/10 = 1/(幂基×静默) 是框架量——'π 位置被锁定'在 m_b 精度内成立")
print("② ★ C = 41+π/10 dev −0.0018%（0.001% 级）与 A/B 同窗口三候选并存；A/B/C 反推 m_b 均在 4.1799x 互相 0.001% 内")
print("③ ★ 超越常数嵌入规则统一：公设层禁（λ=π² 循环）vs 表达式层许（位置参数框架量）——π/10 新实例与 e/ln 先例（P7-4d/5v）同规则")
print("④ 诚实边界：C 为外族候选（C−B 含 π 非纯框架量，三角互锁未成形）；系数反推 0.09976 vs 1/10 差 0.24%（m_b 精度内非 0.01% 级）——C 升级为与 A/B 并列的第三候选，'位置锁定'为结构层主张，数值终判仍受 m_b 口径阻塞")
