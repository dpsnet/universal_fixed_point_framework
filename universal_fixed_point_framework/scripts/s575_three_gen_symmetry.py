sigma = 1/15

def chk(name, lhs, rhs, tol=1e-12):
    ok = abs(lhs - rhs) <= tol
    print(f"  [{'PASS' if ok else 'FAIL'}] {name}: {lhs!r} vs {rhs!r}")
    return ok

print("=== S575: '该量→该类'闭环——三代全对称排列计数 ===")

print("\n--- ① 三代全对称分类（9 例）---")
