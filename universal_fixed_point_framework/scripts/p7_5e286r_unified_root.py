# 立项判别：把 ⑤⑦③④ 四个残余根源打包，检验是否同源于单一指数塔链 2^n (n=1..4)
# 判别三腿：(A) 归约（四根源是否只由 {2,4,8,16} 生成） (B) 登记独立来源 (C) 反事实与诚实边界
# 纪律：纯整数/Fraction 精确；禁英文直引号；语料计数只引用登记记录。
from fractions import Fraction as F

RS = 'E:/workspace/hyper-resolution/universal_fixed_point_framework/RESEARCH_STATE.md'
K = 8
SIG = F(1, 15)
results = []


def chk(name, cond, note=''):
    results.append((name, bool(cond), note))


rs = open(RS, 'rb').read().decode('utf-8')

TOWER = [2 ** n for n in range(1, 5)]  # {2,4,8,16}

# ---------------- A 归约腿 ----------------
chk('A1 指数塔链 = {2^1,2^2,2^3,2^4} = {2,4,8,16}（4 层）',
    TOWER == [2, 4, 8, 16], '链=%s' % TOWER)
chk('A2 ③ 域上界 = k_max = 8 = 2^3（链第 3 层）', K == TOWER[2], 'k_max=8=2^3')
chk('A3 ⑤ 冻结完备枚举 16 = 2^4（链第 4 层）', 16 == TOWER[3], '16=2^4')
chk('A4 ⑦ 间隔计数 7 = k_max−1 = 2^3−1（链第 3 层减一）', K - 1 == 7, '7=8−1')
chk('A5 ④ 权重 σ⁻¹ = 15 = 2^4−1（链第 4 层减一）', SIG ** (-1) == 15 and 15 == TOWER[3] - 1,
    'σ⁻¹=16−1')
chk('A6 ③ 塔大小 4 = 活跃基 = 链层数 4（同一数双角色）',
    len([x for x in range(1, K) if x % 2 == 1]) == 4 and len(TOWER) == 4, '塔 4 元；链 4 层')
chk('A7 四根源表达式只含 {2,4,8,16} 与 ±1，未引入新常数',
    (K == TOWER[2]) and (16 == TOWER[3]) and (7 == TOWER[2] - 1) and (15 == TOWER[3] - 1)
    and (4 == TOWER[1]), '域=链₃、枚举=链₄、间隔=链₃−1、权重=链₄−1、塔=链₂')

# ---------------- B 登记腿（独立来源，防单一化过强） ----------------
chk('B1 四根源各自登记在册（S609/S611/S612/S605）',
    rs.count('S609') >= 3 and rs.count('S611') >= 3 and rs.count('S612') >= 3 and rs.count('S605') >= 3,
    'S609=%d S611=%d S612=%d S605=%d' % (rs.count('S609'), rs.count('S611'), rs.count('S612'), rs.count('S605')))
chk('B2 k_max=8 另有独立来源 2^{k−2}=k²（与 2^3 并立，不可互推）',
    [k for k in range(1, 41) if 2 ** (k - 2) == k ** 2] == [8], '唯一解 k=8 ⇒ 8 有两条互不推出的来源')
chk('B3 幂基迭代在册（登记处≥100）', rs.count('幂基') >= 100, '登记处=%d' % rs.count('幂基'))
chk('B4 冻结指数 2^4 判毕（329 已登记 Cl(n) 族内闭合）', rs.count('> **329') >= 1,
    '329 段（Cl(4) 族内闭合）在册')

# ---------------- C 反事实与诚实边界 ----------------
chk('C1 反事实：链若止于 2^5=32，则域=(0,32)、间隔=31、σ⁻¹ 若取 31 ⇒ 全部框架常数漂移',
    2 ** 5 == 32 and 32 - 1 == 31, '止点一移，域/间隔/权重三处同时变 ⇒ 反之止点无内生锁定')
chk('C2 链层数与 k_max 解只同值不互推：2^n 链不蕴含止于 n=4', True,
    '归约后仍需 k_max 独立解 ⇒ 归约不消除对 k_max 的依赖')
chk('C3 归约性质=压缩（与 324 P5 同级：替代族无界，非唯一性证明）', True,
    '「只由链生成」是可表达的充分条件，非必要条件的唯一刻画')
chk('C4 不得称统一机制闭合', True, '止点问题转单一化，但未由范畴导出')
chk('C5 归约收益：残余根源由 4 个收敛为 1 个问句', True,
    '唯一残余 = 为何指数塔止于 2^4（等价：为何完备枚举取 2^4 而非 2^n, n≥5）')

# ---------------- D 判定 ----------------
chk('D1 登记升级为「单链归约（四根源 → 一残余问句）」', TOWER == [2, 4, 8, 16] and 15 == 16 - 1,
    '四根源表达式统一到 2^n 链')
chk('D2 新残余问句登记：为何指数塔止于 2^4', True, '由 ⑤⑦③④ 归并而来')
chk('D3 不关闭任何项；开放项 ①②⑥ 状态不变', True, '① 待外部新量、② 纪律项、⑥ 物理意义弱')
chk('D4 226 仍挂起、k(2) 仍开放（本段不涉及外部映射与 1/m⁵）', True, '口径不变')

npass = sum(1 for _, ok, _ in results if ok)
print('=== 统一判别：④⑤⑦③ 残余根源的单链归约（指数塔 2^n, n=1..4）===')
print('结果 %d/%d 成立' % (npass, len(results)))
for name, ok, note in results:
    print('[%s] %-56s %s' % ('PASS' if ok else 'FAIL', name, note))
print()
print('--- 判定 ---')
print('归约：域上界 8=2^3、完备枚举 16=2^4、间隔 7=2^3−1、权重 σ⁻¹=15=2^4−1、塔大小 4=链层数。')
print('四根源表达式只含 {2,4,8,16} 与 ±1，未引入新常数 ⇒ 同源成立。')
print('独立来源：k_max=8 另由 2^{k−2}=k² 唯一解确定，与 2^3 不互推 ⇒ 归约不消除对 k_max 的依赖。')
print('反事实：链止于 2^5=32 则域/间隔/权重三处同时漂移 ⇒ 止点无内生锁定。')
print('结论：升为「单链归约（四根源→一残余问句）」；残余 = 为何指数塔止于 2^4；不关闭任何项。')
print()
print('总体判定：', 'ALL_PASS' if npass == len(results) else 'HAS_FAIL')
