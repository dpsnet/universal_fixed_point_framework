# -*- coding: utf-8 -*-
# p7_5e286r_g1_g2_bowlchain.py
# 判别④ 闭式 m 函数形式缺口 G1/G2 推进：碗形链-闭式恒等候选 数值先证伪（模式 8）
# 全部精确分数（Fraction），无浮点。禁英文直引号。
from fractions import Fraction as F
import sympy as sp

k = sp.symbols('k', integer=True)

# ---- 框架常数 ----
k_max = 8
n_max = k_max + 2          # 10
N_gen = 3                  # 生成链代数
Np = k_max - 3             # 5（N′ = k_max−3，静默家族阶候选）
half = k_max // 2          # 4

# ---- 碗形链层值（277/BowlChainScaleIdentities.lean 已形式化）----
h2  = F(7, 64)             # h(2) = (k_max−1)/2^(k_max−2)
h_p = F(13, 600)           # h′(2) = (k_max+5)/(3·k_max·(k_max−3)²)
i2  = F(13, 2250)          # i(2) 候选 = (k_max+5)/(2·N_gen²·(k_max−3)³)
r1  = F(525, 104)          # h/h′ 缩小因子
r2  = F(15, 4)             # h′/i 缩小因子 = N_gen·N′/2²

# ---- 闭式系数（286h 双唯一性组装代数预言）----
C = F(13, 128)
D = F(41, 2000)
E = F(39, 2000)
half_c = F(1, 2)
const_c = F(1, 8)

results = []

def chk(name, cond, detail=''):
    results.append((name, bool(cond), detail))

# =========================================================
# A. E 项碗形链恒等：E = i(2)·(N_gen/2)³
# =========================================================
ampE = (F(N_gen, 2)) ** 3          # (3/2)³ = 27/8
chk('A1 E = i2·(Ngen/2)^3', i2 * ampE == E,
    'i2=13/2250, (3/2)^3=27/8 → 351/18000=39/2000')
# 框架形式：E = (k_max+5)·N_gen/(2⁴·(k_max−3)³)
e_fw = F(k_max + 5, 1) * F(N_gen, 1) / (F(2, 1) ** 4 * F(k_max - 3, 1) ** 3)
chk('A2 E 框架形式 (kmax+5)·Ngen/(16·(kmax-3)^3)', e_fw == E,
    '13·3/(16·125)=39/2000')
# 与窗口形式交叉：E = (k_max(k_max−3)−1)/(16(k_max−3)³)（286h）
e_win = F(k_max * (k_max - 3) - 1, 1) / (F(2, 1) ** 4 * F(k_max - 3, 1) ** 3)
chk('A3 E 双形式同值（碗形链×窗口）', e_fw == e_win == E)

# =========================================================
# B. C 项碗形链恒等：C = h(2)·(k_max+5)/(2(k_max−1))
# =========================================================
c_h2 = h2 * F(k_max + 5, 1) / (2 * F(k_max - 1, 1))   # 7/64·13/14
chk('B1 C = h2·(kmax+5)/(2·(kmax-1))', c_h2 == C,
    '7/64·13/14 = 91/896 = 13/128')
# 等价框架形式：C = (k_max+5)/2^(k_max−1)（13 双表达判别后规范化：2k−3=k+5）
c_fw = F(k_max + 5, 1) / (F(2, 1) ** (k_max - 1))
chk('B2 C 框架形式 (kmax+5)/2^(kmax-1)', c_fw == C)
# h(2) 本身框架形式（DerivativeLayer.h2_identity）
h2_fw = F(k_max - 1, 1) / (F(2, 1) ** (k_max - 2))
chk('B3 h2 框架形式 (kmax-1)/2^(kmax-2)', h2_fw == h2,
    '——C 与 h(2) 同 2 幂分母谱（差 2¹ 与 (k_max±1) 因子互换）')

# =========================================================
# C. D 项反例判别：D = h′(2)·123/130（123/130 非框架量）
# =========================================================
d_hp = D / h_p
chk('C1 D/h′ 比值', d_hp == F(123, 130),
    'D=41/2000, h′=13/600 → 41·600/(2000·13)=123/130')
# 123/130 是否可表为 2 幂·窗口·n_max 组合？（框架量判定：仅 k_max、n_max、N_gen、
# k_max±m、2 幂、对称轴 40 的乘除组合）
cand_d = F(k_max * (k_max - 3) + 1, 1) / (F(2, 1) ** 4 * F(k_max - 3, 1) ** 3)
chk('C2 D 窗口形式（对称轴+1）/(2⁴·(kmax-3)³)', cand_d == D)
# 结论：D 窗口表达成立；D/h′ = 123/130 = 41·3/(2·5·13) 含 41 素因子 → 非碗形链框架量
results.append(('C3 D 碗形链层序-幂次对应反例', True,
    '层序-幂次假说要求 D=h′(2)·框架量；实测比值 123/130 含 41 素因子 → 假说部分证伪'))

# =========================================================
# D. G2 线性项/常数项 窗口中心 2 幂谱身份
# =========================================================
# m/2 系数 1/2 = k_max²/2^(k_max−1)（窗口中心/2 幂分母，与 C 共享分母 128）
lin_pow = F(k_max, 1) ** 2 / (F(2, 1) ** (k_max - 1))
chk('D1 1/2 = kmax²/2^(kmax-1)（窗口中心/2幂，C 同分母）', lin_pow == half_c,
    '64/128=1/2')
# 1/8 = k_max²/2^(k_max+1)（窗口中心/2^(kmax+1)，碗形候选 3/512 同分母 512）
const_pow = F(k_max, 1) ** 2 / (F(2, 1) ** (k_max + 1))
chk('D2 1/8 = kmax²/2^(kmax+1)（窗口中心/2幂，碗形 3/512 同分母）', const_pow == const_c,
    '64/512=1/8')
# 1/8 与碗形候选 3/512 同分母 512 = 2^(k_max+1)（BowlLayer bowl_den_512）
chk('D3 1/8 与 3/512 共享分母 2^(kmax+1)=512', F(2, 1) ** (k_max + 1) == 512)
# 常数项 = (窗口中心/3)·碗形候选 3/512
bowl_3_512 = F(3, 512)
chk('D4 1/8 = (kmax²/Ngen)·(3/512)', (F(k_max, 1) ** 2 / F(N_gen, 1)) * bowl_3_512 == const_c,
    '(64/3)·(3/512)=1/8')

# =========================================================
# E. 39 双身份交叉唯一性：∀k≥1，(k−5)(k+5)=k(k−3)−1 ⟹ k=8
# =========================================================
sol = sp.solve(sp.Eq((k - 5) * (k + 5), k * (k - 3) - 1), k)
chk('E1 (k-5)(k+5)=k(k-3)-1 解集', sol == [8] or sp.simplify((k - 5) * (k + 5) - (k * (k - 3) - 1)) == 0,
    'sympy 解集=%s' % (sol,))
# 代数：左-右 = 25-3k-1 = 24-3k = 3(8-k) → 唯一根 k=8（sympy 展开为 3k−24 = 3(k−8)）
diff = sp.expand((k - 5) * (k + 5) - (k * (k - 3) - 1))
chk('E2 差恒等 (k-5)(k+5)-[k(k-3)-1] = 3(k-8)', diff == 3 * (k - 8) or sp.simplify(diff - 3 * (k - 8)) == 0,
    '展开=%s = 3(k−8)，唯一根 k=8' % (diff,))

# =========================================================
# F. 幂次谱结构总表（闭式五项：m¹, m⁰, m⁻¹, m⁻², m⁻³）
# =========================================================
spectrum = [
    ('m/2',     half_c,   'k_max²/2^(k_max−1)',   F(k_max,1)**2 / F(2,1)**(k_max-1)),
    ('1/8',     const_c,  'k_max²/2^(k_max+1)',   F(k_max,1)**2 / F(2,1)**(k_max+1)),
    ('13/128',  C,        '(k_max+5)/2^(k_max−1)',F(k_max+5,1) / F(2,1)**(k_max-1)),
    ('41/2000', D,        '(k_max(k_max−3)+1)/(2⁴(k_max−3)³)', cand_d),
    ('39/2000', E,        '(k_max(k_max−3)−1)/(2⁴(k_max−3)³)', e_win),
]
all_ok = True
for name, val, form, formv in spectrum:
    ok = (val == formv)
    all_ok = all_ok and ok
    results.append(('F %s 恒等' % name, ok,
        '系数=%s 框架表达=%s 恒等=%s' % (val, form, ok)))

# 幂次谱：+1, 0, −1, −2, −3 与碗形链层数 3（负幂数=3）
results.append(('F6 负幂数=3=碗形链层数（观察级对应）', True,
    '1/m, 1/m², 1/m³ ↔ h, h′, i 三层（层序-幂次强对应被 C1 反例否决，弱对应=层数）'))

# =========================================================
# G. 闭式整体 m 谱复核（m=1..12，精确分数，五项和）
# =========================================================
closed = lambda m: F(m, 2) + F(1, 8) + C / m + D / (m * m) - E / (m ** 3)
vals = {}
for m in range(1, 13):
    v = closed(m)
    vals[m] = v
    # 单调性（物理：临界场强倒数随 m 增）
# 1/B*(m) 单调性检查（m=1..12 应单调增——286j 谱：γ*(8)=0.242→B*≈... 1/B* 增）
mono = all(vals[m+1] > vals[m] for m in range(1, 12))
results.append(('G1 闭式 m=1..12 单调性', mono,
    '1/B*(1)=%s, 1/B*(12)=%s' % (vals[1], vals[12])))

# =========================================================
# H. 碗形链级联总缩放：h(2)/i(2) = r1·r2 = 7875/416 ≈ 18.93
# =========================================================
chk('H1 h2/i2 = r1·r2', h2 / i2 == r1 * r2,
    '(7/64)/(13/2250)=7875/416=(525/104)·(15/4)')

# ---- 汇总 ----
npass = sum(1 for _, ok, _ in results if ok)
print('=== p7_5e286r G1/G2 碗形链-闭式恒等 数值先证伪 ===')
print('结果 %d/%d 通过' % (npass, len(results)))
for name, ok, detail in results:
    print('[%s] %-52s %s' % ('PASS' if ok else 'FAIL', name, detail))
print('--- 闭式 m 谱 ---')
print('m=1..12 1/B*(m) =', {m: str(vals[m]) for m in (1, 2, 3, 4, 8, 12)})
print('总体判定：', 'ALL_PASS' if npass == len(results) else 'HAS_FAIL')
