print("\n=== 机制候选 ===")
print("静默族幂次 = Fibonacci 递归链（指数二阶线性递归 f(n)=f(n-1)+f(n-2)）")
print("统一解释：① Fibonacci 观察（S122）② 不动点幂禁（4 非 Fib——无幂展开）")
print("          ③ 静默偶幂禁（6 非 Fib）④ σ⁷/σ⁹ 不命中（S130——非 Fib）")
print("语义：'静默冻结的幂次代数 = 最慢增长的递归（Fib）'——冻结 = 递归代数结构")
