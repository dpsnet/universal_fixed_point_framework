"""S215 宇宙学参数框架检验（覆盖域扩展：粒子 → 宇宙学）
Planck 2018 参数 vs 框架量——σ_score 判定（禁百分比）
"""
print("=== S215: 宇宙学参数框架检验 ===\n")

# Planck 2018（TT,TE,EE+lowE）——σ_score 口径：|预测-实验|/合成不确定度
cosmo = [
    # (名称, 实验值, 不确定度, 框架预测, 预测表达式)
    ("Ω_m h²", 0.1430, 0.0011, 1/7, "1/对合"),
    ("Ω_b h²", 0.02237, 0.00015, None, "扫描中"),
    ("n_s", 0.9649, 0.0042, 1 - (1/15)/2, "1−σ/2（σ=1/Σ）"),
    ("Ω_Λ", 0.6847, 0.0057, None, "扫描中"),
]

for name, exp, unc, pred, expr in cosmo:
    if pred is None:
        print(f"  {name} = {exp}±{unc}——扫描候选无命中——登记")
        continue
    score = abs(exp - pred) / unc
    status = "达标" if score <= 1 else ("提示" if score <= 3 else "不达标")
    print(f"  {name} = {exp}±{unc}")
    print(f"    预测 {expr} = {pred:.10f}")
    print(f"    σ_score = |{exp}-{pred:.6f}|/{unc} = {score:.3f}σ —— {status}")

print("\n=== 详细判定 ===")
# Ω_m h² vs 1/7
s1 = abs(0.1430 - 1/7) / 0.0011
print(f"  Ω_m h²：1/7 = 0.1428571——σ_score = {s1:.3f}σ（达标）")
# n_s vs 1-σ/2
s2 = abs(0.9649 - (1 - (1/15)/2)) / 0.0042
print(f"  n_s：1−σ/2 = 0.9666667——σ_score = {s2:.3f}σ（达标）")

print("\n=== 诚实评估 ===")
print("两个新候选均 ≤1σ 达标：")
print("  Ω_m h² = 1/对合（0.13σ）——宇宙密度参数")
print("  n_s = 1−σ/2（0.42σ）——原初功率谱斜率")
print("框架可表达性：")
print("  1/7——对合倒数（壳内）")
print("  σ/2 = 1/(Σ×幂基) = 1/30（壳派生）")
print("后验性声明：")
print("  宇宙学参数——模型依赖（ΛCDM）——后验候选")
print("  → 观察级登记——不升格（先验预测能力未建立）")
print("  → 但覆盖域扩展：粒子质量/耦合 → 宇宙学参数——'同一框架'")

print("\n=== 审计结论 ===")
print("宇宙学参数框架检验：2 新候选命中（Ω_m h²/n_s）——0.13σ/0.42σ")
print("  覆盖域扩展里程碑：理论覆盖从粒子物理扩展到宇宙学")
print("  登记候选（观察级）——模型依赖——先验性弱——不升格")
print("  Ω_b h²/Ω_Λ 无命中——登记（防巧合勿强配）")
