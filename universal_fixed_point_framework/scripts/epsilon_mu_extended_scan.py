for c in [1,2,3,4,5,6,7,8,10,12,15,16,20,24,30,32,40,48,64]:
    for n in [3,4,5,6,7,8]:
        v = base*(1+c*sp(n))
        d = abs(v-TARGET)/TARGET*100
        if d < 0.05: hits.append((d, f"144e^{{−16}}(1+{c}σ^{n}) = {v:.6e}"))
