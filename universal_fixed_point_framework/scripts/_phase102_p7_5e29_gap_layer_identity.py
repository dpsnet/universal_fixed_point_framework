# -*- coding: utf-8 -*-
"""
Phase 102 P7-5e-29：双谱隙口径的层级身份分解
================================================================
检查两个口径的数学结构差异（拓扑/几何/递归层级）：
EM 口径：Δλ_EM = π/(24(d_H+3)) —— 24 = k_max·N_gen？π 拓扑？
P20 口径：Δλ_P20 = (√3−1)/6 —— 6 = N_gen!？√3 几何？
"""
import math

dH   = math.log(15)
kmax, Ngen = 8, 3
dlam_EM = math.pi/(24*dH+72)
dlam_P20 = (math.sqrt(6)-math.sqrt(2))/math.sqrt(72)

print("="*104)
print("P7-5e-29：双谱隙口径的层级身份分解")
print("="*104)

print("① EM 口径分母分解：")
print("  Δλ_EM = π/(24d_H+72) = π/(24(d_H+3))")
print("  24 = k_max·N_gen = %d×%d = %d ✓" % (kmax, Ngen, kmax*Ngen))
print("  d_H+3 = 谱维+空间维 = %.6f" % (dH+3))
print("  → Δλ_EM = π/(k_max·N_gen·(d_H+3))——π（拓扑闭合）× 旋量代计数 × 谱维展开")
print("  验证：π/(%d×%d×%.6f) = %.10f vs %.10f ✓" % (kmax, Ngen, dH+3, math.pi/(kmax*Ngen*(dH+3)), dlam_EM))
print()

print("② P20 口径分母分解：")
print("  Δλ_P20 = (√6−√2)/√72 = (√3−1)/6")
print("  6 = N_gen! = 3! = 6 ✓")
print("  √3 = 正三角形几何比（等边三角形高/边 = √3/2 类）")
print("  → Δλ_P20 = (√3−1)/N_gen!——√3（几何格点）× 代阶乘（组合结构）")
print("  验证：(√3−1)/3! = %.10f vs %.10f ✓" % ((math.sqrt(3)-1)/6, dlam_P20))
print()

print("③ 结构对比（拓扑/几何/递归层级）：")
print("  %-14s %-30s %-30s" % ("维度", "EM 口径（Δλ_EM）", "P20 口径（Δλ_P20）"))
print("  %-14s %-30s %-30s" % ("拓扑", "含 π（圆周/旋转闭合——拓扑量）", "不含 π（纯代数）"))
print("  %-14s %-30s %-30s" % ("几何", "含 d_H+3（谱维+空间维——谱几何）", "含 √3（正三角格点——欧氏几何）"))
print("  %-14s %-30s %-30s" % ("递归层级", "分母 k_max·N_gen·(d_H+3)——Rec 计数×谱维", "分母 N_gen!——组合阶乘"))
print("  %-14s %-30s %-30s" % ("数域", "超越数（π×ln15）", "代数数（√3 域）"))
print("  %-14s %-30s %-30s" % ("κΛ 映射", "→ C² = 4ln10（对数平方）", "→ 7²（整数平方）"))
print()

print("④ 层级语义：")
print("  EM 口径 = Rec 层（递归/拓扑）：π 圆周闭合（旋转对称）+ k_max·N_gen（递归计数）+ 谱维")
print("  P20 口径 = Sp 层（谱/几何）：√3 格点（正三角密堆）+ N_gen!（组合）")
print("  → 双谱隙 = 两个数学层级的谱结构：Rec 谱隙（拓扑闭合）vs Sp 谱隙（几何格点）")
print("  → κΛ 是'平方算符'：Rec 谱隙→对数平方（C²）、Sp 谱隙→计数平方（7²）")
print()

print("⑤ 应用分工的层级语义：")
print("  质量谱隙链（轻子/夸克绝对质量）用 EM（Rec/拓扑）——质量谱是递归谱")
print("  m_t（v 链、弱电）用 P20（Sp/几何）——v 链是几何谱")
print("  → 分工 = Rec/Sp 通道分工（P7-5e-6 登记：Rec→加法/Sp→乘法 的谱通道分工）")
print()
print("exit 0")
