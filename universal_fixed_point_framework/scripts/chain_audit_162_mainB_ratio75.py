"""chain_audit_162_mainB_ratio75.py — 主线 B 织³ 简化表达 + 7/5 骨架精度判别"""
import io, sys, math
sys.stdout = io.TextIOWrapper(sys.stdout.buffer, encoding="utf-8")

print("=== 1. 框架恒等 N_gen+k_max−1 = 幂基·静默 ===")
print(f"3+8−1 = {3+8-1}；幂基×静默 = {2*5} ✓")

print("\n=== 2. 织³ 简化表达 ===")
zhi = 9/10
print(f"织 = N_gen²/(幂基·静默) = 9/10 = {zhi}")
print(f"织³ = (9/10)³ = {zhi**3} = 729/1000（729 = 3⁶、1000 = 2³·5³——纯素基 {{2,3,5}}）")
print(f"104az-67 形式 (N_gen²/(N_gen+k_max−1))³ = {(3*3/(3+8-1))**3}——恒等等价 ✓")

print("\n=== 3. F_np 全组件纯框架复算 ===")
dlam_min = (math.sqrt(3)-1)/6
print(f"Δλ_min = (√3−1)/6 = {dlam_min:.9f}")
dlam3 = math.sqrt(2)*dlam_min
print(f"Δλ₃ = √2·Δλ_min = {dlam3:.9f}")
delta = 1/675
F_np = zhi**3*(1-delta)/dlam3
print(f"F_np = (9/10)³×(1−1/675)/(√2·Δλ_min) = {F_np:.7f}")

print("\n=== 4. F_np 双重 dev 判别（7/5 骨架 vs 观测）===")
print(f"F_np vs 观测 4.220：dev {(F_np-4.220)/4.220*100:+.5f}%")
print(f"F_np vs 4.2 = 3×(7/5)：dev {(F_np-4.2)/4.2*100:+.5f}%")
print(f"→ 7/5 骨架（4.2 = N_gen×(对合域/静默)）为近似锚（+0.44% 不达标）；观测 4.220 命中 −0.031%（0.01% 级达标）")
print("→ 判别：主线 B 的 7/5 是主结构近似锚，非精确身份；精确链走 F_np = 4.2187")

print("\n=== 5. 织 与 7/5 的组合观察 ===")
print(f"织/(7/5) = (9/10)/(7/5) = 9/14 = N_gen²/(幂基×对合域) = {9/14:.6f}")
print(f"织×(7/5) = 63/50 = {63/50:.6f}（63 = 对合域×N_gen²、50 = 静默²×幂基——g_p/g_n 分母 50 同款）")
print(f"织+7/5 = 9/10+7/5 = 23/10 = {23/10:.2f}（23 = 静默×不动点+N_gen——g_n/2 分母 23 同源）")

print("\n=== 6. 判别汇总 ===")
print("① 恒等 N_gen+k_max−1 = 幂基·静默 = 10（框架新恒等，可 Lean 化）")
print("② 织³ = (N_gen²/(幂基·静默))³ = 729/1000——104az-67 形式简化等价（纯素基 {2,3,5}）")
print("③ F_np = 4.2187 对观测 4.220 dev −0.031%（0.01% 级达标维持）")
print("④ 主线 B 的 7/5 = 4.2 为近似锚（+0.44%），核磁子链 μ_³H/|μ_³He| ≈ 7/5 为 0.0156% 组合候选——同一骨架不同精度")
print("⑤ 织+7/5 = 23/10（23 与 g_n/2 分母同源）、织/(7/5) = 9/14、织×(7/5) = 63/50——组合观察登记")
