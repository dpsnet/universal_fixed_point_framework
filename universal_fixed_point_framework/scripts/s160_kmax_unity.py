"""S160 k_max 三种组成的深层统一（S159 开放项——为何多表达）
k_max = 8 三种组成：3+5（韦达）、2×4（对称加倍）、1+7（时间+对合）
候选：全部是"不动点 4 的镜像配对"——差序列 {1,2,3}
"""
print("=== S160: k_max 三种组成的深层统一 ===\n")

print("=== 镜像配对验证（关于不动点 4） ===")
pairs = {"3+5（韦达和——差 1）": (3, 5), "2+6（幂基配对——差 2）": (2, 6), "1+7（时间+对合——差 3）": (1, 7)}
for name, (a, b) in pairs.items():
    center = (a + b) / 2
    diff = (b - a) / 2
    mark = "✓" if center == 4 else "✗"
    print(f"  {name}: ({a},{b})——中心 {center}{mark}——差 {diff}")

print("\n=== 差序列 {1,2,3} = {恒等,幂基,活跃代} ===")
print("  3+5 = (4−1)+(4+1)——差 1（恒等）")
print("  2+6 = (4−2)+(4+2)——差 2（幂基）——新表达！")
print("  1+7 = (4−3)+(4+3)——差 3（活跃代）——S159")
print("  8 = 2×4（幂基×不动点——对称加倍——S153）——同一族")

print("\n=== 重大发现：不动点 4 的代数生成框架量 ===")
print(f"  16 = 4² = 不动点²（全态）——也 = 2^4（幂基^不动点——S149）")
print(f"  15 = 4²−1 = (4−1)(4+1) = 3×5（冻结——完美平方差！）")
print(f"  8 = 2×4（幂基×不动点——谱宽）")
print(f"  4 = 2²（幂基² = 不动点——框架内平方恒等！）")
print(f"  → {{2,4,16}} = 2^1, 2^2, 2^4——幂基平方链")

print("\n=== 验证 ===")
print(f"  4² = {4**2} ✓   4²−1 = {4**2-1} ✓   (4−1)(4+1) = {(4-1)*(4+1)} ✓")
print(f"  2² = {2**2} ✓   (4−1)+(4+1) = {(4-1)+(4+1)} ✓")
print(f"  (4−2)+(4+2) = {(4-2)+(4+2)} ✓   (4−3)+(4+3) = {(4-3)+(4+3)} ✓")

print("\n=== 判别 ===")
print("  ✓ 三种组成统一：不动点 4 的镜像配对族（差 {1,2,3}）")
