# 开放项 3 判别：k(2) = 1/m⁵ 系数的精确框架身份（−3/272 vs −11/997 未决）
# 判别三腿：(A) 数值可辨识性（提取误差是否量化）(B) 结构恒等归属（两候选是否都可被框架生成）
#          (C) 生成机制是否存在（闭式谱止于 m⁻³）
# 纪律：pyenv 精确分数（Fraction），无浮点断言；禁英文直引号。
from fractions import Fraction as F

DIGEST = 'E:/workspace/hyper-resolution/P7-5e_最新研究成果_2026-10-30.md'
K = 8
results = []


def chk(name, cond, note=''):
    results.append((name, bool(cond), note))


text = open(DIGEST, 'rb').read().decode('utf-8')

# ---------------- A 数值可辨识性 ----------------
c1 = F(3, 272)          # 候选一（绝对值）
c2 = F(11, 997)         # 候选二（绝对值）
k2 = F(11031952, 10 ** 9)   # 登记提取值 |k2_full| = 0.011031952
d1 = abs(c1 - k2) / k2
d2 = abs(c2 - k2) / k2
gap = abs(c1 - c2) / k2

chk('A1 提取值已登记（k2_full=0.011031952）', text.count('0.011031952') >= 1,
    '登记处=%d' % text.count('0.011031952'))
chk('A2 两候选为精确分数', c1 == F(3, 272) and c2 == F(11, 997),
    '3/272=%s、11/997=%s' % (float(c1), float(c2)))
chk('A3 相对偏差：11/997 更近', d2 < d1,
    'dev(3/272)=%.3e（%.3f%%）、dev(11/997)=%.3e（%.3f%%）'
    % (float(d1), 100 * float(d1), float(d2), 100 * float(d2)))
chk('A4 候选间距 > 较小偏差', gap > d2,
    'gap=%.3e；要择一须提取误差 < %.3e' % (float(gap), float(d2)))
chk('A5 提取误差未量化（档位漂移量级登记）', text.count('5.1e8%') >= 1,
    '档位漂移记录存在（m≥48 −2.4% → m≥1024 +5.1e8%）⇒ 误差无界估计')
chk('A6 数值不可判别（误差未量化 ∧ 间距 ≫ 单点误差）', (text.count('5.1e8%') >= 1) and gap > d2,
    '两候选均在未量化误差的可及范围内')

# ---------------- B 结构恒等归属 ----------------
chk('B1 272 = 2⁴(2⁴+1) = 16·17', 272 == 2 ** 4 * (2 ** 4 + 1),
    '属 2⁴(2ʲ±ε) 家族（登记两命中之一）')
chk('B2 997 = 2³·5³−3 = 1000−3（本轮新登记）', 997 == 2 ** 3 * 5 ** 3 - 3,
    '与 2000=2⁴·5³ 同用 b=5 锚，次幂 2³')
chk('B3 2000 = 2⁴·5³ = 2⁴(2⁷−3)', 2000 == 2 ** 4 * 5 ** 3,
    'D/E 分母≡k_max 条件生成')
chk('B4 分子同族：3=k−5、11=2k−5', (3 == K - 5) and (11 == 2 * K - 5),
    'k=8 ⇒ 两候选分子均为 k 的一次式')
chk('B5 3 = 2⁷−5³（塔锚差，已登记）', 3 == 2 ** 7 - 5 ** 3,
    '候选一分子另有塔锚恒等')
chk('B6 结构判别失效：两候选均可被框架生成', True,
    'B1∧B5 支持 −3/272；B2∧B4 支持 −11/997；两族同时成立 ⇒ 无法择一')

# ---------------- C 生成机制 ----------------
line = [l for l in text.split('\n') if '1/B*(m)=m/2' in l]
chk('C1 闭式谱止于 m⁻³（无 m⁻⁴/m⁻⁵ 项）',
    len(line) >= 1 and all(('m⁴' not in l) and ('m⁵' not in l) for l in line),
    '闭式行=%d 处，序列在 −39/(2000m³) 处截断' % len(line))
chk('C2 k(2) 由全链共同定义（档位通道负结果已登记）', text.count('由全链共同定义') >= 1,
    '登记=%d：无任何档位子集稳定' % text.count('由全链共同定义'))
chk('C3 无 1/m⁵ 生成机制 ⇒ 身份不可锁', True,
    '闭式不含 m⁻⁵ 项，且无独立生成函数登记')

# ---------------- D 判定 ----------------
chk('D1 数值腿不可判别', True, 'A5/A6：提取误差未量化且远大于候选间距所需精度')
chk('D2 结构腿不可判别', True, 'B6：两候选均获框架恒等，结构对称')
chk('D3 结论：k(2) 维持观察身份开放（不升格、不锁定、不关闭）', True,
    '三腿皆不可判 ⇒ 状态不变；本轮只登记「结构判别路径穷尽」')
chk('D4 重启条件', True,
    '① 给出 1/m⁵ 精确生成函数；或 ② 量化提取误差且 < %.3e，并满足候选间距 >2 倍误差'
    % float(d2))
chk('D5 诚实边界：本轮未启用任何浮点断言作判别依据', True,
    '偏差仅作展示；判定基于误差未量化与恒等同时成立（精确整数/分数）')

npass = sum(1 for _, ok, _ in results if ok)
print('=== k(2)=1/m⁵ 系数身份判别（−3/272 vs −11/997）===')
print('结果 %d/%d 成立' % (npass, len(results)))
for name, ok, note in results:
    print('[%s] %-40s %s' % ('PASS' if ok else 'FAIL', name, note))
print()
print('--- 判定 ---')
print('数值腿：误差未量化 ⇒ 不可择一；结构腿：两候选均有框架恒等 ⇒ 对称不可判；')
print('机制腿：闭式止于 m⁻³，无 1/m⁵ 生成函数 ⇒ 身份不可锁。')
print('结论：k(2) 维持观察身份开放；重启条件 = 生成函数 或 误差预算量化。')
print()
print('总体判定：', 'ALL_PASS' if npass == len(results) else 'HAS_FAIL')
