#   用"幂基/活跃代的平方根"作为 √ 项——扫描其他框架角色

from math import sqrt, log, pi

sqrt23 = sqrt(2/3)
print(f"√(2/3) = {sqrt23:.9f}")
print(f"√(2/3)² = 2/3 = 幂基/活跃代（2 = Powers、3 = N_gen——框架常数）")

print("\n=== 框架角色扫描（先证伪——找其他精确连接） ===")
cands = {
    "1/4 = 1/FixedPoint": 1/4,
    "5/6": 5/6,
    "7/8 = (Involution)/8": 7/8,
    "8/10 = k_max/10": 8/10,
    "15/16 = σ⁻¹窗口比": 15/16,
    "ln2 = 0.693": log(2),
    "tanh(2ln2) = 15/17": 15/17,
    "σ·16/3 = (1/15)·(16/3)": (1/15)*(16/3),
    "√(15/16)": sqrt(15/16),
    "√(7/10)": sqrt(7/10),
    "√(2/5)": sqrt(2/5),
    "√(16/15)": sqrt(16/15),
}
for name, v in cands.items():
    d = sqrt23 - v
    print(f"√(2/3) − {name} = {d:+.7f}（相对 {abs(d)/sqrt23*100:.3f}%）")

print("\n=== α_v 组合身份 ===")
av = 16/15 + sqrt23*(1 + 6/(15**3))
av2 = 16/15 + sqrt23
print(f"α_v' = 16/15 + √(2/3)(1+6σ³) = {av:.9f}")
print(f"16/15 + √(2/3)（无 6σ³ 修正）= {av2:.9f}")
print(f"修正项 6σ³ = {6/(15**3):.3e}——√(2/3)·6σ³ = {sqrt23*6/(15**3):.3e}")
print(f"(1+6σ³) = {1+6/(15**3):.7f}——1127/1125 = {1127/1125:.7f}？——{1+6/(15**3)==1127/1125}")

print("\n=== √(2/3) 与 α_v 判别精度 ===")
print(f"α_v*（实验反解）= 1.884621（B''' 判别——0.0003% 支持）")
print(f"√(2/3) 项相对修正 ≈ 1.3e-3（B''' 登记——σ³×4.4 候选——4.4 非整开放）")
print(f"√(2/3)·15 = {sqrt23*15:.6f} vs 12？——差 {abs(sqrt23*15-12)/12*100:.2f}%")
