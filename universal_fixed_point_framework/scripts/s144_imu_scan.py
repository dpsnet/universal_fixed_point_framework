import numpy as np

I_μ = 2.8223920247
I_e = 8.1539907847

σ = 1/15
e = np.exp(1)
ln15 = np.log(15)
ln16 = np.log(16)
ln1615 = np.log(16/15)
sq2 = np.sqrt(2)
sq23 = np.sqrt(2/3)
α_vp = 16/15 + sq23*(1 + 6*σ**3)
α_v = 1 + σ + sq23
π = np.pi

print(f"I_μ        = {I_μ:.12f}")
print(f"I_e        = {I_e:.12f}")
print(f"ΔI         = {I_e-I_μ:.12f} (ln(m_μ/m_e) = 5.33159876)")

print("\n=== 基础量对照 ===")
base = {"e": e, "ln15": ln15, "ln16": ln16, "ln(16/15)": ln1615,
        "√2": sq2, "√(2/3)": sq23, "α_v'": α_vp, "α_v": α_v,
        "π": π, "2√2": 2*sq2, "3": 3.0, "σ⁻¹/5.31": 15/5.313}
for k, v in base.items():
    print(f"{k:12s} = {v:.12f}    I_μ-{k} = {I_μ-v:+.6f}   I_μ/{k} = {I_μ/v:.6f}")

print("\n=== 差值 δ 的框架分解（I_μ = X + δ） ===")
deltas = {
    "I_μ-e": I_μ-e, "I_μ-ln15": I_μ-ln15, "I_μ-ln16": I_μ-ln16,
    "I_μ-2√2": I_μ-2*sq2, "I_μ-α_v'": I_μ-α_vp, "I_μ-3": I_μ-3.0,
    "I_μ-π": I_μ-π, "I_μ-2.8": I_μ-2.8,
}
for k, δ in deltas.items():
    print(f"{k:10s} = {δ:+.8f}   δ/σ = {δ/σ:+.6f}   δ·15 = {δ*15:+.6f}   δ·150 = {δ*150:+.6f}")

print("\n=== I_μ 的乘法结构 ===")
print(f"I_μ/e        = {I_μ/e:.8f}   (1+{I_μ/e-1:.6f})")
print(f"I_μ/ln15     = {I_μ/ln15:.8f}   (1+{I_μ/ln15-1:.6f})")
print(f"I_μ·σ        = {I_μ*σ:.8f}")
print(f"I_μ/(2√2)    = {I_μ/(2*sq2):.8f}")
print(f"I_μ/α_v'     = {I_μ/α_vp:.8f}")
print(f"I_μ/(e+1)    = {I_μ/(e+1):.8f}")
print(f"e·(1+σ)      = {e*(1+σ):.8f}")
print(f"ln15·(1+σ²)  = {ln15*(1+σ**2):.8f}")
print(f"2·ln(15/2)   = {2*np.log(7.5):.8f}")

print("\n=== 阶结构（E 层——质量谱尺度） ===")
print(f"I_μ/ln(16/15) = {I_μ/ln1615:.6f}   (16/15 的 43.7 倍)")
print(f"16·ln(16/15)  = {16*ln1615:.8f}")
