"""chain_audit_182b_2adic.py — v2 收缩的 2 进幂剩余深度判别（补充）
ord(2) = (p−1)/2^m：m = 2 进幂剩余深度。
k=1: m=0（非二次剩余）；k=3: m=2（到四次）；k≥7: m=3（到八次）。
验证：2^((p−1)/16)（十六次判别）对 k≥7 应为 −1；k=3 的八次判别 2^14 ≡ −1。
"""
import io, sys
sys.stdout = io.TextIOWrapper(sys.stdout.buffer, encoding="utf-8")

Ks = [1, 3, 7, 9, 11, 13]
print("=== 2 进幂剩余深度 m（ord(2) = (p−1)/2^m）===")
print(f"{'k':>3} {'p':>10} {'v2(p−1)':>8} {'v2(ord2)':>8} {'m':>3} {'收缩=2^(m+1)':>12} {'2^((p−1)/8)':>12} {'2^((p−1)/16)':>13}")
for k in Ks:
    p = 49 + 4**k
    v2p = (p - 1 & -(p - 1)).bit_length() - 1
    ord2 = {1: 52, 3: 28, 7: 2054, 9: 32774, 11: 524294, 13: 645278}[k]
    v2o = 0
    t = ord2
    while t % 2 == 0:
        v2o += 1
        t //= 2
    m = v2p - v2o
    shrink = 2 ** (m + 1)
    e8 = (p - 1) // 8
    e16 = (p - 1) // 16
    r8 = pow(2, e8, p) if (p - 1) % 8 == 0 else -999
    r16 = pow(2, e16, p) if (p - 1) % 16 == 0 else -999
    s8 = "—" if r8 == -999 else str(r8)
    s16 = "—" if r16 == -999 else str(r16)
    print(f"{k:>3} {p:>10} {v2p:>8} {v2o:>8} {m:>3} {shrink:>12} {s8:>12} {s16:>13}")

print("\n=== 判别汇总 ===")
print("k=1: m=0, 收缩=2  = 幂基        —— p≡5 mod 8 → Legendre(2/p)=−1 解析闭合 ✓")
print("k=3: m=2, 收缩=8  = k_max       —— 二次+四次剩余、非八次（2^14≡−1）")
print("k≥7: m=3, 收缩=16 = 不动点²    —— 二次+四次+八次剩余、非十六次（2^奇≡−1）")
print("→ v2 收缩因子 {2,8,16} = {幂基, k_max, 不动点²} 全框架量；m 序列 {0,2,3} 深度分界（0 解析，2/3 观察级）")
