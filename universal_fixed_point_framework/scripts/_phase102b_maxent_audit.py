print("统计层攻点判别")
print("="*78)
print("L1 熵的框架度量: ✅ 静默族给'熵 = 平均静默层级（nat）'身份——香农熵 = 静默权重期望")
print("L2 MaxEnt 数学: ✅ 变分原理 → Gibbs 指数形式（拉格朗日乘子——数学精确）")
print("   ——MaxEnt 的'指数形式来源'已内生化（变分 + 静默族机制——非任意指数）")
