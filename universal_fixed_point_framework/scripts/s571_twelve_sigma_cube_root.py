"""
S571: O5 深层——12σ³ 的代数根源判别
12σ³ = 4/1125 的 '12' 来源：
  A 候选：12 = 2·3! = 幂基 × 活跃!（纯算术分解——无框架语义）
  B 候选：12 = 16−4 = 全态 16 − 不动点 4（Clifford 结构减法——
    S471 不动点 4 不可作用化——伴随骨架不可作用化——16 基中
    4 缺席——余 12 活跃基——σ³ 修正乘）
判别标准：框架内生性（生成链可溯源——用户硬约束）
  + 与 δ_hf 3/4 的关系（12/16 = 3/4——δ_hf = (3/4)(1−σ) 系数再现）
  + 与 ε_μ 6σ³ 的 N 来源分类（6=|S₃| 排列阶 → +；12=16−4 → −）
输出：两候选判别 + 恒等检验 + 生成链溯源表
"""
sigma = 1/15

def chk(name, lhs, rhs, tol=1e-12):
    ok = abs(lhs - rhs) <= tol
    print(f"  [{'PASS' if ok else 'FAIL'}] {name}: {lhs!r} vs {rhs!r}")
    return ok

print("=== S571: 12σ³ 代数根源判别 ===")
print(f"sigma = 1/15, 12σ³ = {12*sigma**3:.12f} = 4/1125 = {4/1125:.12f}")

print("\n--- 恒等检验 ---")
# 精确恒等
chk("12σ³ = (16−4)σ³", 12*sigma**3, (16-4)*sigma**3)
chk("12σ³ = 2·3!·σ³", 12*sigma**3, 2*6*sigma**3)
chk("12 = 16−4", 12, 16-4)
chk("12 = 2·3!", 12, 2*6)
chk("12/16 = 3/4（δ_hf 系数再现）", 12/16, 3/4)
# 与公共残差 (1−12σ³) 结构——S496 重组：30σ⁵(1−12σ³) = 30σ⁵ − 360σ⁸
chk("1−12σ³ = 1121/1125", 1-12*sigma**3, 1121/1125)
chk("30σ⁵(1−12σ³) = 30σ⁵ − 360σ⁸（S496 重组）",
    30*sigma**5*(1-12*sigma**3), 30*sigma**5 - 360*sigma**8)
# 与 6σ³ 的 2:1 关系
chk("12σ³ = 2·(6σ³)", 12*sigma**3, 2*6*sigma**3)

print("\n--- 语义判别：A 算术分解 vs B Clifford 结构减法 ---")
# B: 全态 16 基 − 不动点 4（S471 不可作用化）→ 12 活跃基
print("B 候选 12 = 16−4（Clifford 结构减法）")
print("  - 全态 16：框架常数（S271 两通道共享 Clifford 全态 16 基）")
print("  - 不动点 4：S161 范畴论证 + S471 双向禁（伴随骨架不可作用化）")
print("  - 16−4 = 12：不动点 4 在 16 基中不可作用化→余 12 活跃基")
print("  - 12/16 = 3/4：与 δ_hf = (3/4)(1−σ) 系数 3/4 再现（同源结构）")
print("  - 生成链：全态 16 → 不动点 4 禁（S471）→ 活跃基 12 → ×σ³ 修正")
print("A 候选 12 = 2·3! = 幂基×活跃!")
print("  - 仅算术恒等——无框架语义支撑——降级为平凡分解")

print("\n--- N 来源分类（与 9 例判别表衔接）---")
print("ε_μ:  N = 6 = |S₃| = 活跃!（排列群阶——全对称累积）→ + 修正")
print("公共残差: N = 12 = 16−4（全态−不动点——结构扣除）→ − 修正")
print("δ_hf: N = 1（单位平凡 1!）→ − 修正（S567 已闭合）")
print("结论：+ 修正的 N 来源 = 排列群阶；− 修正的 N 来源 = 结构扣除")
print("      12 = 16−4 是结构扣除类——12σ³ 与 6σ³ 的 N 来源分类不同")

print("\n--- 12σ³ 生成链溯源（O5 交付件）---")
print("链：Clifford 全态 16 基（S271）")
print("  → 不动点 4 不可作用化（S161+S471——伴随骨架禁）")
print("  → 余 12 活跃基（16−4）")
print("  → σ³ 修正乘（12σ³ = 4/1125——(1−12σ³) 公共残差因子）")
print("  → 公共残差 30σ⁵(1−12σ³)（S494/S496）")
print("可溯源：12 的每个因子（16/4）均为框架常数——无自由参数")

print("\n=== 判别结论 ===")
print("B 候选胜出：12 = 16−4（Clifford 结构减法——不动点 4 不可作用化）")
print("  内生于框架（全态 16/不动点 4 均为框架常数——S271/S161/S471）")
print("  且 12/16 = 3/4 与 δ_hf 系数 3/4 同源再现（交叉互证）")
print("A 候选（2·3!）降级：纯算术分解——无语义——平凡恒等")
