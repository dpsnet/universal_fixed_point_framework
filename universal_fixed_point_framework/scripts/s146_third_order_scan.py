"""S146 第三阶残余形态扫描（3.86e-13——S145 修正后残余——快速先证伪）
修正后组装链 E_e 残余 = +3.860e-13（σ_score 0.001σ——已在 m_e 测量
精度内达标）——本扫描判断：是否还有整洁第三阶形态（若无——关闭）
"""
import numpy as np

σ = 1/15
e = np.exp(1)
res = 3.860e-13  # S145 修正后残余（δ_obs − 27/80·e^-19）

print(f"第三阶残余 = {res:.4e}")
print(f"σ_score     = {res/2.94e-10:.4f}σ（m_e σ_rel = 2.94e-10——已达标）")

print("\n=== 形态空间（res = 系数 × 基底） ===")
bases = {
    "σ^8": σ**8, "σ^9": σ**9, "σ^10": σ**10, "σ^11": σ**11,
    "e^-27": np.exp(-27), "e^-28": np.exp(-28),
    "σ^8·e^-1": σ**8/e, "σ^8·e^-2": σ**8/e**2, "σ^9·e^-1": σ**9/e,
    "σ^9·e^-2": σ**9/e**2, "σ^10·e^-1": σ**10/e,
    "σ^8·σ^3": σ**8*σ**3, "2σ^8(1+σ)·e^-1": 2*σ**8*(1+σ)/e,
    "ε_μ·σ^8": 144*e**-16*(1+6*σ**3)*σ**8,
}
print(f"{'基底':16s} {'基底值':12s} {'res/基底':10s} {'接近有理?':12s}")
for k, v in bases.items():
    ratio = res/v
    note = ""
    for num in [2/9, 1/3, 1/4, 2/7, 3/16, 1/8, 2/3, 1/2, 5/27, 1/9, 1/6]:
        if abs(ratio-num)/num < 0.01:
            note = f"≈ {num:.5f}"
            break
    print(f"{k:16s} {v:12.4e} {ratio:10.4f} {note:12s}")

print("\n=== 判断 ===")
print("目标：是否有整洁第三阶形态（<1% 接近简单有理数）")
print("若无——第三阶残余在测量精度内（0.001σ）——形态无候选——关闭")
