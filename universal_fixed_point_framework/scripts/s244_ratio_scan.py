print("=== S244: 覆盖域比值族扩展扫描 ===\n")

def sigma_score_ratio(r, sig_r, cand):
    return abs(r - cand) / sig_r

print("=== 1. 新检验 ===")
# m_Δ = 1232.0 ± 0.3、m_ρ = 775.11 ± 0.23、m_μ = 105.6583755 ± 0.0000023
m_d = 1232.0; sd = 0.3
m_rho = 775.11; sr = 0.23
m_mu = 105.6583755; sm = 0.0000023

# m_Δ/m_ρ vs 27/17 = 活跃^3/F2
r1 = m_d / m_rho
s1 = r1 * ((sd/m_d)**2 + (sr/m_rho)**2)**0.5
c1 = 27.0/17.0
sc1 = sigma_score_ratio(r1, s1, c1)
print(f"m_Δ/m_ρ = {r1:.6f} vs 27/17 = {c1:.6f}（活跃^3/F2）——"
      f"σ = {sc1:.2f}σ——{'达标' if sc1 <= 1 else ('提示' if sc1 <= 3 else '证伪')}")

# m_ρ/m_μ vs 22/3 = 幂基×显态/活跃
r2 = m_rho / m_mu
s2 = r2 * ((sr/m_rho)**2 + (sm/m_mu)**2)**0.5
c2 = 22.0/3.0
sc2 = sigma_score_ratio(r2, s2, c2)
print(f"m_ρ/m_μ = {r2:.6f} vs 22/3 = {c2:.6f}（幂基×显态/活跃）——"
      f"σ = {sc2:.2f}σ——{'达标' if sc2 <= 1 else ('提示' if sc2 <= 3 else '证伪')}")

# m_ρ/m_τ vs 幂基/√21?——m_τ/m_ρ = √21/2 已达标——反向检验
r3 = m_rho / 1776.86
s3 = r3 * ((sr/m_rho)**2 + (0.12/1776.86)**2)**0.5
c3 = 2.0/(21**0.5)
sc3 = sigma_score_ratio(r3, s3, c3)
print(f"m_ρ/m_τ = {r3:.6f} vs 2/√21 = {c3:.6f}（反向——已达标链）——"
      f"σ = {sc3:.3f}σ——{'达标' if sc3 <= 1 else '提示'}")

print("\n=== 2. Δ 端比值模式观察 ===")
print(f"m_Δ/m_μ = 35/3——2.27σ 提示")
