# 3. 数值验证: 轨道测度的τ(q)
# ============================================================
def tau_bowen(q, c_list, p_list):
    p = np.array(p_list)
    c = np.array(c_list)
    def eq(tau):
        return np.sum(p**q * c**tau) - 1
    try:
        return brentq(eq, -20, 20)
    except:
        return np.nan

c_base = 0.5
print(f"\n  验证轨道测度的τ(q):")
print(f"  收缩因子 c = {c_base}")
print(f"\n  {'轨道大小':>10} | {'q':>6} | {'τ_num':>10} | {'τ_ana':>10} | {'误差%':>8}")
print("  " + "-" * 55)

for N_orbit in [1, 3]:
    c_list = [c_base] * N_orbit
    p_list = [1.0/N_orbit] * N_orbit
    D_O = np.log(N_orbit) / np.log(1/c_base) if N_orbit > 1 else 0
    for q in [-2, -1, 0, 1, 2]:
        tau_n = tau_bowen(q, c_list, p_list)
        tau_a = (q - 1) * D_O if N_orbit > 1 else 0
        err = abs(tau_n - tau_a) / abs(tau_n) * 100 if abs(tau_n) > 1e-10 else 0
        print(f"  {N_orbit:>10} | {q:>6.1f} | {tau_n:>10.6f} | {tau_a:>10.6f} | {err:>7.3f}%")

