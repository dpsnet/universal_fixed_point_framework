"""
β_s 的严格推导: 从转移算子层级递归到 α·f 乘积

核心思路:
  1. IFS转移算子 T 具有层级递归结构: T = Σ_i p_i · S_i^* K S_i
  2. 每一层迭代对应一个"有效算子" T_k，其特征值决定第k代的质量
  3. 层级递归关系: T_{k+1} = T(T_k) (算子迭代)
  4. 特征值递归: λ_{k+1} = Σ_i p_i · λ_k(c_i) (测度迭代)
  5. 通过分析特征值的递归增长/衰减率，推导出 β 与 α·f 的关系

关键定理:
  设 T 是IFS转移算子，其特征值满足:
    λ_{k+1} = Σ_i p_i · c_i^{τ(q)} · λ_k
    
  则特征值的指数衰减率 β 满足:
    β = N_EW · α(q) · f(α(q)) / d_frac
    
  其中 α(q) = dτ/dq, f(α) = qα - τ(q), d_frac = τ(0)

推导路径:
  路径1: 算子迭代 → 特征值递归 → 指数衰减率
  路径2: 测度的层级结构 → 多分形谱 → α·f 乘积
  路径3: 热力学形式 → 自由能密度 → β 的物理意义
"""

import numpy as np
from scipy.optimize import brentq
import matplotlib.pyplot as plt

# ============================================================
# 辅助函数: Bowen公式计算τ(q)及其导数
# ============================================================
def tau_bowen(q, c_list, p_list):
    p = np.array(p_list)
    c = np.array(c_list)
    def eq(tau):
        return np.sum(p**q * c**tau) - 1
    try:
        return brentq(eq, -20, 20)
    except:
        return np.nan

def tau_derivs(q, c_list, p_list, dq=1e-4):
    tau_0 = tau_bowen(q, c_list, p_list)
    tau_p = tau_bowen(q + dq, c_list, p_list)
    tau_m = tau_bowen(q - dq, c_list, p_list)
    tau_pp = tau_bowen(q + 2*dq, c_list, p_list)
    tau_mm = tau_bowen(q - 2*dq, c_list, p_list)
    alpha = (tau_p - tau_m) / (2*dq)
    tau_pp_val = (tau_p - 2*tau_0 + tau_m) / dq**2
    tau_ppp_val = (tau_pp - 2*tau_p + 2*tau_m - tau_mm) / (2*dq**3)
    f_val = q * alpha - tau_0
    return tau_0, alpha, tau_pp_val, tau_ppp_val, f_val

