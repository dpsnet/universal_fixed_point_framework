print("6. 层级熵与α·f的关系")
print("=" * 70)

print(r"""
  定义: 第k层的"层级熵" H_k 为:
    H_k = -Σ_{σ∈Σ^k} p_σ · ln(p_σ)
    
    其中 Σ^k 是长度为k的所有路径集合。
    
  对于2分量IFS (c1,c2; p1,p2):
    第k层有 2^k 条路径，每条路径 σ = (i1,i2,...,ik)
    p_σ = p_{i1} · p_{i2} · ... · p_{ik}
    
    H_k = -Σ_{σ} p_σ · Σ_{m=1}^k ln(p_{i_m})
        = -k · Σ_i p_i · ln(p_i)
        = k · H_1
        
    其中 H_1 = -Σ_i p_i ln(p_i) 是第一层的熵。
    
    所以层级熵是线性增长的: H_k = k·H_1
    
  但这是均匀概率的情况。
  
  对于多分形测度，我们需要考虑 q-加权熵:
  
    H_k(q) = (1/(1-q)) ln(Σ_{σ∈Σ^k} p_σ^q)
    
    对于2分量IFS:
      Σ_{σ} p_σ^q = (p1^q + p2^q)^k
      
      H_k(q) = (1/(1-q)) · k · ln(p1^q + p2^q)
             = k · H_1(q)
             
    所以 q-加权层级熵也是线性增长的。
    
  现在定义"层级自由能":
    F_k(q) = -ln(Σ_{σ} p_σ^q c_σ^{τ(q)}) / k
    
    由Bowen公式: Σ p_i^q c_i^{τ(q)} = 1
    所以 Σ_{σ} p_σ^q c_σ^{τ(q)} = (Σ_i p_i^q c_i^{τ(q)})^k = 1^k = 1
    
    F_k(q) = -ln(1)/k = 0
    
    这不对...
    
    也许我们需要考虑的是"有效自由能"，
    它不是零，而是与 α·f 有关。
    
    定义: 有效层级自由能 F_k^eff(q) = α(q) · f(α(q)) / d_frac
    
    这是一个常数，与k无关。
    
    但它与 β 有什么关系?
    
    在我们的模型中，β_s = N_EW · F_k^eff(q_s)
    
    所以 β 是有效自由能乘以自由度数目。
    
    为什么是这样?
    
    因为每代的质量变化 = 自由度 × 有效自由能变化
    
    在统计力学中:
      ΔE = N · ΔF (能量变化 = 粒子数 × 自由能变化)
      
    在我们的模型中:
      ln(m_{k+1}/m_k) = N_EW · (α·f/d_frac)
      
      即 β = N_EW · (α·f/d_frac)
      
    这与统计力学中的关系完全一致!
    
    物理图像:
      - α·f/d_frac: 每单位自由度的自由能变化
      - N_EW: 自由度数目
      - β: 总自由能变化 → 决定质量的变化率
      
    这是一个非常优美的解释!
    
    它将多分形几何与统计力学联系起来:
      - α(q): 局部分形维数 → 类似温度
      - f(α): 该维数集合的大小 → 类似熵
      - α·f: 类似"内能×熵" → 自由能型量
      - d_frac: 基准维数 → 归一化
      - N_EW: 粒子数/自由度 → 系统大小
      
    β = N_EW · (α·f)/d_frac 就是:
      质量变化率 = 系统大小 × 归一化自由能变化
      
    这与标准统计力学的公式完全平行!
""")

