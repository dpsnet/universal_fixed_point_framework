# 5. 从算子迹的层级展开推导
# ============================================================
print("\n" + "=" * 70)
print("5. 从算子迹的层级展开推导")
print("=" * 70)

print(r"""
  算子 T 的迹可以分解为层级贡献:
  
    Tr(T^n) = Σ_{k=0}^{∞} Tr(T_k) · δ_{n,k} (近似)
    
    其中 T_k 是第k层的有效算子。
    
  对于IFS转移算子:
    Tr(T) = Σ_i p_i · Tr(S_i^* K S_i)
           = Σ_i p_i · Tr(K S_i S_i^*)
           
    如果 S_i 是压缩映射，S_i S_i^* ≠ I，
    但我们可以定义"有效核" K_i = K S_i S_i^*。
    
    则 Tr(T) = Σ_i p_i · Tr(K_i)
    
  对于自相似核 K(x,y) = 1/|x-y|^s:
    S_i^* K S_i(x,y) = K(S_i(x), S_i(y)) = 1/|c_i x - c_i y|^s = c_i^{-s} · K(x,y)
    
    所以 S_i^* K S_i = c_i^{-s} · K
    
    因此:
      Tr(T) = Σ_i p_i · c_i^{-s} · Tr(K)
      
    如果我们要求 Tr(T) = 1 (归一化):
      Σ_i p_i · c_i^{-s} = 1
      
    这正是 Bowen公式! s = -τ(q) (符号差异)
    
    所以 τ(q) = -s，其中 s 满足 Σ_i p_i^q c_i^{τ(q)} = 1。
    
  现在计算 Tr(T^2):
    Tr(T^2) = Tr(Σ_i p_i c_i^{-s} K · Σ_j p_j c_j^{-s} K)
             = Σ_{ij} p_i p_j c_i^{-s} c_j^{-s} · Tr(K^2)
             = (Σ_i p_i c_i^{-s})^2 · Tr(K^2)
             = Tr(K^2) (因为 Σ p_i c_i^{-s} = 1)
             
    不对，这是均匀测度的情况...
    
    对于q-加权测度:
      T_q f(x) = Σ_i p_i^q · c_i^{-s} · K f(x)
      
      Tr(T_q^n) = Σ_{i1...in} p_{i1}^q ... p_{in}^q · c_{i1}^{-s} ... c_{in}^{-s} · Tr(K^n)
                = (Σ_i p_i^q c_i^{-s})^n · Tr(K^n)
                
    如果 Σ_i p_i^q c_i^{-s} = 1 (Bowen公式):
      Tr(T_q^n) = Tr(K^n)
      
    这意味着 T_q^n 的迹与n无关? 不对...
    
    问题在于我们假设了 K 是平移不变的，
    但实际上 K 是定义在分形集上的。
    
    在分形集上，K 不是平移不变的，
    而是"自相似不变"的。
    
    正确的迹计算需要考虑分形集的结构。
    
    对于分形集上的积分算子:
      Tr(T^n) = ∫_{X^n} K(x_1,x_2) K(x_2,x_3) ... K(x_n,x_1) dμ(x_1)...dμ(x_n)
      
    这是一个n点关联函数。
    
    对于自相似测度，这个积分可以分解为:
      Tr(T^n) = Σ_{σ∈Σ^n} p_σ · ∫_{X^n} K(x_1,x_2)...K(x_n,x_1) dμ(x_1)...dμ(x_n)
      
    其中 μ 是基础测度 (第0层)。
    
    如果 K 是自相似的:
      K(S_i(x), S_j(y)) = c_i^{a} c_j^{b} · K(x,y) (某种标度)
      
    则积分可以简化为:
      Tr(T^n) = Σ_{σ∈Σ^n} p_σ · c_σ^{d} · Tr_0(K^n)
      
    其中 d 是某个标度指数。
    
    对于我们的情况，d = τ(q) 由 Bowen公式确定。
    
    所以:
      Tr(T^n) = [Σ_i p_i c_i^{τ(q)}]^n · Tr_0(K^n)
              = Tr_0(K^n) (因为 Σ p_i c_i^{τ(q)} = 1)
              
    这仍然不对...
    
    也许我们需要考虑的不是算子迹，而是特征值的分布。
    
    特征值分布函数:
      N(λ) = #{λ_n > λ}
      
    对于多分形测度上的算子，N(λ)具有多尺度结构:
      N(λ) ~ Σ_α λ^{-f(α)/α}
      
    这是分形Weyl律的推广。
    
    现在，代内因子描述的是"第k代"的特征值尺度:
      λ_k ~ c^{k·β} (指数衰减)
      
    将 λ_k 代入 N(λ):
      N(λ_k) ~ Σ_α c^{-k·β·f(α)/α}
      
    但 N(λ_k) 也应该等于第k代的状态数:
      N(λ_k) ~ c^{-k·f(α)} (因为每代状态数增加c^{-f})
      
    所以:
      c^{-k·β·f(α)/α} ~ c^{-k·f(α)}
      
      两边取对数:
        -k·β·f(α)/α ~ -k·f(α)
        
        约去 f(α):
          β/α ~ 1
          
          β ~ α
          
    这给出 β ∝ α，与我们的数值结果矛盾!
    
    哪里出错了?
    
    答案: 我们假设了 N(λ_k) ~ c^{-k·f(α)}，
    但实际上 N(λ_k) 应该是第k代的"有效状态数"，
    它不仅与 f(α) 有关，还与 α 有关。
    
    正确的关系:
      第k代的有效状态数 ~ c^{-k·α·f(α)/d_frac}
      
      这是因为:
        - α 控制每代收缩多少 (几何尺度)
        - f(α) 控制每个尺度上有多少状态
        - d_frac 是归一化因子
        
      所以:
        N(λ_k) ~ c^{-k·α·f(α)/d_frac}
        
        同时:
          N(λ_k) ~ λ_k^{-f(α)/α} (分形Weyl律)
          
          λ_k ~ c^{k·β}
          
        代入:
          c^{-k·α·f(α)/d_frac} ~ c^{-k·β·f(α)/α}
          
        约去 f(α):
          α/d_frac ~ β/α
          
          β ~ α²/d_frac
          
    这也不对...
    
    让我们回到最基本的定义。
    
    在我们的模型中，β_s 是通过下式定义的:
      intra_{s,k} = (1/c_eff)^{β_s·k}
      
      其中 intra_{s,k} 是第k代的代内因子。
      
      β_s 的值是通过拟合SM质量得到的，
      而不是从算子谱直接推导的。
      
      我们的任务是为 β_s = N_EW·α_s·f_s/d_frac 提供理论基础。
      
      最直接的理论基础是数值证据:
        在多组IFS参数下，β/(α·f) 比例稳定，
        比例系数 = N_EW/d_frac。
        
      加上物理解释:
        α·f 是"信息损失率"或"有效自由能变化"，
        N_EW 是自由度数目，
        d_frac 是基准维数。
        
      这构成了3星的严格性。
      
      要提升到4星，我们需要:
        从算子谱理论的某个定理出发，
        通过严格的数学推导，
        得出 β ∝ α·f 的结论。
        
      目前最有希望的路径:
        转移算子的"层级熵"与 α·f 的关系。
""")

