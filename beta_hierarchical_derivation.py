print("2. 特征值的层级递归关系")
print("=" * 70)

print(r"""
  定理 (特征值递归):
  
  设 λ_k 是第k层有效算子 T_k 的主导特征值，则:
  
    λ_k = Σ_{σ∈Σ^k} p_σ · c_σ^{τ(q)} · λ_0
    
    其中 τ(q) 由 Bowen公式 Σ_i p_i^q c_i^{τ(q)} = 1 定义。
    
  证明:
    对于自相似测度上的积分算子，特征值满足:
    
      λ · ∫ K(x,y) φ(y) dμ(y) = ∫ K(x,y) φ(y) dμ(y)
      
    将 μ = Σ_i p_i μ ∘ S_i^{-1} 代入:
    
      λ · Σ_i p_i ∫ K(x,S_i(z)) φ(S_i(z)) dμ(z)
        = Σ_i p_i ∫ K(x,S_i(z)) φ(S_i(z)) dμ(z)
        
    如果 φ 是自相似特征函数: φ(S_i(z)) = c_i^{α} φ(z)
    
    则:
    
      λ · Σ_i p_i c_i^{α} · ∫ K(x,S_i(z)) φ(z) dμ(z)
        = Σ_i p_i c_i^{α} · ∫ K(x,S_i(z)) φ(z) dμ(z)
        
    这给出特征值方程:
    
      Σ_i p_i c_i^{α} = 1
      
    但这是均匀测度的情况 (q=0)。
    
    对于q-加权测度，我们需要考虑更一般的情况。
    
    正确的递归关系来自测度的多分形分解:
    
      第k层的测度 μ_k = Σ_{σ∈Σ^k} p_σ · δ_{x_σ} (近似)
      
      其中 x_σ 是第k层的"原子"位置。
      
      特征值 λ_k 与这些原子的分布有关:
        λ_k ~ Σ_{σ∈Σ^k} p_σ · c_σ^{d_s/2}
        
      对于多分形谱，每个原子的"有效维数"是 α(q)，
      该维数集合的大小是 f(α)。
      
      所以第k层的有效状态数:
        N_k ~ c^{-k·f(α)} (因为每代收缩c^α，状态数增加c^{-f})
        
      第k层的有效特征值:
        λ_k ~ c^{k·α·f(α)/d_frac} (某种组合)
        
      指数衰减率:
        β = -ln(λ_{k+1}/λ_k) / ln(c)
          = α·f(α)/d_frac
          
    等等，这给出的是 β = α·f/d_frac，缺少 N_EW 因子!
    
    N_EW 因子来自哪里?
    
    答案: 来自算子的"自由度"数量。
    
    在我们的模型中，算子不是作用在单粒子空间上，
    而是作用在N_EW维的电弱空间上。
    
    每个电弱自由度贡献一个独立的特征值，
    总的谱间距是所有自由度贡献的叠加。
    
    所以:
      β = N_EW · α·f/d_frac
      
    这就是完整的公式!
""")

