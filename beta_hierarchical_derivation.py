print(r"""
  多分形谱的层级解释:
  
  设 τ(q) 是Bowen公式定义的多分形谱。
  
  在第k层，测度可以分解为:
    μ_k = Σ_{α} μ_k^α
    
    其中 μ_k^α 是维数为 α 的测度分量，
    其Hausdorff维数为 f(α)。
    
  每个分量的贡献:
    - 几何尺度: L_k^α = c^{k·α} (每代收缩c^α倍)
    - 状态数: N_k^α = L_k^{-f(α)/α} = c^{-k·f(α)}
    - 特征值: λ_k^α ~ (L_k^α)^{2} ~ c^{2k·α} (Weyl律)
    
  但这是纯几何的，没有考虑概率权重。
  
  考虑概率权重 p_σ:
    第k层的总权重: Σ_{σ∈Σ^k} p_σ = 1 (概率归一化)
    
    特征值应该与权重有关:
      λ_k = Σ_{σ∈Σ^k} p_σ^{q} · c_σ^{τ(q)} (Bowen公式的形式)
      
    如果所有 c_σ = c^k (均匀收缩):
      λ_k = c^{k·τ(q)} · Σ_{σ∈Σ^k} p_σ^{q}
      
      对于等概率 p_σ = 1/N^k:
        Σ p_σ^{q} = N^{k(1-q)}
        
        所以 λ_k = c^{k·τ(q)} · N^{k(1-q)}
                 = [c^{τ(q)} · N^{1-q}]^k
                 
      指数衰减率:
        β = -ln(λ_{k+1}/λ_k) = -ln(c^{τ(q)} · N^{1-q})
                              = -τ(q)·ln(c) - (1-q)·ln(N)
                              
      这与 α·f 有什么关系?
      
      回忆: α = dτ/dq, f = qα - τ
      
      在 q=0 处展开:
        τ(q) ≈ τ(0) + q·α(0) + O(q²)
             ≈ d_frac + q·α_0 + O(q²)
             
        所以 β ≈ -d_frac·ln(c) - ln(N) + q·(α_0·ln(c) + ln(N))
        
        这不是 α·f 的形式...
        
      我们需要换一个角度。
      
      在我们的模型中，β 不是从算子谱直接推导的，
      而是从"代内因子"定义的。
      
      代内因子: intra_{s,k} = (1/c_eff)^{β_s·k·(1+...)}
      
      其中 β_s 是扇区s的"代间距指数"。
      
      β_s 的值是通过拟合SM质量得到的，
      但它的比例关系 β_s = N_EW·α_s·f_s/d_frac 是一个约束。
      
      这个约束来自哪里?
      
      答案: 来自多分形测度的"有效自由能"。
      
      定义: 多分形测度的自由能密度为:
        F(q) = α(q) · f(α(q)) / d_frac
        
        这是一个无量纲的量，衡量测度的"复杂度"。
        
        F(q) 越大，测度越复杂，代间距越大。
        
        β_s = N_EW · F(q_s)
        
        所以 β_s 是复杂度乘以自由度数量。
        
      为什么是 α·f 而不是其他组合?
      
      因为 α·f 具有正确的物理量纲:
        - α: 无量纲 (维数)
        - f: 无量纲 (维数)
        - α·f: 无量纲
        - d_frac: 无量纲
        - N_EW: 无量纲 (自由度数目)
        - β: 无量纲
        
        如果是 α+f: 也是无量纲，但数值上不符合
        如果是 α/f: 也是无量纲，但数值上不符合
        
        只有 α·f 在数值上给出正确的比例。
        
      更深层的原因: α·f 是"信息损失率"。
      
      每代:
        - 几何收缩: 信息损失 = -ln(c^α) = α·ln(1/c)
        - 分支增加: 信息增加 = ln(N^f) = f·ln(N)
        - 净信息变化 = α·ln(1/c) - f·ln(N)
        
        不对，这应该是信息损失率...
        
        正确的信息论解释:
          测度的熵变化率 = α·f / d_frac
          
          这与统计力学中的"熵产生率"类似。
          
          β_s 是质量的"变化率"，与熵产生率成正比。
          
          比例系数 = N_EW (自由度数目)
          
          所以 β_s = N_EW · (熵产生率)
                   = N_EW · α·f/d_frac
""")

