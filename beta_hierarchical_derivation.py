print("1. 转移算子的层级递归结构")
print("=" * 70)

print(r"""
  IFS转移算子的定义:
    T f(x) = ∫ K(x,y) f(y) dμ(y)
  
  自相似测度 μ = Σ_i p_i μ ∘ S_i^{-1}
  
  将测度代入算子:
    T f(x) = Σ_i p_i ∫ K(x,y) f(y) dμ(S_i^{-1}(y))
            = Σ_i p_i ∫ K(x, S_i(z)) f(S_i(z)) dμ(z)
  
  定义拉回算子 S_i^*: (S_i^* f)(z) = f(S_i(z))
  
  则 T 可以重写为:
    T = Σ_i p_i · S_i^* K S_i
    
  这是一个"加权拉回"结构，每一项对应一个IFS映射。
  
  关键观察: 算子 T 具有自相似性!
  
  T^2 = T(T) = Σ_i p_i · S_i^* K S_i · Σ_j p_j · S_j^* K S_j
       = Σ_{ij} p_i p_j · S_i^* K S_i S_j^* K S_j
       
  如果 S_i S_j^* 可以简化 (例如 S_i 是压缩映射):
    S_i S_j^* f(z) = f(S_j^{-1}(S_i(z))) = f(S_{i∘j}(z))
    
  其中 S_{i∘j} 是两个映射的复合。
  
  对于线性压缩映射 S_i(z) = c_i z:
    S_i S_j^* f(z) = f(z / c_j * c_i) = f(z · c_i/c_j)
    
  如果 c_i = c_j = c (均匀收缩):
    S_i S_j^* f(z) = f(z) → S_i S_j^* = I (恒等算子)
    
    所以 T^2 = Σ_{ij} p_i p_j · S_i^* K I K S_j
              = Σ_i p_i · S_i^* (Σ_j p_j · K^2) S_i
              
    这意味着 T^2 具有与 T 相同的自相似结构，
    只是核函数从 K 变成了 K^2。
    
  对于非均匀收缩 (c_i ≠ c_j):
    复合映射的收缩因子是 c_i/c_j，不是常数。
    
    但我们关心的是"层级"结构，不是任意复合。
    
    在第k层，我们只考虑"深度为k"的路径:
      第0层: 1个路径 (空路径)
      第1层: N个路径 (长度为1)
      第2层: N^2个路径 (长度为2)
      ...
      第k层: N^k个路径 (长度为k)
      
    每条路径 σ = (i1, i2, ..., ik) 对应一个复合映射:
      S_σ = S_{i1} ∘ S_{i2} ∘ ... ∘ S_{ik}
      收缩因子: c_σ = c_{i1} · c_{i2} · ... · c_{ik}
      概率权重: p_σ = p_{i1} · p_{i2} · ... · p_{ik}
      
    第k层的有效算子:
      T_k = Σ_{σ∈Σ^k} p_σ · S_σ^* K S_σ
      
    这是一个"粗粒化"的算子，描述第k层的动力学。
    
    关键问题: T_k 的特征值与 T_{k-1} 的特征值有什么关系?
    
    答案: 通过测度的层级分解。
""")

